using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Bank;
using Content.Shared.Cargo;
using Content.Shared.Cargo.BUI;
using System.Numerics;
using Content.Shared._WH40K.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Cargo.UI;

[GenerateTypedNameReferences]
public sealed partial class CargoPalletMenu : FancyWindow
{
    public Action? SellRequested;
    public Action? AppraiseRequested;
    private bool? _marketMode;

    public CargoPalletMenu()
    {
        RobustXamlLoader.Load(this);
        SellButton.OnPressed += OnSellPressed;
        AppraiseButton.OnPressed += OnAppraisePressed;
        MarketPanel.SellRequested += () => SellRequested?.Invoke();
    }

    public void SetAppraisal(int amount)
    {
        AppraisalLabel.Text = BankSystemExtensions.ToSpesoString(amount);
    }

    public void SetCount(int count)
    {
        CountLabel.Text = count.ToString();
    }

    public void SetTradeCrateMultiplier(double multiplier)
    {
        TradeCrateMultiplierLabel.Text = $"{multiplier:0.00}x";
    }

    public void SetOtherMultiplier(double multiplier)
    {
        OtherMultiplierLabel.Text = $"{multiplier:0.00}x";
    }

    public void SetEnabled(bool enabled)
    {
        AppraiseButton.Disabled = !enabled;
        SellButton.Disabled = !enabled;
    }

    public void SetMarketState(CargoPalletConsoleInterfaceState state)
    {
        var enabled = state.MarketEnabled;
        LegacyPanel.Visible = !enabled;
        MarketPanel.Visible = enabled;
        if (_marketMode != enabled)
        {
            _marketMode = enabled;
            MinSize = enabled ? new Vector2(640, 400) : new Vector2(340, 195);
            SetSize = enabled ? new Vector2(680, 420) : new Vector2(340, 240);
            Title = Loc.GetString(enabled ? "wh40k-market-window-title" : "cargo-pallet-console-menu-title");
        }
        if (enabled)
            MarketPanel.UpdateState(state);
    }

    public void ShowSaleResult(MaterialMarketSaleResultMessage result) => MarketPanel.ShowSaleResult(result);

    private void OnSellPressed(BaseButton.ButtonEventArgs obj)
    {
        SellRequested?.Invoke();
    }

    private void OnAppraisePressed(BaseButton.ButtonEventArgs obj)
    {
        AppraiseRequested?.Invoke();
    }
}
