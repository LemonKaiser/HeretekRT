using System.Linq;
using Content.Client._WH40K.CharacterCreation;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Markings;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Humanoid;

[GenerateTypedNameReferences]
public sealed partial class SingleMarkingPicker : BoxContainer
{
    [Dependency] private MarkingManager _markingManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;


    /// <summary>
    ///     What happens if a marking is selected.
    ///     It will send the 'slot' (marking index)
    ///     and the selected marking's ID.
    /// </summary>
    public Action<(int slot, string id)>? OnMarkingSelect;
    /// <summary>
    ///     What happens if a slot is removed.
    ///     This will send the 'slot' (marking index).
    /// </summary>
    public Action<int>? OnSlotRemove;

    /// <summary>
    ///     What happens when a slot is added.
    /// </summary>
    public Action? OnSlotAdd;

    /// <summary>
    ///     What happens if a marking's color is changed.
    ///     Sends a 'slot' number, and the marking in question.
    /// </summary>
    public Action<(int slot, Marking marking)>? OnColorChanged;
    public bool UseTiles { get; set; }

    private bool _editingDisabled;
    public bool EditingDisabled
    {
        get => _editingDisabled;
        set
        {
            _editingDisabled = value;
            Tiles.SetDisabled(value);
            foreach (var palette in PaletteContainer.Children.OfType<Wh40kColorPalette>())
                palette.SetDisabled(value);
        }
    }

    // current selected slot
    private int _slot = -1;
    private int Slot
    {
        get
        {
            if (_markings == null || _markings.Count == 0)
            {
                _slot = -1;
            }
            else if (_slot == -1)
            {
                _slot = 0;
            }

            return _slot;
        }
        set
        {
            if (_markings == null || _markings.Count == 0)
            {
                _slot = -1;
                return;
            }

            _slot = value;
            if (UseTiles)
                PopulateList(Search.Text);
            _ignoreItemSelected = true;

            foreach (var item in MarkingList)
            {
                item.Selected = (string) item.Metadata! == _markings[_slot].MarkingId;
            }

            _ignoreItemSelected = false;
            PopulateColors();
        }
    }

    // amount of slots to show
    private int _totalPoints;

    private bool _ignoreItemSelected;

    private MarkingCategories _category;
    public MarkingCategories Category
    {
        get => _category;
        set
        {
            _category = value;
            CategoryName.Text = Loc.GetString($"markings-category-{_category}");

            if (!string.IsNullOrEmpty(_species))
            {
                PopulateList(Search.Text);
            }
        }
    }
    private IReadOnlyDictionary<string, MarkingPrototype>? _markingPrototypeCache;

    private string? _species;
    private List<Marking>? _markings;

    private int PointsLeft
    {
        get
        {
            if (_markings == null)
            {
                return 0;
            }

            if (_totalPoints < 0)
            {
                return -1;
            }

            return _totalPoints - _markings.Count;
        }
    }

    private int PointsUsed => _markings?.Count ?? 0;

    public SingleMarkingPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        MarkingList.OnItemSelected += SelectMarking;
        AddButton.OnPressed += _ =>
        {
            OnSlotAdd!();
        };

        SlotSelector.OnItemSelected += args =>
        {
            Slot = args.Button.SelectedId;
        };

        RemoveButton.OnPressed += _ =>
        {
            OnSlotRemove!(_slot);
        };

        Search.OnTextChanged += args =>
        {
            PopulateList(args.Text);
        };
    }

    public void UpdateData(List<Marking> markings, string species, int totalPoints, Sex? sex = null)
    {
        if (UseTiles)
        {
            VerticalExpand = false;
            MarkingSelectorContainer.VerticalExpand = false;
            SeparationOverride = 6;
            MarkingSelectorContainer.SeparationOverride = 10;
        }
        _markings = markings;
        _species = species;
        _totalPoints = totalPoints;
        if (_slot >= markings.Count)
            _slot = -1;

        _markingPrototypeCache = sex is { } selectedSex
            ? _markingManager.MarkingsByCategoryAndSpeciesAndSex(Category, species, selectedSex)
            : _markingManager.MarkingsByCategoryAndSpecies(Category, species);

        Visible = _markingPrototypeCache.Count != 0;
        if (_markingPrototypeCache.Count == 0)
        {
            return;
        }

        PopulateList(Search.Text);
        PopulateColors();
        PopulateSlotSelector();
    }

    public void SetPreviewDirection(Direction direction) => Tiles.SetDirection(direction);

    public void SetCompactTiles(bool compact)
    {
        var height = compact ? 168 : 254;
        TileScroll.MinHeight = height;
        TileScroll.MaxHeight = height;
    }

    public void PopulateList(string filter)
    {
        if (string.IsNullOrEmpty(_species))
        {
            throw new ArgumentException("Tried to populate marking list without a set species!");
        }

        _markingPrototypeCache ??= _markingManager.MarkingsByCategoryAndSpecies(Category, _species);

        MarkingSelectorContainer.Visible = UseTiles || _markings is { Count: > 0 };
        LegacyListScroll.Visible = !UseTiles;
        LegacyColorScroll.Visible = !UseTiles;
        TileScroll.Visible = UseTiles;
        if (_markings == null || !UseTiles && _markings.Count == 0)
        {
            return;
        }

        MarkingList.Clear();

        var sortedMarkings = _markingPrototypeCache.Select(pair => (pair.Key, pair.Value, Name: GetMarkingName(pair.Value)))
            .Where(m => m.Key.Contains(filter, StringComparison.OrdinalIgnoreCase) || m.Name.Contains(filter, StringComparison.CurrentCultureIgnoreCase))
            .OrderBy(m => m.Name, StringComparer.CurrentCulture);
        var sprites = _entityManager.System<SpriteSystem>();

        if (UseTiles)
        {
            Tiles.ClearTiles();
            var current = Slot >= 0 ? _markings[Slot] : null;
            Tiles.AddTile(Loc.GetString("wh40k-personalization-no-style"), null, current == null, () =>
            {
                if (Slot >= 0)
                    OnSlotRemove?.Invoke(Slot);
            });
            var tint = current?.MarkingColors.Count > 0 ? current.MarkingColors[0] : Color.White;
            foreach (var (id, marking, name) in sortedMarkings)
                Tiles.AddMarkingTile(name, marking.Sprites, current?.MarkingId == id,
                    () => SelectMarking(id), tint, closeUp: true);
            Tiles.SetDisabled(EditingDisabled);
            return;
        }

        foreach (var (id, marking, name) in sortedMarkings)
        {
            var item = MarkingList.AddItem(name, sprites.Frame0(marking.Sprites[0]));
            item.Metadata = marking.ID;

            if (_markings[Slot].MarkingId == id)
            {
                _ignoreItemSelected = true;
                item.Selected = true;
                _ignoreItemSelected = false;
            }
        }
    }

    private void PopulateColors()
    {
        (UseTiles ? PaletteContainer : ColorSelectorContainer).DisposeAllChildren();
        PaletteContainer.Visible = false;
        if (_markings == null
            || _markings.Count == 0
            || !_markingManager.TryGetMarking(_markings[Slot], out var proto))
        {
            return;
        }

        var marking = _markings[Slot];

        if (UseTiles)
        {
            // Each hairstyle in a character profile has one color shared by all its sprite layers.
            var palette = new Wh40kColorPalette(marking.MarkingColors[0]);
            palette.OnColorChanged += color =>
            {
                marking.SetColor(0, color);
                Tiles.SetMarkingTint(color);
                OnColorChanged?.Invoke((Slot, marking));
            };
            palette.SetDisabled(EditingDisabled);
            PaletteContainer.AddChild(palette);
            PaletteContainer.Visible = true;
            return;
        }

        if (marking.MarkingColors.Count != proto.Sprites.Count)
        {
            marking = new Marking(marking.MarkingId, proto.Sprites.Count);
        }

        for (var i = 0; i < marking.MarkingColors.Count; i++)
        {
            var colorIndex = i;
            void ApplyColor(Color color)
            {
                marking.SetColor(colorIndex, color);
                OnColorChanged?.Invoke((_slot, marking));
            }

            var selector = new ColorSelectorSliders
            {
                HorizontalExpand = true
            };
            selector.Color = marking.MarkingColors[i];
            selector.SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv; // defaults color selector to HSV

            selector.OnColorChanged += ApplyColor;

            ColorSelectorContainer.AddChild(selector);
        }
    }

    private void SelectMarking(ItemList.ItemListSelectedEventArgs args)
    {
        if (_ignoreItemSelected)
        {
            return;
        }

        SelectMarking((string) MarkingList[args.ItemIndex].Metadata!);
    }

    internal void SelectMarking(string id)
    {
        if (EditingDisabled)
            return;

        if (!_markingManager.Markings.TryGetValue(id, out var proto))
        {
            throw new ArgumentException("Attempted to select non-existent marking.");
        }

        if (UseTiles && Slot < 0)
        {
            OnMarkingSelect?.Invoke((0, id));
            return;
        }

        var oldMarking = _markings![Slot];
        _markings[Slot] = proto.AsMarking();

        for (var i = 0; i < _markings[Slot].MarkingColors.Count && i < oldMarking.MarkingColors.Count; i++)
        {
            _markings[Slot].SetColor(i, oldMarking.MarkingColors[i]);
        }

        PopulateColors();

        OnMarkingSelect?.Invoke((_slot, id));
    }

    // Slot logic

    private void PopulateSlotSelector()
    {
        var singleTileSlot = UseTiles && _totalPoints == 1;
        SlotSelectorContainer.Visible = !singleTileSlot;
        SlotSelector.Visible = Slot >= 0 && !singleTileSlot;
        AddButton.Visible = !singleTileSlot;
        RemoveButton.Visible = !singleTileSlot;
        Search.Visible = UseTiles || Slot >= 0;
        AddButton.HorizontalExpand = Slot < 0;
        RemoveButton.HorizontalExpand = Slot < 0;
        AddButton.Disabled = PointsLeft == 0 && _totalPoints > -1 ;
        RemoveButton.Disabled = PointsUsed == 0;
        SlotSelector.Clear();

        if (Slot < 0)
        {
            return;
        }

        for (var i = 0; i < PointsUsed; i++)
        {
            SlotSelector.AddItem(Loc.GetString("marking-slot", ("number", $"{i + 1}")), i);

            if (i == _slot)
            {
                SlotSelector.SelectId(i);
            }
        }
    }

    private string GetMarkingName(MarkingPrototype marking)
    {
        return Loc.GetString($"marking-{marking.ID}");
    }
}
