    private void RequestOnboardingPortraitPreview(Wh40kPortraitPrototype? portrait)
    {
        if (portrait is null)
        {
            if (_onboardingPortraitPreviewPhase == OnboardingPortraitPreviewPhase.Hidden)
                return;

            _pendingOnboardingPortraitPreview = null;
            _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.HidePending;
            _onboardingPortraitPreviewElapsed = 0f;
            return;
        }

        if (_onboardingDraft is null ||
            !OnboardingAppearancePage.IsPortraitSectionVisible)
        {
            return;
        }

        if (IsReducedMotion)
        {
            SetOnboardingPortraitPreview(portrait);
            _pendingOnboardingPortraitPreview = null;
            _onboardingPortraitPreviewOpacity = 1f;
            _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.Visible;
            ApplyOnboardingPortraitPreviewVisuals();
            return;
        }

        if (_onboardingPortraitPreviewPhase is OnboardingPortraitPreviewPhase.Hidden
            or OnboardingPortraitPreviewPhase.FadingOut)
        {
            SetOnboardingPortraitPreview(portrait);
            _pendingOnboardingPortraitPreview = null;
            _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.FadingIn;
            _onboardingPortraitPreviewElapsed = 0f;
            OnboardingPortraitPreview.Visible = true;
            ApplyOnboardingPortraitPreviewVisuals();
            return;
        }

        if (_onboardingPortraitPreview?.ID == portrait.ID)
        {
            _pendingOnboardingPortraitPreview = null;
            _onboardingPortraitPreviewPhase = _onboardingPortraitPreviewOpacity >= 0.999f
                ? OnboardingPortraitPreviewPhase.Visible
                : OnboardingPortraitPreviewPhase.FadingIn;
            _onboardingPortraitPreviewElapsed = 0f;
            ApplyOnboardingPortraitPreviewVisuals();
            return;
        }

        _pendingOnboardingPortraitPreview = portrait;
        _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.SwitchingOut;
        _onboardingPortraitPreviewElapsed = 0f;
        ApplyOnboardingPortraitPreviewVisuals();
    }

    private void UpdateOnboardingPortraitPreview(float deltaSeconds, bool reducedMotion)
    {
        if (_onboardingPortraitPreviewPhase == OnboardingPortraitPreviewPhase.Hidden)
            return;

        if (reducedMotion)
        {
            if (_onboardingPortraitPreviewPhase == OnboardingPortraitPreviewPhase.HidePending)
            {
                _onboardingPortraitPreviewElapsed += deltaSeconds;
                if (_onboardingPortraitPreviewElapsed < OnboardingPortraitPreviewHideDelay)
                    return;

                HideOnboardingPortraitPreviewImmediately();
                return;
            }

            if (_pendingOnboardingPortraitPreview is { } pendingPortrait)
                SetOnboardingPortraitPreview(pendingPortrait);

            _pendingOnboardingPortraitPreview = null;
            _onboardingPortraitPreviewOpacity = 1f;
            _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.Visible;
            ApplyOnboardingPortraitPreviewVisuals();
            return;
        }

        switch (_onboardingPortraitPreviewPhase)
        {
            case OnboardingPortraitPreviewPhase.FadingIn:
                _onboardingPortraitPreviewOpacity = Math.Min(
                    1f,
                    _onboardingPortraitPreviewOpacity +
                    deltaSeconds / OnboardingPortraitPreviewFadeDuration);
                if (_onboardingPortraitPreviewOpacity >= 1f)
                    _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.Visible;
                break;
            case OnboardingPortraitPreviewPhase.Visible:
                _onboardingPortraitPreviewOpacity = 1f;
                break;
            case OnboardingPortraitPreviewPhase.SwitchingOut:
                _onboardingPortraitPreviewOpacity = Math.Max(
                    0f,
                    _onboardingPortraitPreviewOpacity -
                    deltaSeconds / OnboardingPortraitPreviewSwitchDuration);
                if (_onboardingPortraitPreviewOpacity <= 0f)
                {
                    SetOnboardingPortraitPreview(_pendingOnboardingPortraitPreview);
                    _pendingOnboardingPortraitPreview = null;
                    _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.SwitchingIn;
                }
                break;
            case OnboardingPortraitPreviewPhase.SwitchingIn:
                _onboardingPortraitPreviewOpacity = Math.Min(
                    1f,
                    _onboardingPortraitPreviewOpacity +
                    deltaSeconds / OnboardingPortraitPreviewFadeDuration);
                if (_onboardingPortraitPreviewOpacity >= 1f)
                    _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.Visible;
                break;
            case OnboardingPortraitPreviewPhase.HidePending:
                _onboardingPortraitPreviewElapsed += deltaSeconds;
                _onboardingPortraitPreviewOpacity = Math.Min(
                    1f,
                    _onboardingPortraitPreviewOpacity +
                    deltaSeconds / OnboardingPortraitPreviewFadeDuration);
                if (_onboardingPortraitPreviewElapsed >= OnboardingPortraitPreviewHideDelay)
                    _onboardingPortraitPreviewPhase = OnboardingPortraitPreviewPhase.FadingOut;
                break;
            case OnboardingPortraitPreviewPhase.FadingOut:
                _onboardingPortraitPreviewOpacity = Math.Max(
                    0f,
                    _onboardingPortraitPreviewOpacity -
                    deltaSeconds / OnboardingPortraitPreviewFadeDuration);
                if (_onboardingPortraitPreviewOpacity <= 0f)
                {
                    HideOnboardingPortraitPreviewImmediately();
                    return;
                }
                break;
        }

        ApplyOnboardingPortraitPreviewVisuals();
    }

