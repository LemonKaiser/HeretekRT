    private void UpdateOnboardingPageTransition(float deltaSeconds)
    {
        if (_onboardingPageTransitionPhase == OnboardingPageTransitionPhase.None)
            return;

        if (!OnboardingState.Visible)
        {
            ResetOnboardingPageTransition();
            return;
        }

        if (IsReducedMotion)
        {
            var pendingTab = _pendingOnboardingTab;
            ResetOnboardingPageTransition();
            if (pendingTab >= 0)
                ApplyOnboardingTab(pendingTab);
            return;
        }

        _onboardingPageTransitionElapsed += deltaSeconds;
        switch (_onboardingPageTransitionPhase)
        {
            case OnboardingPageTransitionPhase.FadingOut:
            {
                var progress = Math.Clamp(_onboardingPageTransitionElapsed / OnboardingPageFadeOutDuration, 0f, 1f);
                SetOnboardingPageOpacity(1f - progress);
                if (progress < 1f)
                    return;

                var pendingTab = _pendingOnboardingTab;
                if (pendingTab < 0 || pendingTab >= _onboardingTabs.Count)
                {
                    ResetOnboardingPageTransition();
                    return;
                }

                ApplyOnboardingTab(pendingTab);
                _pendingOnboardingTab = -1;
                _onboardingPageTransitionPhase = OnboardingPageTransitionPhase.FadingIn;
                _onboardingPageTransitionElapsed = 0f;
                SetOnboardingPageOpacity(0f);
                return;
            }
            case OnboardingPageTransitionPhase.FadingIn:
            {
                var progress = Math.Clamp(_onboardingPageTransitionElapsed / OnboardingPageFadeInDuration, 0f, 1f);
                SetOnboardingPageOpacity(progress);
                if (progress >= 1f)
                    ResetOnboardingPageTransition();
                return;
            }
            default:
                ResetOnboardingPageTransition();
                return;
        }
    }

    private void ResetOnboardingPageTransition()
    {
        _onboardingPageTransitionPhase = OnboardingPageTransitionPhase.None;
        _onboardingPageTransitionElapsed = 0f;
        _pendingOnboardingTab = -1;
        SetOnboardingPageOpacity(1f);
    }

    private void SetOnboardingPageOpacity(float opacity)
    {
        var modulate = Color.White.WithAlpha(Math.Clamp(opacity, 0f, 1f));
        OnboardingNavigationPanel.Modulate = modulate;
        OnboardingContentPanel.Modulate = modulate;
    }

    private void UpdateOnboardingTransition(float deltaSeconds)
    {
        switch (_onboardingTransitionPhase)
        {
            case OnboardingTransitionPhase.None:
                return;
            case OnboardingTransitionPhase.FadingIn:
                _onboardingTransitionElapsed += deltaSeconds;
                OnboardingFade.Modulate = Color.White.WithAlpha(Math.Clamp(
                    _onboardingTransitionElapsed / OnboardingFadeInDuration,
                    0f,
                    1f));

                if (_onboardingTransitionElapsed < OnboardingFadeInDuration)
                    return;

                SwitchState(LobbyGuiState.Onboarding);
                _onboardingTransitionPhase = OnboardingTransitionPhase.FadingOut;
                _onboardingTransitionElapsed = 0f;
                return;
            case OnboardingTransitionPhase.FadingOut:
                _onboardingTransitionElapsed += deltaSeconds;
                OnboardingFade.Modulate = Color.White.WithAlpha(1f - Math.Clamp(
                    _onboardingTransitionElapsed / OnboardingFadeOutDuration,
                    0f,
                    1f));

                if (_onboardingTransitionElapsed < OnboardingFadeOutDuration)
                    return;

                OnboardingFade.Visible = false;
                OnboardingFade.Modulate = Color.White;
                _onboardingTransitionPhase = OnboardingTransitionPhase.None;
                return;
        }
    }

