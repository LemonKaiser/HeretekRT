    /// <summary>
    /// Starts the lobby presentation once for the lifetime of the client process.
    /// Returning to the lobby uses the normal immediately-visible layout.
    /// </summary>
    public void BeginPresentation()
    {
        _introElapsed = 0f;
        _ambientElapsed = 0f;
        _introActive = !_introPlayedThisProcess && !IsReducedMotion;
        _introPlayedThisProcess = true;

        if (_introActive)
        {
            ApplyIntroOpacity(left: 0f, utility: 0f, chat: 0f);
            return;
        }

        ApplyIntroOpacity(left: 1f, utility: 1f, chat: 1f);
        ApplyStaticVisuals();
    }

    public void UpdateVisualEffects(float deltaSeconds)
    {
        UpdateResponsiveLayout();
        UpdateInteractiveVisuals(deltaSeconds, IsReducedMotion);
        UpdateOnboardingTransition(deltaSeconds);
        UpdateOnboardingPageTransition(deltaSeconds);
        UpdateOnboardingPortraitPreview(deltaSeconds, IsReducedMotion);

        if (IsReducedMotion)
        {
            _introActive = false;
            if (!_staticVisualsApplied)
            {
                ApplyIntroOpacity(left: 1f, utility: 1f, chat: 1f);
                ApplyStaticVisuals();
                _staticVisualsApplied = true;
            }
            return;
        }

        _staticVisualsApplied = false;

        _ambientElapsed += deltaSeconds;

        if (_introActive)
        {
            _introElapsed += deltaSeconds;
            ApplyIntroOpacity(
                left: EaseTimeline(_introElapsed, 0.05f, 0.52f),
                utility: EaseTimeline(_introElapsed, 0.42f, 0.42f),
                chat: EaseTimeline(_introElapsed, 0.58f, 0.47f));

            if (_introElapsed >= IntroDuration)
            {
                _introActive = false;
                ApplyIntroOpacity(left: 1f, utility: 1f, chat: 1f);
            }
        }

        var logoPulse = 0.5f + 0.5f * MathF.Sin(_ambientElapsed * MathF.Tau / LogoGlowCycleDuration);
        LogoDisplay.Pulse = logoPulse;
        DeckDecoration.AnimationTime = _ambientElapsed;
        var signalPhase = _ambientElapsed / 2.4f;
        signalPhase -= MathF.Floor(signalPhase);
        RoundIndicator.Pulse = signalPhase;
        _drawerDecoration.Pulse = logoPulse;
        if (_roundStarted)
            return;

        var readyPulse = 0.5f + 0.5f * MathF.Sin(_ambientElapsed * MathF.Tau / ReadyPulseCycleDuration);
        if (MathF.Abs(readyPulse - _lastReadyPulse) >= 0.015f)
            ApplyReadyButtonVisual(_ready, roundStarted: false, readyPulse);
    }

    /// <summary>
    /// Hides the lobby behind a short fade before exposing the onboarding shell.
    /// No profile data is altered by this transition.
    /// </summary>
    public void BeginOnboardingTransition(Wh40kOnboardingDraft draft)
    {
        if (OnboardingState.Visible || _onboardingTransitionPhase != OnboardingTransitionPhase.None)
            return;

        ResetOnboardingPageTransition();
        _onboardingDraft = draft;
        OnboardingAppearancePage.SetDraft(draft);
        OnboardingHomeworldPage.SetDraft(draft);
        OnboardingOriginPage.SetDraft(draft);
        OnboardingTraitsPage.SetDraft(draft);
        OnboardingClassesPage.SetDraft(draft);
        OnboardingCharacteristicsPage.SetDraft(draft);
        OnboardingResultPage.SetDraft(draft);
        RebuildOnboardingHomeworldNavigation();
        RebuildOnboardingOriginNavigation();
        RebuildOnboardingTraitsNavigation();
        RebuildOnboardingClassesNavigation();
        RebuildOnboardingCharacteristicsNavigation();
        RefreshOnboardingPreview(draft);
        SetOnboardingCompletionPending(false);
        // A new draft always starts at the first appearance section. Reapply it
        // after all page data has been populated so the selected navigation card
        // cannot retain a stale visual state from an earlier onboarding session.
        ApplyOnboardingTab(0);

        // Lobby's visual update can be suspended while the initial server state is
        // catching up. Do not leave a full-screen input-blocking fade dependent on
        // those frames: the HTML reference opens the workspace directly.
        OnboardingFade.Visible = false;
        OnboardingFade.Modulate = Color.White;
        SwitchState(LobbyGuiState.Onboarding);
    }

    public void ReturnToLobbyFromOnboarding()
