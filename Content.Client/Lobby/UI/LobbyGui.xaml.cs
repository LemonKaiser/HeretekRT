    private void RequestOnboardingTab(int index)
    {
        if (index < 0 || index >= _onboardingTabs.Count)
            return;

        if (!OnboardingState.Visible || IsReducedMotion)
        {
            ApplyOnboardingTab(index);
            return;
        }

        if (_onboardingPageTransitionPhase != OnboardingPageTransitionPhase.None || index == _selectedOnboardingTab)
            return;

        _pendingOnboardingTab = index;
        _onboardingPageTransitionElapsed = 0f;
        _onboardingPageTransitionPhase = OnboardingPageTransitionPhase.FadingOut;
    }

    private void ApplyOnboardingTab(int index)
    {
        if (index < 0 || index >= _onboardingTabs.Count)
            return;

        _selectedOnboardingTab = index;
        var tab = _onboardingTabs[index];
        OnboardingPageProgress.Text = Loc.GetString(
            "heretek-onboarding-page-progress",
            ("current", index + 1));
        OnboardingMetaPhase.Text = Loc.GetString(
            "heretek-onboarding-meta-phase",
            ("current", (index + 1).ToString("D2")),
            ("title", Loc.GetString(tab.TitleLocId)));

        var appearanceSelected = index == 0;
        var homeworldSelected = index == 1;
        var originSelected = index == 2;
        var traitsSelected = index == 3;
        var classesSelected = index == 4;
        var characteristicsSelected = index == 5;
        var resultSelected = index == 6;
        OnboardingNavigationPlaceholder.Visible = !appearanceSelected && !homeworldSelected && !originSelected && !traitsSelected && !classesSelected && !characteristicsSelected && !resultSelected;
        OnboardingAppearanceNavigation.Visible = appearanceSelected;
        OnboardingHomeworldNavigation.Visible = homeworldSelected;
        OnboardingOriginNavigation.Visible = originSelected;
        OnboardingTraitsNavigation.Visible = traitsSelected;
        OnboardingClassesNavigation.Visible = classesSelected;
        OnboardingCharacteristicsNavigation.Visible = characteristicsSelected;
        OnboardingNavigationPanel.Visible = !resultSelected;
        OnboardingContentPanel.SetWidth = resultSelected ? 1078 : 760;
        OnboardingPlaceholderPage.Visible = !appearanceSelected && !homeworldSelected && !originSelected && !traitsSelected && !classesSelected && !characteristicsSelected && !resultSelected;
        OnboardingAppearancePage.Visible = appearanceSelected;
        OnboardingHomeworldPage.Visible = homeworldSelected;
        OnboardingOriginPage.Visible = originSelected;
        OnboardingTraitsPage.Visible = traitsSelected;
        OnboardingClassesPage.Visible = classesSelected;
        OnboardingCharacteristicsPage.Visible = characteristicsSelected;
        OnboardingResultPage.Visible = resultSelected;
        OnboardingCompleteButton.Visible = resultSelected;
        if (!appearanceSelected)
            HideOnboardingPortraitPreviewImmediately();
        RefreshOnboardingResultPortrait();

        if (appearanceSelected)
            SelectOnboardingAppearanceSection(_selectedOnboardingAppearanceSection);
        else if (traitsSelected)
        {
            OnboardingTraitsPage.RefreshForDraft();
            RebuildOnboardingTraitsNavigation();
        }
        else if (classesSelected)
            UpdateOnboardingClassesNavigation();
        else if (characteristicsSelected)
        {
            OnboardingCharacteristicsPage.RefreshForDraft();
            UpdateOnboardingCharacteristicsNavigation();
        }
        else if (resultSelected)
            RefreshOnboardingResult();

        foreach (var candidate in _onboardingTabs)
        {
            var selected = candidate.Index == _selectedOnboardingTab;
            candidate.Button.StyleBoxOverride = CreateOnboardingTabStyleBox(selected);
            candidate.Button.Label.FontColorOverride = selected ? BrightGold : Color.FromHex("#AAA18F");
        }

        RefreshOnboardingResponsiveLayout();
    }

    private void SelectOnboardingAppearanceSection(Wh40kAppearanceSection section)
    {
        _selectedOnboardingAppearanceSection = section;
        OnboardingAppearancePage.SelectSection(section);
        if (section != Wh40kAppearanceSection.Portraits)
            HideOnboardingPortraitPreviewImmediately();

        foreach (var candidate in _onboardingAppearanceSections)
        {
            candidate.Selected = candidate.Section == section;
            candidate.VisualDirty = true;
            UpdateOnboardingAppearanceSectionPresentation(candidate, IsReducedMotion);
        }
    }

    private void UpdateOnboardingAppearanceSectionVisuals(float deltaSeconds, bool reducedMotion)
    {
        if (!OnboardingAppearanceNavigation.Visible)
            return;

        foreach (var presentation in _onboardingAppearanceSections)
        {
            // Selection is derived from the only authoritative state every frame.
            // This also repairs a card if the page was made visible after its first
            // presentation update, rather than leaving it with the normal surface.
            var selected = presentation.Section == _selectedOnboardingAppearanceSection;
            if (presentation.Selected != selected)
            {
                presentation.Selected = selected;
                presentation.VisualDirty = true;
            }

            var hovered = presentation.Button.IsHovered;
            if (hovered != presentation.Hovered)
            {
                presentation.Hovered = hovered;
                presentation.VisualDirty = true;
            }

            var hoverChanged = presentation.HoverTransition.Update(
                presentation.Hovered,
                deltaSeconds,
                reducedMotion);

            if (hoverChanged || presentation.VisualDirty)
                UpdateOnboardingAppearanceSectionPresentation(presentation, reducedMotion);
        }
    }

    private void UpdateOnboardingAppearanceSectionPresentation(
        OnboardingAppearanceSectionPresentation presentation,
        bool reducedMotion)
    {
        if (reducedMotion)
        {
            presentation.Hovered = presentation.Button.IsHovered;
            presentation.HoverTransition.Update(presentation.Hovered, 0f, reducedMotion: true);
        }

        ApplyOnboardingNavigationCardStyle(
            presentation.Button,
            presentation.Selected,
            presentation.HoverTransition.Value);
        presentation.IndexLabel.FontColorOverride = Gold;
        presentation.TitleLabel.FontColorOverride = Paper;
        presentation.DescriptionLabel.FontColorOverride = presentation.Selected
            ? Color.FromHex("#D4C9B2")
            : Color.FromHex("#AAA18F");
        presentation.Button.Margin = new Thickness(
            presentation.HoverTransition.Value * 3f,
            0f,
            0f,
            0f);
        presentation.VisualDirty = false;
    }

    /// <summary>
    /// Creates the common numbered navigation card used by every data-driven
    /// onboarding step.  Keeping its text in bounded child labels prevents a long
    /// localized name from asking a ScrollContainer for an unbounded width.
    /// </summary>
    private OnboardingNavigationCardPresentation<T> CreateOnboardingNavigationCard<T>(
        T value,
        int ordinal,
        string title,
        string description)
    {
        var button = new Button
        {
            HorizontalExpand = true,
            MinHeight = 69,
        };
        button.Label.Visible = false;
        button.DefaultCursorShape = Control.CursorShape.Hand;

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            VerticalExpand = true,
            SeparationOverride = 12,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var index = new Label
        {
            Text = ordinal.ToString("D2"),
            FontOverride = _onboardingNavigationIndexFont,
            FontColorOverride = Gold,
            SetWidth = 27,
            Align = Label.AlignMode.Center,
            VerticalAlignment = Control.VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var copy = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalAlignment = Control.VAlignment.Center,
            SeparationOverride = 4,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var titleLabel = new Label
        {
            Text = title,
            FontOverride = _onboardingNavigationTitleFont,
            FontColorOverride = Color.FromHex("#DFD7C3"),
            HorizontalExpand = true,
            ClipText = true,
            MouseFilter = MouseFilterMode.Ignore,
        };
        var descriptionLabel = new Label
        {
            Text = description,
            FontOverride = _onboardingNavigationDescriptionFont,
            FontColorOverride = Color.FromHex("#AAA18F"),
            HorizontalExpand = true,
            ClipText = true,
            MouseFilter = MouseFilterMode.Ignore,
        };

        copy.AddChild(titleLabel);
        copy.AddChild(descriptionLabel);
        content.AddChild(index);
        content.AddChild(copy);
        button.AddChild(content);

        var presentation = new OnboardingNavigationCardPresentation<T>(
            button,
            index,
            titleLabel,
            descriptionLabel,
            value);
        return presentation;
    }

