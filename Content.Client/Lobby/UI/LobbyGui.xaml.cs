    private void RefreshOnboardingPreview(Wh40kOnboardingDraft draft)
    {
        _onboardingDraft = draft;
        RefreshOnboardingResultPortrait();
        if (_onboardingPreviewDummy is { } existingDummy &&
            _entityManager.EntityExists(existingDummy) &&
            _onboardingPreviewSpecies == draft.Profile.Species.ToString() &&
            _onboardingPreviewShowClothes == draft.ShowClothes)
        {
            // Updating the existing client-side dummy is the cheap path for all
            // appearance sliders. Re-spawning it for every slider tick causes
            // visible hitches and is only needed when its species or clothes change.
            _entityManager.System<HumanoidAppearanceSystem>().LoadProfile(existingDummy, draft.Profile);
            ApplyOnboardingPortraitPreviewVisuals();
            return;
        }

        if (_onboardingPreviewDummy is { } oldDummy)
        {
            OnboardingSpriteView.SetEntity(null);
            if (_entityManager.EntityExists(oldDummy))
                _entityManager.DeleteEntity(oldDummy);
        }

        var controller = UserInterfaceManager.GetUIController<LobbyUIController>();
        var dummy = controller.LoadProfileEntity(draft.Profile, null, draft.ShowClothes);
        _onboardingPreviewDummy = dummy;
        _onboardingPreviewSpecies = draft.Profile.Species.ToString();
        _onboardingPreviewShowClothes = draft.ShowClothes;
        OnboardingSpriteView.SetEntity(dummy);
        OnboardingPreviewPlaceholder.Visible = false;
        ApplyOnboardingPortraitPreviewVisuals();
    }

