    private static float ApproachPresentation(float value, float target, float deltaSeconds, bool reducedMotion)
    {
        if (reducedMotion)
            return target;

        var speed = Math.Clamp(deltaSeconds * 12f, 0f, 1f);
        var approached = value + (target - value) * speed;
        return MathF.Abs(approached - target) <= 0.002f ? target : approached;
    }

    /// <summary>
    /// Reproduces the <c>transition: ... .18s ease</c> used by the HTML navigation cards.
    /// It is intentionally separate from the lobby-wide presentation smoothing, whose
    /// duration and curve are different.
    /// </summary>
    private sealed class OnboardingCardHoverTransition
    {
        private const float Duration = 0.18f;
        private float _start;
        private float _target;
        private float _elapsed = Duration;

        public float Value { get; private set; }

        public bool Update(bool active, float deltaSeconds, bool reducedMotion)
        {
            var target = active ? 1f : 0f;
            var previous = Value;

            if (reducedMotion)
            {
                Value = target;
                _start = target;
                _target = target;
                _elapsed = Duration;
                return previous != Value;
            }

            if (target != _target)
            {
                _start = Value;
                _target = target;
                _elapsed = 0f;
            }

            if (_elapsed >= Duration)
                return false;

            _elapsed = Math.Min(Duration, _elapsed + Math.Max(0f, deltaSeconds));
            Value = _start + (_target - _start) * EvaluateOnboardingCardCssEase(_elapsed / Duration);
            if (_elapsed >= Duration)
                Value = _target;

            return previous != Value;
        }
    }

    private static float EvaluateOnboardingCardCssEase(float progress)
    {
        progress = Math.Clamp(progress, 0f, 1f);
        var low = 0f;
        var high = 1f;

        // CSS ease: cubic-bezier(.25, .1, .25, 1).  The x coordinate must be
        // inverted before its y coordinate can be used as the interpolation value.
        for (var iteration = 0; iteration < 12; iteration++)
        {
            var time = (low + high) * 0.5f;
            if (EvaluateCubicBezier(time, 0.25f, 0.25f) < progress)
                low = time;
            else
                high = time;
        }

        return EvaluateCubicBezier((low + high) * 0.5f, 0.1f, 1f);
    }

    private static float EvaluateCubicBezier(float time, float firstControl, float secondControl)
    {
        var inverseTime = 1f - time;
        return 3f * inverseTime * inverseTime * time * firstControl
               + 3f * inverseTime * time * time * secondControl
               + time * time * time;
    }

    private static Color LerpColor(Color from, Color to, float progress)
    {
        progress = Math.Clamp(progress, 0f, 1f);
        return new Color(
            from.R + (to.R - from.R) * progress,
            from.G + (to.G - from.G) * progress,
            from.B + (to.B - from.B) * progress,
            from.A + (to.A - from.A) * progress);
    }

