    /// <summary>
    /// Applies the card surface as a value object. The selected branch is never
    /// mutated on an existing <see cref="StyleBox"/>, so a normal card cannot keep
    /// rendering after its selection changes.
    /// </summary>
    private static void ApplyOnboardingNavigationCardStyle(
        Button button,
        bool selected,
        float hoverAmount,
        Color? persistentAccentColor = null)
    {
        // The base SS14 theme darkens the surface of every Button with its own
        // ModulateSelf colour. It must not tint this CSS-equivalent StyleBox: its
        // selected border, marker and gradient own their exact colours.
        button.ModulateSelfOverride = Color.White;

        var previousStyle = button.StyleBoxOverride as OnboardingAppearanceCardStyleBox;
        var replaced = previousStyle == null ||
                       previousStyle.Selected != selected ||
                       !Nullable.Equals(previousStyle.PersistentAccentColor, persistentAccentColor);
        var style = replaced
            ? new OnboardingAppearanceCardStyleBox(selected, persistentAccentColor)
            : previousStyle!;
        if (replaced)
            button.StyleBoxOverride = style;

        var hoverChanged = style.HoverAmount != hoverAmount;
        style.HoverAmount = hoverAmount;
        if (replaced || hoverChanged)
            button.InvalidateMeasure();
    }

