using Content.Client._WH40K.UserInterface;
using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Lobby.UI.Roles;

[GenerateTypedNameReferences]
public sealed partial class TraitPreferenceSelector : Control
{
    public int Cost;
    private bool _preference;

    public bool Preference
    {
        get => _preference;
        set
        {
            _preference = value;
            UpdateButtonState();
        }
    }

    public event Action<bool>? PreferenceChanged;
    public string SearchText { get; }

    public TraitPreferenceSelector(TraitPrototype trait)
    {
        RobustXamlLoader.Load(this);

        Cost = trait.Cost;

        // Set the trait name
        NameLabel.Text = Loc.GetString(trait.Name);
        var description = trait.Description is { } desc ? Loc.GetString(desc) : string.Empty;
        SearchText = $"{NameLabel.Text}\n{description}";
        DescriptionLabel.Visible = description.Length > 0;
        DescriptionLabel.SetMessage(description, Wh40kInterfaceTheme.MutedText);

        // Set the cost text and color
        string costText = "";
        if (trait.Cost > 0)
        {
            costText = $"-{trait.Cost}";
            CostLabel.FontColorOverride = Color.FromHex("#EF987E");
        }
        else if (trait.Cost < 0)
        {
            costText = $"+{-trait.Cost}";
            CostLabel.FontColorOverride = Color.FromHex("#9ED1AA");
        }
        else
        {
            costText = $"{trait.Cost}";
            CostLabel.FontColorOverride = Wh40kInterfaceTheme.MutedText;
        }

        CostLabel.Text = costText;

        // Set up button event
        TraitButton.OnPressed += OnTraitButtonPressed;

        TraitButton.ToolTip = description;

        UpdateButtonState();
    }

    public void SetTooltip(string tooltip)
    {
        TraitButton.TooltipSupplier = _ =>
        {
            var tip = new Robust.Client.UserInterface.CustomControls.Tooltip();
            tip.SetMessage(FormattedMessage.FromMarkupPermissive(tooltip));
            return tip;
        };
    }

    private void OnTraitButtonPressed(BaseButton.ButtonEventArgs args)
    {
        // Clicking the trait button toggles selection
        Preference = !Preference;
        PreferenceChanged?.Invoke(Preference);
    }

    private void UpdateButtonState()
    {
        TraitButton.Pressed = Preference;
    }

    /// <summary>
    /// Dims the trait name and disables selection when the trait is unavailable.
    /// </summary>
    /// <param name="unavailable">Whether the trait is unavailable for selection</param>
    public void SetUnavailable(bool unavailable)
    {
        NameLabel.FontColorOverride = unavailable ? Wh40kInterfaceTheme.MutedText : Wh40kInterfaceTheme.Text;
        TraitButton.Disabled = unavailable;
    }
}
