using System;
using Content.Client.UserInterface.Controls;
using Content.Shared.Mapping;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Mapping.MapTransfer;

[GenerateTypedNameReferences]
public sealed partial class MapTransferWindow : FancyWindow
{
    private Guid? _selectedFolder;
    private Guid? _selectedMap;
    private MapTransferEuiState? _state;

    public event Action? RefreshRequested;
    public event Action? GoBackRequested;
    public event Action<Guid>? FolderOpenRequested;
    public event Action? UploadRequested;
    public event Action<Guid>? DownloadRequested;
    public event Action<Guid, string>? RenameRequested;
    public event Action? OpenDownloadFolderRequested;

    public bool OpenDownloadFolderAfterDownload => OpenDownloadFolderCheckBox.Pressed;

    public MapTransferWindow()
    {
        RobustXamlLoader.Load(this);

        RefreshButton.OnPressed += _ => RefreshRequested?.Invoke();
        BackButton.OnPressed += _ => GoBackRequested?.Invoke();
        OpenFolderButton.OnPressed += _ =>
        {
            if (_selectedFolder is { } folder)
                FolderOpenRequested?.Invoke(folder);
        };
        UploadButton.OnPressed += _ => UploadRequested?.Invoke();
        OpenDownloadFolderButton.OnPressed += _ => OpenDownloadFolderRequested?.Invoke();
        DownloadButton.OnPressed += _ =>
        {
            if (_selectedMap is { } map)
                DownloadRequested?.Invoke(map);
        };
        RenameButton.OnPressed += _ => RequestRename();
        RenameLineEdit.OnTextEntered += _ => RequestRename();
        FolderList.OnItemSelected += args =>
        {
            _selectedFolder = (args.ItemList[args.ItemIndex].Metadata as MapTransferFolderEntry)?.Id;
            UpdateButtons();
        };
        FolderList.OnItemDeselected += _ =>
        {
            _selectedFolder = null;
            UpdateButtons();
        };
        MapList.OnItemSelected += args =>
        {
            var map = args.ItemList[args.ItemIndex].Metadata as MapTransferMapEntry;
            _selectedMap = map?.Id;
            RenameLineEdit.Text = map == null ? string.Empty : GetMapBaseName(map.Name);
            UpdateButtons();
        };
        MapList.OnItemDeselected += _ =>
        {
            _selectedMap = null;
            RenameLineEdit.Text = string.Empty;
            UpdateButtons();
        };
    }

    public void UpdateState(MapTransferEuiState state)
    {
        _state = state;
        CurrentFolder.Text = state.CurrentFolder;
        StatusLabel.Text = Loc.GetString(GetStatusLocId(state.Status));
        _selectedFolder = null;
        _selectedMap = null;
        RenameLineEdit.Text = string.Empty;

        FolderList.Clear();
        foreach (var folder in state.Folders)
        {
            FolderList.Add(new ItemList.Item(FolderList)
            {
                Text = folder.Name,
                Metadata = folder,
            });
        }

        MapList.Clear();
        foreach (var map in state.Maps)
        {
            MapList.Add(new ItemList.Item(MapList)
            {
                Text = $"{map.Name} ({FormatBytes(map.Size)})",
                Metadata = map,
            });
        }

        UpdateButtons();
    }

    private void UpdateButtons()
    {
        var state = _state;
        var enabled = state?.Enabled == true;
        RefreshButton.Disabled = !enabled;
        BackButton.Disabled = !enabled || state?.CanGoBack != true;
        OpenFolderButton.Disabled = !enabled || _selectedFolder == null;
        UploadButton.Disabled = !enabled
                                || state?.CanUpload != true
                                || state?.Status is MapTransferUiStatus.Uploading or MapTransferUiStatus.Downloading;
        DownloadButton.Disabled = !enabled
                                  || state?.CanDownload != true
                                  || _selectedMap == null
                                  || state?.Status is MapTransferUiStatus.Uploading or MapTransferUiStatus.Downloading;
        var canRename = enabled
                        && _selectedMap != null
                        && state?.Status is not (MapTransferUiStatus.Uploading or MapTransferUiStatus.Downloading);
        RenameLineEdit.Editable = canRename;
        RenameButton.Disabled = !canRename;
        OpenDownloadFolderButton.Disabled = false;
    }

    private void RequestRename()
    {
        if (_selectedMap is { } map)
            RenameRequested?.Invoke(map, RenameLineEdit.Text);
    }

    private static string GetMapBaseName(string filename)
    {
        return filename.EndsWith(".yml", StringComparison.OrdinalIgnoreCase)
            ? filename[..^4]
            : filename;
    }

    private static string FormatBytes(long bytes)
    {
        return bytes < 1024 * 1024
            ? $"{Math.Max(0, bytes) / 1024d:0.0} KiB"
            : $"{bytes / 1024d / 1024d:0.0} MiB";
    }

    private static string GetStatusLocId(MapTransferUiStatus status)
    {
        return status switch
        {
            MapTransferUiStatus.Ready => "map-transfer-status-ready",
            MapTransferUiStatus.Disabled => "map-transfer-status-disabled",
            MapTransferUiStatus.AccessDenied => "map-transfer-status-access-denied",
            MapTransferUiStatus.Uploading => "map-transfer-status-uploading",
            MapTransferUiStatus.Downloading => "map-transfer-status-downloading",
            MapTransferUiStatus.Completed => "map-transfer-status-completed",
            MapTransferUiStatus.InvalidMap => "map-transfer-status-invalid-map",
            MapTransferUiStatus.FileTooLarge => "map-transfer-status-file-too-large",
            MapTransferUiStatus.QuotaExceeded => "map-transfer-status-quota-exceeded",
            MapTransferUiStatus.Busy => "map-transfer-status-busy",
            MapTransferUiStatus.TimedOut => "map-transfer-status-timed-out",
            MapTransferUiStatus.InvalidName => "map-transfer-status-invalid-name",
            MapTransferUiStatus.NameTaken => "map-transfer-status-name-taken",
            _ => "map-transfer-status-failed",
        };
    }
}
