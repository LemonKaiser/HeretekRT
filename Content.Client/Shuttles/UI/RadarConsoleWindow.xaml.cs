using Content.Client.Computer;
using Content.Client.UserInterface.Controls;
using Content.Shared.Shuttles.BUIStates;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Shuttles.UI;

[GenerateTypedNameReferences]
public sealed partial class RadarConsoleWindow : FancyWindow,
    IComputerWindow<NavInterfaceState>
{
    public RadarConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        IFFToggle.Pressed = RadarScreen.ShowIFF;
        IFFDetailedToggle.Pressed = RadarScreen.ShowIFFDetailed;
        IFFToggle.OnToggled += args => RadarScreen.ShowIFF = args.Pressed;
        IFFDetailedToggle.OnToggled += args => RadarScreen.ShowIFFDetailed = args.Pressed;
        MainTabs.SetTabTitle(0, Loc.GetString("radar-console-window-title"));
        MainTabs.SetTabTitle(1, Loc.GetString("shuttle-console-sensors-tab"));
    }

    public void UpdateState(NavInterfaceState scc)
    {
        RadarScreen.UpdateState(scc);
    }

    public void SetConsole(EntityUid consoleEntity)
    {
        RadarScreen.SetConsole(consoleEntity);
    }

}
