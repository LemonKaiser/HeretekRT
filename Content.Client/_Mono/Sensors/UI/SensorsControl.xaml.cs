using System.Globalization;
using System.Linq;
using Content.Shared._Mono.Sensors;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Timing;

namespace Content.Client._Mono.Sensors.UI;

[GenerateTypedNameReferences]
public sealed partial class SensorsControl : BoxContainer
{
    [Dependency] private IGameTiming _gameTiming = default!;

    public event Action<SensorsSetEmconMessage>? OnEmcon;
    public event Action<SensorsSetArcMessage>? OnArc;
    public event Action<SensorsSetDatalinkMessage>? OnDatalink;
    public event Action<NetEntity>? OnContactLock;

    private readonly Dictionary<NetEntity, float> _predictedOffset = new();
    private SensorsBuiState? _lastState;
    private string _contactFilter = string.Empty;
    private HashSet<string>? _pendingDatalinkCodes;

    private static readonly float[] ContactColumnWidths = [64, 56, 68, 70, 86, 86];

    private static readonly Color DatalinkColor = Color.FromHex("#FFAA33");
    private static readonly Color IlluminatorColor = Color.FromHex("#4488FF");

    public SensorsControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        DatalinkApply.OnPressed += _ => SubmitDatalink();
        DatalinkEdit.OnTextEntered += _ => SubmitDatalink();

        ContactHeader.AddChild(CreateContactRow([
            Loc.GetString("gunnery-emcon-range"),
            Loc.GetString("gunnery-emcon-angle"),
            Loc.GetString("gunnery-emcon-source"),
            Loc.GetString("gunnery-emcon-cross-section"),
            Loc.GetString("gunnery-emcon-infrared"),
            Loc.GetString("gunnery-emcon-ars"),
            Loc.GetString("gunnery-emcon-track"),
        ]));

        ContactSearch.OnTextChanged += args =>
        {
            _contactFilter = args.Text.Trim();
            if (_lastState != null)
                RebuildContacts(_lastState);
        };

        DatalinkEdit.Editable = false;
        DatalinkApply.Disabled = true;
    }

    private void SubmitDatalink()
    {
        if (_lastState == null)
            return;

        var codes = SensorsSetDatalinkMessage.NormalizeCodes(DatalinkEdit.Text.Split([' ', ',', ';']));
        _pendingDatalinkCodes = codes.ToHashSet();
        DatalinkEdit.Text = string.Join(' ', codes);
        OnDatalink?.Invoke(new SensorsSetDatalinkMessage { Codes = codes });
    }

    public void UpdateState(SensorsBuiState? state)
    {
        DatalinkEdit.Editable = state != null;
        DatalinkApply.Disabled = state == null;

        if (state == null)
        {
            _lastState = null;
            ContactsBox.RemoveAllChildren();
            HardwareBox.RemoveAllChildren();
            _predictedOffset.Clear();
            _pendingDatalinkCodes = null;
            DatalinkEdit.Text = string.Empty;
            ArcDisplay.Update(
                Array.Empty<SensorHardwareDto>(),
                Array.Empty<SensorContactDto>(),
                0f,
                _gameTiming.CurTime,
                predictedOffsets: null,
                chaffArcs: null);
            return;
        }

        _lastState = state;

        foreach (var h in state.Hardware)
        {
            if (_predictedOffset.TryGetValue(h.Entity, out var pred)
                && MathF.Abs(AngleDiff(pred, h.ArcOffset)) < 0.5f)
            {
                _predictedOffset.Remove(h.Entity);
            }
        }

        if (!IsHardwareFocused(UserInterfaceManager.ControlFocused) &&
            !IsHardwareFocused(UserInterfaceManager.KeyboardFocused))
        {
            RebuildHardware(state);
        }

        RebuildContacts(state);

        if (_pendingDatalinkCodes?.SetEquals(state.DatalinkCodes) == true)
            _pendingDatalinkCodes = null;

        if (_pendingDatalinkCodes == null && !DatalinkEdit.HasKeyboardFocus())
            DatalinkEdit.Text = string.Join(' ', state.DatalinkCodes);

        ArcDisplay.Update(
            state.Hardware,
            state.Contacts,
            state.GridWorldRotationDegrees,
            _gameTiming.CurTime,
            _predictedOffset,
            state.ChaffArcs);
    }

    private void RebuildContacts(SensorsBuiState state)
    {
        ContactsBox.RemoveAllChildren();
        var now = _gameTiming.CurTime;

        IEnumerable<SensorContactDto> list = state.Contacts.OrderBy(c => c.Range);
        if (!string.IsNullOrEmpty(_contactFilter))
        {
            list = list.Where(c =>
                (c.Name?.Contains(_contactFilter, StringComparison.OrdinalIgnoreCase) ?? false)
                || c.Sources.Contains(_contactFilter, StringComparison.OrdinalIgnoreCase)
                || c.Target.ToString().Contains(_contactFilter, StringComparison.OrdinalIgnoreCase));
        }

        foreach (var c in list)
        {
            var threshold = c.IsDatalink ? 6.0 : 2.0;
            var stale = (now - c.LastSeen).TotalSeconds > threshold;

            Color color;
            if (stale)
                color = Color.Red;
            else if (c.IsIlluminator)
                color = IlluminatorColor;
            else if (c.IsDatalink)
                color = DatalinkColor;
            else
                color = Color.Lime;

            var row = CreateContactRow([
                Loc.GetString("gunnery-emcon-range-value", ("range", $"{c.Range:F0}")),
                $"{c.BearingDegrees:F0}°",
                c.Sources,
                c.Rcs > 0 ? $"{c.Rcs:F0} m²" : "—",
                c.IrSignature > 0 ? $"{c.IrSignature:F0}" : "—",
                c.ActiveRadarWatts > 0
                    ? Loc.GetString("gunnery-emcon-ars-value", ("output", c.ActiveRadarWatts))
                    : "—",
                c.Name ?? c.Target.ToString(),
            ], color);

            if (OnContactLock != null)
            {
                row.MouseFilter = MouseFilterMode.Stop;
                row.OnKeyBindDown += args =>
                {
                    if (args.Function != EngineKeyFunctions.UIClick)
                        return;

                    OnContactLock?.Invoke(c.Target);
                    args.Handle();
                };
            }

            ContactsBox.AddChild(row);
        }
    }

    private static BoxContainer CreateContactRow(string[] values, Color? color = null)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Margin = new Thickness(0, 1),
        };

        for (var i = 0; i < values.Length; i++)
        {
            var label = new Label { Text = values[i], FontColorOverride = color };
            if (color == null)
                label.AddStyleClass("LabelKeyText");

            if (i < ContactColumnWidths.Length)
            {
                label.SetWidth = ContactColumnWidths[i];
                label.ClipText = true;
                label.MouseFilter = MouseFilterMode.Pass;
                label.ToolTip = values[i];
            }
            else
            {
                label.HorizontalExpand = true;
            }

            row.AddChild(label);
        }

        return row;
    }

    private bool IsHardwareFocused(Control? control) =>
        control?.GetSelfAndLogicalAncestors().Contains(HardwareBox) == true;

    private void RebuildHardware(SensorsBuiState state)
    {
        HardwareBox.RemoveAllChildren();

        foreach (var h in state.Hardware)
        {
            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                SeparationOverride = 2,
            };

            var type = Loc.GetString($"gunnery-emcon-sensor-{h.SensorType}");
            var text = h.SensorType == SensorType.ActiveRadar
                ? Loc.GetString("gunnery-emcon-sensor-info-emitter",
                    ("name", h.Name),
                    ("type", type),
                    ("output", h.TransmitWatts))
                : Loc.GetString("gunnery-emcon-sensor-info-passive",
                    ("name", h.Name),
                    ("type", type),
                    ("sensitivity", h.Sensitivity));

            var description = new RichTextLabel { RectClipContent = true };
            description.SetMessage(text, Color.Lime);
            row.AddChild(description);

            var controls = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                SeparationOverride = 4,
            };
            row.AddChild(controls);

            var power = new Button
            {
                Text = Loc.GetString(h.Enabled ? "gunnery-emcon-power-on" : "gunnery-emcon-power-off"),
                ToggleMode = true,
                Pressed = h.Enabled,
                MinWidth = 48,
            };
            var ent = h.Entity;
            var active = h.ActiveMode;
            power.OnPressed += args =>
            {
                OnEmcon?.Invoke(new SensorsSetEmconMessage
                {
                    Sensor = ent,
                    Enabled = args.Button.Pressed,
                    ActiveMode = active,
                });
            };
            controls.AddChild(power);

            if (h.SensorType is SensorType.ActiveRadar)
            {
                var emit = new Button
                {
                    Text = Loc.GetString(h.ActiveMode ? "gunnery-emcon-emitting" : "gunnery-emcon-standby"),
                    ToggleMode = true,
                    Pressed = h.ActiveMode,
                    Disabled = !h.Enabled || !h.Powered,
                    MinWidth = 56,
                };
                var enabled = h.Enabled;
                emit.OnPressed += args =>
                {
                    OnEmcon?.Invoke(new SensorsSetEmconMessage
                    {
                        Sensor = ent,
                        Enabled = enabled,
                        ActiveMode = args.Button.Pressed,
                    });
                };
                controls.AddChild(emit);
            }

            if (h is { ArcDegrees: < 360f, ArcConfigurable: true })
            {
                var offset = GetEffectiveOffset(h);
                var displayBearing = WorldOffsetToDisplayBearing(
                    offset,
                    h.GridRelativeArc,
                    state.GridWorldRotationDegrees);

                var bearingEdit = new LineEdit
                {
                    Text = $"{displayBearing:F0}",
                    MinWidth = 44,
                };

                var lastSubmittedText = bearingEdit.Text;
                void SubmitBearing()
                {
                    if (_lastState == null || bearingEdit.Text == lastSubmittedText)
                        return;

                    if (CommitBearingEdit(bearingEdit, h, _lastState.GridWorldRotationDegrees))
                        lastSubmittedText = bearingEdit.Text;
                }

                bearingEdit.OnFocusExit += _ => SubmitBearing();
                bearingEdit.OnTextEntered += _ => SubmitBearing();

                controls.AddChild(bearingEdit);

                var left = new Button { Text = "<", MinWidth = 28 };
                var right = new Button { Text = ">", MinWidth = 28 };
                left.OnPressed += _ => NudgeArc(ent, h, +15f);
                right.OnPressed += _ => NudgeArc(ent, h, -15f);
                controls.AddChild(left);
                controls.AddChild(right);
            }
            else if (h.ArcDegrees < 360f)
            {
                var displayBearing = WorldOffsetToDisplayBearing(
                    h.ArcOffset,
                    h.GridRelativeArc,
                    state.GridWorldRotationDegrees);
                controls.AddChild(new Label
                {
                    Text = $"{displayBearing:F0}°",
                    MinWidth = 40,
                    FontColorOverride = Color.Gray,
                });
            }

            if (!h.Powered)
                row.Modulate = Color.FromHex("#884444");

            HardwareBox.AddChild(row);
        }
    }

    private bool CommitBearingEdit(LineEdit edit, SensorHardwareDto h, float gridWorldDeg)
    {
        if (!float.TryParse(edit.Text, NumberStyles.Float, CultureInfo.InvariantCulture, out var entered)
            || !float.IsFinite(entered))
        {
            return false;
        }

        var worldOff = DisplayBearingToWorldOffset(Normalize360(entered), h.GridRelativeArc, gridWorldDeg);
        PredictAndSendArc(h.Entity, worldOff);
        return true;
    }

    private float GetEffectiveOffset(SensorHardwareDto h)
    {
        return _predictedOffset.TryGetValue(h.Entity, out var p) ? p : h.ArcOffset;
    }

    private void NudgeArc(NetEntity ent, SensorHardwareDto h, float deltaDegrees)
    {
        var current = GetEffectiveOffset(h);
        PredictAndSendArc(ent, Normalize360(current + deltaDegrees));
    }

    private void PredictAndSendArc(NetEntity ent, float worldOffsetDeg)
    {
        worldOffsetDeg = Normalize360(worldOffsetDeg);
        _predictedOffset[ent] = worldOffsetDeg;

        OnArc?.Invoke(new SensorsSetArcMessage
        {
            Sensor = ent,
            ArcOffsetDegrees = worldOffsetDeg,
        });

        if (_lastState != null)
        {
            ArcDisplay.Update(
                _lastState.Hardware,
                _lastState.Contacts,
                _lastState.GridWorldRotationDegrees,
                _gameTiming.CurTime,
                _predictedOffset,
                _lastState.ChaffArcs);
        }
    }

    private static float Normalize360(float deg)
    {
        deg %= 360f;
        if (deg < 0f)
            deg += 360f;
        return deg;
    }

    private static float AngleDiff(float a, float b)
    {
        var d = MathF.Abs(Normalize360(a) - Normalize360(b));
        return d > 180f ? 360f - d : d;
    }

    private static float WorldOffsetToDisplayBearing(float arcOffset, bool gridRelative, float gridWorldDeg)
    {
        var world = gridRelative ? gridWorldDeg + arcOffset : arcOffset;
        return WorldToDisplay(world);
    }

    private static float DisplayBearingToWorldOffset(float displayBearing, bool gridRelative, float gridWorldDeg)
    {
        var world = DisplayToWorld(displayBearing);
        if (gridRelative)
            world = Normalize360(world - gridWorldDeg);
        return world;
    }

    private static float WorldToDisplay(float worldDeg)
    {
        var d = (90f - worldDeg) % 360f;
        if (d < 0f)
            d += 360f;
        return d;
    }

    public static float DisplayToWorld(float displayDeg)
    {
        return WorldToDisplay(displayDeg);
    }
}
