using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._WH40K.Augments;
using Content.Shared.Storage;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Augments;

[GenerateTypedNameReferences]
public sealed partial class AugmentToolPanelMenu : RadialMenu
{
    private static readonly Color ActiveAccentBorder = Color.FromHex("#E1C17E");
    private static readonly Color ActiveAccentBackground = Color.FromHex("#3A2C16CC");
    private static readonly Color RetractTileBorder = Color.FromHex("#79603D");
    private static readonly Color RetractTileBackground = Color.FromHex("#1A140ED8");
    private static readonly ResPath RetractIconPath = new("/Textures/Interface/VerbIcons/eject.svg.192dpi.png");

    [Dependency] private EntityManager _entities = default!;
    [Dependency] private IResourceCache _resourceCache = default!;

    public event Action<EntityUid?>? SendSwitchMessage;

    private EntityUid _owner;

    public AugmentToolPanelMenu()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    public void SetEntity(EntityUid owner)
    {
        _owner = owner;
        Refresh();
    }

    private void Refresh()
    {
        Main.RemoveAllChildren();
        if (!_entities.TryGetComponent<StorageComponent>(_owner, out var storage))
            return;

        EntityUid? activeTool = null;
        if (_entities.TryGetComponent<AugmentToolPanelComponent>(_owner, out var panel) &&
            panel.ActiveTool is { } activeNet &&
            _entities.TryGetEntity(activeNet, out var resolvedActive) &&
            resolvedActive is { } activeUid &&
            _entities.EntityExists(activeUid))
        {
            activeTool = activeUid;
        }

        if (activeTool is { } deployed)
        {
            var activeButton = new RadialMenuTextureButton
            {
                SetSize = new Vector2(64f, 64f),
                StyleClasses = { "RadialMenuButton" },
                ToolTip = Loc.GetString("augment-tool-panel-active-tooltip", ("item", _entities.GetComponent<MetaDataComponent>(deployed).EntityName)),
            };
            var highlight = new PanelContainer
            {
                HorizontalExpand = true,
                VerticalExpand = true,
                MouseFilter = MouseFilterMode.Ignore,
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = ActiveAccentBackground,
                    BorderColor = ActiveAccentBorder,
                    BorderThickness = new Thickness(2),
                },
            };
            highlight.AddChild(new SpriteView(deployed, _entities) { Scale = new Vector2(3f, 3f) });
            activeButton.AddChild(highlight);
            Main.AddChild(activeButton);
            activeButton.OnButtonUp += _ =>
            {
                SendSwitchMessage?.Invoke(null);
                Close();
            };
        }

        foreach (var (entity, _) in storage.StoredItems)
        {
            var button = new RadialMenuTextureButton
            {
                SetSize = new Vector2(64f, 64f),
                StyleClasses = { "RadialMenuButton" },
                ToolTip = _entities.GetComponent<MetaDataComponent>(entity).EntityName,
            };
            button.AddChild(new SpriteView(entity, _entities) { Scale = new Vector2(3f, 3f) });
            Main.AddChild(button);
            button.OnButtonUp += _ =>
            {
                SendSwitchMessage?.Invoke(entity);
                Close();
            };
        }

        var retract = new RadialMenuTextureButton
        {
            SetSize = new Vector2(64f, 64f),
            StyleClasses = { "RadialMenuButton" },
            ToolTip = Loc.GetString("augment-tool-panel-retract-tooltip"),
        };
        var retractTile = new PanelContainer
        {
            HorizontalExpand = true,
            VerticalExpand = true,
            MouseFilter = MouseFilterMode.Ignore,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = RetractTileBackground,
                BorderColor = RetractTileBorder,
                BorderThickness = new Thickness(1),
            },
        };
        if (_resourceCache.TryGetResource<TextureResource>(RetractIconPath, out var ejectRes))
        {
            retractTile.AddChild(new TextureRect
            {
                Texture = ejectRes.Texture,
                SetSize = new Vector2(30f, 30f),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                Modulate = ActiveAccentBorder,
                MouseFilter = MouseFilterMode.Ignore,
            });
        }
        else
        {
            retractTile.AddChild(new Label
            {
                Text = "✕",
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                FontColorOverride = ActiveAccentBorder,
            });
        }
        retract.AddChild(retractTile);
        Main.AddChild(retract);
        retract.OnButtonUp += _ =>
        {
            SendSwitchMessage?.Invoke(null);
            Close();
        };
    }
}
