using System.Linq;
using System.Numerics;
using Content.Shared._WH40K.Augments;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Graphics.RSI;
using Robust.Shared.Prototypes;

namespace Content.Client._WH40K.Augments;

[GenerateTypedNameReferences]
public sealed partial class Wh40kAugmentBedWindow : DefaultWindow
{
    private static readonly RsiDirection[] Directions =
        [RsiDirection.South, RsiDirection.East, RsiDirection.North, RsiDirection.West];

    private readonly IPrototypeManager _prototypes;
    private readonly IComponentFactory _componentFactory;
    private readonly SpriteSystem _sprites;
    private readonly (EntityPrototype Prototype, Wh40kAugmentBedZone Zone)[] _catalogue;
    private readonly Dictionary<Wh40kAugmentBedOption, ContainerButton> _deviceRows = new();
    private Wh40kAugmentBedState? _state;
    private Wh40kAugmentBedOption? _selected;
    private string? _zone;
    private string? _catalogueSelection;
    private int _facing;

    public event Action<Wh40kAugmentBedOption>? Install;

    public Wh40kAugmentBedWindow()
    {
        RobustXamlLoader.Load(this);
        _prototypes = IoCManager.Resolve<IPrototypeManager>();
        _componentFactory = IoCManager.Resolve<IComponentFactory>();
        _catalogue = Wh40kAugmentInfo.Catalogue(_prototypes, _componentFactory).ToArray();
        _sprites = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
        HeaderPanel.PanelOverride = Wh40kAugmentStyle.Panel(8);
        Scanner.PanelOverride = Wh40kAugmentStyle.Panel(8);
        FacingPanel.PanelOverride = Wh40kAugmentStyle.Panel(3);
        InventoryPanel.PanelOverride = Wh40kAugmentStyle.Panel(8);

        BodyMap.ZoneSelected += SelectZone;
        AllZones.OnPressed += _ => SelectZone(null);
        TurnLeft.OnPressed += _ => Rotate(-1);
        TurnRight.OnPressed += _ => Rotate(1);
        Confirm.OnPressed += _ =>
        {
            if (_selected is { } option)
                Install?.Invoke(option);
        };

        Rotate(0);
        UpdateZoneTitle();
        UpdateSelection();
    }

    public void Apply(Wh40kAugmentBedState state)
    {
        var previous = _state;
        _state = state;
        HeaderPanel.Visible = true;
        PowerStatus.Text = Loc.GetString(state.Powered ? "wh40k-augment-bed-ready" : "wh40k-augment-bed-offline");
        PowerStatus.FontColorOverride = state.Powered ? Wh40kAugmentStyle.Text : Wh40kAugmentStyle.SecondaryText;

        if (_selected != null && !state.Options.Contains(_selected))
            _selected = null;

        if (previous == null || !previous.Installed.SequenceEqual(state.Installed))
            UpdateZoneContents();
        if (previous == null || !previous.Options.SequenceEqual(state.Options))
            UpdateInventory();

        UpdateSelection();
    }

    private void SelectZone(string? zone)
    {
        if (_zone == zone)
            return;

        _zone = zone;
        _selected = null;
        _catalogueSelection = null;
        ItemScroll.VScroll = 0;
        UpdateZoneTitle();
        UpdateZoneContents();
        UpdateInventory();
        UpdateSelection();
    }

    private void Rotate(int delta)
    {
        _facing = (_facing + delta + Directions.Length) % Directions.Length;
        BodyMap.Facing = Directions[_facing];
        FacingLabel.Text = Loc.GetString("wh40k-augments-facing-" + _facing);
    }

    private void UpdateZoneTitle()
    {
        InventoryTitle.Text = _zone == null
            ? Loc.GetString("wh40k-augment-bed-inventory")
            : Loc.GetString("wh40k-augments-zone-" + _zone);
    }

    private void UpdateInventory()
    {
        Items.RemoveAllChildren();
        _deviceRows.Clear();

        if (_state is { } state)
        {
            foreach (var entry in state.Options.Where(entry => _zone == null || Wh40kAugmentCatalog.IsInZone(entry.Zone, _zone)).Distinct())
                AddRow(entry);
        }

        Empty.Visible = _state != null && _deviceRows.Count == 0;
        Empty.SetMessage(Loc.GetString(_zone == null ? "wh40k-augment-bed-empty" : "wh40k-augment-bed-empty-zone"),
            Wh40kAugmentStyle.SecondaryText);
    }

    private void UpdateSelection()
    {
        var highlight = _zone ?? (_selected is { Zone: not Wh40kAugmentBedZone.Eyes } option
            ? Wh40kAugmentCatalog.MapZone(option.Zone)
            : string.Empty);
        BodyMap.Select(highlight, string.Empty);

        SelectionPanel.Visible = _deviceRows.Count > 0;
        Confirm.Disabled = _selected == null || _state?.Powered != true;
        if (!SelectionPanel.Visible)
            return;

        var details = _selected is { } target
            ? IsOptics(target.Zone)
                ? Loc.GetString(target.Zone == Wh40kAugmentBedZone.Eyes ? "wh40k-augment-bed-pair-detail" : "wh40k-augment-bed-optics-detail")
            : target.ExistingPart == null
                ? Loc.GetString("wh40k-augment-bed-fit-detail")
                : Loc.GetString(target.RemoveInAdvance
                    ? "wh40k-augment-bed-replace-detail"
                    : "wh40k-augment-bed-vital-detail",
                    ("part", NameOf(target.ExistingPart)))
            : Loc.GetString("wh40k-augment-bed-select-detail");
        if (_selected is { } selected && _prototypes.TryIndex<EntityPrototype>(selected.Prototype, out var prototype))
            details = Wh40kAugmentInfo.Describe(prototype, _componentFactory) + "\n\n" + details;
        Details.SetMessage(details, Wh40kAugmentStyle.Text);
    }

    private static bool IsOptics(Wh40kAugmentBedZone zone)
        => zone is Wh40kAugmentBedZone.Eyes or Wh40kAugmentBedZone.LeftEye or Wh40kAugmentBedZone.RightEye;

    private void UpdateZoneContents()
    {
        ZoneContents.RemoveAllChildren();
        if (_zone is not { } zone)
            return;

        var installed = _state?.Installed.Where(entry => Wh40kAugmentCatalog.IsInZone(entry.Zone, zone)).ToArray() ?? [];
        var entries = installed.Length > 0
            ? installed.Select(entry => _prototypes.TryIndex<EntityPrototype>(entry.Prototype, out var entity) ? entity : null).OfType<EntityPrototype>()
            : _catalogue.Where(entry => Wh40kAugmentCatalog.IsInZone(entry.Zone, zone)).Select(entry => entry.Prototype);
        ZoneContents.AddChild(Section(installed.Length > 0 ? "wh40k-augment-bed-installed" : "wh40k-augment-bed-compatible"));
        var choices = entries.Distinct().OrderBy(entry => entry.Name).ToArray();
        if (choices.Length == 0)
            ZoneContents.AddChild(Section("wh40k-augment-bed-no-catalogue"));
        else if (installed.Length == 0 && choices.Length > 1)
        {
            var choice = Array.FindIndex(choices, prototype => prototype.ID == _catalogueSelection);
            choice = Math.Max(0, choice);
            var picker = new Wh40kAugmentModelPicker { HorizontalExpand = true, ToolTip = choices[choice].Name };
            for (var index = 0; index < choices.Length; index++)
                picker.AddItem(choices[index].Name, index);
            picker.SelectId(choice);
            var card = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            card.AddChild(BuildInfoCard(choices[choice]));
            picker.OnItemSelected += args =>
            {
                _catalogueSelection = choices[args.Id].ID;
                picker.SelectId(args.Id);
                picker.ToolTip = choices[args.Id].Name;
                card.RemoveAllChildren();
                card.AddChild(BuildInfoCard(choices[args.Id]));
            };
            ZoneContents.AddChild(picker);
            ZoneContents.AddChild(card);
        }
        else
        {
            foreach (var prototype in choices)
                ZoneContents.AddChild(BuildInfoCard(prototype));
        }

        ZoneContents.AddChild(Section("wh40k-augment-bed-inventory"));
    }

    private Control BuildInfoCard(EntityPrototype prototype)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = Wh40kAugmentStyle.Card(6),
        };
        panel.AddChild(BuildRow(prototype.ID, prototype.Name, Wh40kAugmentInfo.Describe(prototype, _componentFactory)));
        return panel;
    }

    private static Label Section(string key) => new()
    {
        Text = Loc.GetString(key),
        FontColorOverride = Wh40kAugmentStyle.SecondaryText,
    };

    private void AddRow(Wh40kAugmentBedOption entry)
    {
        var name = NameOf(entry.Prototype);
        var zone = Loc.GetString("wh40k-augment-bed-zone-" + entry.Zone.ToString().ToLowerInvariant());
        var button = new ContainerButton
        {
            HorizontalExpand = true,
            ToolTip = name,
            StyleBoxOverride = Wh40kAugmentStyle.Card(6, entry == _selected),
        };
        button.AddChild(BuildRow(entry.Prototype, name, zone));
        button.OnPressed += _ =>
        {
            if (_selected == entry)
                return;

            if (_selected is { } previous && _deviceRows.TryGetValue(previous, out var previousRow))
                previousRow.StyleBoxOverride = Wh40kAugmentStyle.Card(6);

            _selected = entry;
            button.StyleBoxOverride = Wh40kAugmentStyle.Card(6, selected: true);
            UpdateSelection();
        };
        _deviceRows.Add(entry, button);
        Items.AddChild(button);
    }

    private string NameOf(string prototype)
        => _prototypes.TryIndex<EntityPrototype>(prototype, out var entity) ? entity.Name : prototype;

    private Control BuildRow(string prototype, string name, string details)
    {
        var row = new BoxContainer { SeparationOverride = 7, MouseFilter = Control.MouseFilterMode.Ignore };
        row.AddChild(new TextureRect
        {
            Texture = _sprites.GetPrototypeIcon(prototype).Default,
            SetSize = new Vector2(32),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            MouseFilter = Control.MouseFilterMode.Ignore,
        });
        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            MouseFilter = Control.MouseFilterMode.Ignore,
        };
        var title = new RichTextLabel { HorizontalExpand = true, MouseFilter = Control.MouseFilterMode.Ignore };
        title.SetMessage(name, Wh40kAugmentStyle.Text);
        text.AddChild(title);
        var description = new RichTextLabel { HorizontalExpand = true, MouseFilter = Control.MouseFilterMode.Ignore };
        description.SetMessage(details, Wh40kAugmentStyle.SecondaryText);
        text.AddChild(description);
        row.AddChild(text);
        return row;
    }
}
