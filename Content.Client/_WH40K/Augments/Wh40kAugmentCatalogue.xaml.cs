[GenerateTypedNameReferences]
public sealed partial class Wh40kAugmentCatalogue : ScrollContainer
{
    internal const string SpritePath = "/Textures/_WH40K/Objects/Augments/augments.rsi";
    private static readonly RsiDirection[] Directions = [RsiDirection.South, RsiDirection.East, RsiDirection.North, RsiDirection.West];

    private readonly RSI _sprites;
    private readonly Font _technicalFont;
    private readonly Dictionary<string, Specimen[]> _zones;
    private readonly Dictionary<string, Specimen> _lastViewed = new();
    private readonly IPrototypeManager _prototypes;
    private readonly SpriteSystem _spriteSystem;
    private readonly Dictionary<string, Specimen[]> _extraModels = new();
    private string _selectedZone = string.Empty;
    private int _angle;

    public Wh40kAugmentCatalogue()
    {
        RobustXamlLoader.Load(this);
        var cache = IoCManager.Resolve<IResourceCache>();
        _prototypes = IoCManager.Resolve<IPrototypeManager>();
        _spriteSystem = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
        _sprites = cache.GetResource<RSIResource>(new ResPath(SpritePath)).RSI;
        Insignia.Texture = LoadInsignia(cache);
        _technicalFont = Wh40kOnboardingTypography.Technical(cache, 12);
        TerminalTitle.FontOverride = Wh40kOnboardingTypography.Display(cache, 25);
        Tier.FontOverride = _technicalFont;
        _zones = new Dictionary<string, Specimen[]>
        {
            ["head"] =
            [
                new("ironjaw", "jaw", "prosthetic", "WH40KAugmentIronJaw"),
                new("ironscull", "iron-skull", "mechanicus", "WH40KAugmentIronSkull"),
                new("sikariiscull", "skitarii", "mechanicus", "WH40KAugmentSkitariiSkull"),
            ],
            ["core"] =
            [
                new("headimplants", "neurochip", "internal", null),
                new("otherimplants", "service", "internal", null),
                new("mechanicusimplants", "controller", "mechanicus", null),
            ],
            ["left-eye"] = Eyes("left"),
            ["right-eye"] = Eyes("right"),
            ["left-arm"] = Limbs("left", "arm"),
            ["right-arm"] = Limbs("right", "arm"),
            ["left-leg"] = Limbs("left", "leg"),
            ["right-leg"] = Limbs("right", "leg"),
        };
        var catalogue = Wh40kAugmentInfo.Catalogue(_prototypes, IoCManager.Resolve<IComponentFactory>()).ToArray();
        foreach (var (zone, native) in _zones)
        {
            _extraModels[zone] = catalogue
                .Where(entry => Wh40kAugmentCatalog.IsInZone(entry.Zone, zone)
                    && !native.Any(model => model.Entity == entry.Prototype.ID))
                .OrderBy(entry => entry.Prototype.Name)
                .Select(entry => new Specimen(string.Empty, string.Empty, "internal", entry.Prototype.ID))
                .Distinct()
                .ToArray();
        }

        TerminalHeader.PanelOverride = Wh40kAugmentStyle.Panel(8);
        ScannerPanel.PanelOverride = Wh40kAugmentStyle.Panel(10);
        FacingPanel.PanelOverride = Wh40kAugmentStyle.Panel(3);
        InspectionPanel.PanelOverride = Wh40kAugmentStyle.Panel(12);
        IconPanel.PanelOverride = Wh40kAugmentStyle.Card(2);
        PairPanel.PanelOverride = Wh40kAugmentStyle.Card(9);
        Usage.SetMessage(Loc.GetString("wh40k-augments-preview"), Wh40kAugmentStyle.SecondaryText);

        BodyMap.ZoneSelected += zone => Select(zone, _lastViewed.GetValueOrDefault(zone) ?? _zones[zone][0]);
        TurnLeft.OnPressed += _ => Rotate(-1);
        TurnRight.OnPressed += _ => Rotate(1);
        OtherModels.OnItemSelected += args =>
        {
            if (_extraModels.TryGetValue(_selectedZone, out var models) && args.Id > 0 && args.Id <= models.Length)
                Select(_selectedZone, models[args.Id - 1]);
        };

        Rotate(0);
        Select("left-leg", _zones["left-leg"][1]);
    }

    private void Rotate(int delta)
    {
        _angle = (_angle + delta + Directions.Length) % Directions.Length;
        BodyMap.Facing = Directions[_angle];
        Angle.Text = Loc.GetString("wh40k-augments-facing-" + _angle);
    }

    private void Select(string zone, Specimen specimen)
    {
        var zoneChanged = _selectedZone != zone;
        _selectedZone = zone;
        _lastViewed[zone] = specimen;
        BodyMap.Select(zone, specimen.State);
        var zoneName = Loc.GetString("wh40k-augments-zone-" + zone);
        SelectedZone.Text = zoneName;
        Icon.Texture = GetIcon(specimen);
        Tier.Text = Loc.GetString("wh40k-augments-tier-" + specimen.Tier);
        var name = GetName(specimen);
        Title.SetMessage(FormattedMessage.FromMarkupPermissive($"[font size=19]{FormattedMessage.EscapeText(TitleCase(name))}[/font]"), Wh40kAugmentStyle.Text);
        Variants.DisposeAllChildren();
        foreach (var option in _zones[zone])
        {
            Variants.AddChild(Tile(
                option,
                Loc.GetString("wh40k-augments-variant-" + option.Variant),
                option == specimen,
                () => Select(zone, option)));
        }
        var extra = _extraModels[zone];
        if (zoneChanged)
        {
            OtherModels.Visible = extra.Length > 0;
            OtherModels.Clear();
            if (extra.Length > 0)
            {
                OtherModels.AddItem(Loc.GetString("wh40k-augment-info-more-models"), 0);
                OtherModels.SetItemDisabled(0, true);
                for (var index = 0; index < extra.Length; index++)
                    OtherModels.AddItem(GetName(extra[index]), index + 1);
            }
        }

        if (extra.Length > 0)
        {
            var modelIndex = Array.IndexOf(extra, specimen);
            OtherModels.SelectId(modelIndex + 1);
            OtherModels.ToolTip = modelIndex >= 0 ? name : null;
        }

        Effects.DisposeAllChildren();
        var playable = specimen.Entity is not null;
        var isEye = zone.EndsWith("-eye", StringComparison.Ordinal);
        var usesOperatingTable = specimen.State.Length == 0 || zone == "head";
        var installation = !playable
            ? Loc.GetString("wh40k-augments-in-development")
            : usesOperatingTable
                ? Loc.GetString("wh40k-augment-info-bed-install")
            : isEye
                ? Loc.GetString("wh40k-augments-install-eye")
                : Loc.GetString("wh40k-augments-install-limb", ("zone", zoneName));
        Installation.SetMessage(installation, Wh40kAugmentStyle.SecondaryText);
        EffectsTitle.Visible = playable;
        var isLeg = zone.EndsWith("-leg", StringComparison.Ordinal);
        if (usesOperatingTable && specimen.Entity != null && _prototypes.TryIndex<EntityPrototype>(specimen.Entity, out var prototype))
        {
            var details = new RichTextLabel { HorizontalExpand = true };
            details.SetMessage(Wh40kAugmentInfo.Describe(prototype), Wh40kAugmentStyle.Text);
            Effects.AddChild(details);
        }
        else if (specimen.Percent > 0)
        {
            AddEffect("protection", $"−{specimen.Percent}%");
            AddEffect(isLeg ? "movement" : "interaction", $"+{specimen.Percent}%");
            AddEffect(isLeg ? "terrain" : "pulling", $"−{specimen.Percent}%");
        }
        else if (playable)
        {
            AddEffect("health-icons", Loc.GetString("wh40k-augments-hud-value"));
            if (specimen.Variant == "archeotech")
                AddEffect("health-bars", Loc.GetString("wh40k-augments-hud-value"));
        }

        PairPanel.Visible = isLeg && specimen.Percent == 10;
        PairModules.DisposeAllChildren();
        if (!PairPanel.Visible)
            return;

        var other = zone == "left-leg" ? "right-leg" : "left-leg";
        var partner = _zones[other][1];
        PairModules.AddChild(Tile(specimen, Loc.GetString("wh40k-augments-zone-" + zone), true));
        PairModules.AddChild(new Label { Text = "+", FontColorOverride = Wh40kAugmentStyle.SecondaryText, VerticalAlignment = VAlignment.Center });
        PairModules.AddChild(Tile(partner, Loc.GetString("wh40k-augments-zone-" + other), false, () => Select(other, partner)));
        PairEffect.SetMessage(Loc.GetString("wh40k-augments-servo-step-effect"), Wh40kAugmentStyle.Text);
    }

    private void AddEffect(string effect, string value)
    {
        var band = new PanelContainer { PanelOverride = Wh40kAugmentStyle.Card(5) };
        var row = new BoxContainer { SeparationOverride = 9 };
        var amount = new Label
        {
            Text = value,
            MinWidth = 49,
            Align = Label.AlignMode.Center,
            VerticalAlignment = VAlignment.Center,
            FontColorOverride = Wh40kAugmentStyle.Text,
            FontOverride = _technicalFont,
        };
        var text = new RichTextLabel { HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        text.SetMessage(Loc.GetString("wh40k-augments-effect-" + effect), Wh40kAugmentStyle.Text);
        row.AddChild(amount);
        row.AddChild(text);
        band.AddChild(row);
        Effects.AddChild(band);
    }

    private Control Tile(Specimen specimen, string label, bool selected, Action? select = null)
    {
        var frame = Wh40kAugmentStyle.Card(3, selected);
        var row = new BoxContainer { SeparationOverride = 3, MouseFilter = MouseFilterMode.Ignore };
        row.AddChild(new TextureRect
        {
            Texture = GetIcon(specimen),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            SetSize = new Vector2(27),
            MouseFilter = MouseFilterMode.Ignore,
        });
        row.AddChild(new Label { Text = label, ClipText = true, HorizontalExpand = true, FontColorOverride = selected ? Wh40kAugmentStyle.Text : Wh40kAugmentStyle.SecondaryText });
        if (select is null)
        {
            var panel = new PanelContainer { HorizontalExpand = true, PanelOverride = frame };
            panel.AddChild(row);
            return panel;
        }

        var button = new ContainerButton { HorizontalExpand = true, StyleBoxOverride = frame, ToolTip = GetName(specimen) };
        button.AddChild(row);
        button.OnPressed += _ => select();
        return button;
    }

    private Texture GetIcon(Specimen specimen) => specimen.State.Length == 0 && specimen.Entity is { } entity
        ? _spriteSystem.GetPrototypeIcon(entity).Default
        : _sprites[specimen.State + "-icon"].GetFrame(RsiDirection.South, 0);

    private static Texture LoadInsignia(IResourceCache cache)
        => cache.GetResource<RSIResource>(new ResPath("/Textures/_WH40K/Structures/Decorations/banners.rsi"))
            .RSI["mechanicus"].GetFrame(RsiDirection.South, 0);

    private string GetName(Specimen specimen) => specimen.Entity is { } entity
        && _prototypes.TryIndex<EntityPrototype>(entity, out var prototype)
        ? prototype.Name
        : Loc.GetString("wh40k-augments-variant-" + specimen.Variant);

    private static Specimen[] Limbs(string side, string part)
    {
        var state = side + part;
        var name = TitleCase(side) + TitleCase(part);
        return
        [
            new("cheap" + state, "cheap", "basic", "WH40KProstheticCheap" + name, 5),
            new("adamantium" + state, "adamantium", "adamantium", "WH40KProstheticAdamantium" + name, 10),
            new("reinforcedadamantium" + state, "reinforced", "mechanicus", "WH40KProstheticReinforced" + name, 15),
        ];
    }

    private static Specimen[] Eyes(string side) =>
    [
        new("red" + side + "eye", "red", "optics", "WH40KCyberneticEyeRed" + TitleCase(side)),
        new("archeotek" + side + "eye", "archeotech", "optics", "WH40KCyberneticEyeArcheotech" + TitleCase(side)),
    ];

    private static string TitleCase(string text) => text.Length == 0 ? text : text[..1].ToUpperInvariant() + text[1..];

    private sealed record Specimen(string State, string Variant, string Tier, string? Entity, int Percent = 0);
}

public sealed class Wh40kAugmentCatalogueLayout : Container
{
    private const float Gap = 12;
    private const float MinimumRowWidth = 690;

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        var scanner = GetChild(0);
        var inspector = GetChild(1);
        var width = float.IsFinite(availableSize.X) ? availableSize.X : MinimumRowWidth;
        var sideBySide = width >= MinimumRowWidth;
        var scannerWidth = sideBySide ? (width - Gap) * .53f : width;
        var inspectorWidth = sideBySide ? width - scannerWidth - Gap : width;
        scanner.Measure(new Vector2(scannerWidth, availableSize.Y));
        inspector.Measure(new Vector2(inspectorWidth, availableSize.Y));
        var scannerHeight = scanner.DesiredSize.Y;
        var inspectorHeight = inspector.DesiredSize.Y;
        return new Vector2(width, sideBySide ? MathF.Max(scannerHeight, inspectorHeight) : scannerHeight + Gap + inspectorHeight);
    }

    protected override Vector2 ArrangeOverride(Vector2 finalSize)
    {
        var scanner = GetChild(0);
        var inspector = GetChild(1);
        var sideBySide = finalSize.X >= MinimumRowWidth;
        var scannerWidth = sideBySide ? (finalSize.X - Gap) * .53f : finalSize.X;
        var inspectorWidth = sideBySide ? finalSize.X - scannerWidth - Gap : finalSize.X;
        var inspectorPosition = sideBySide ? new Vector2(scannerWidth + Gap, 0) : new Vector2(0, scanner.DesiredSize.Y + Gap);
        scanner.Arrange(UIBox2.FromDimensions(Vector2.Zero, new Vector2(scannerWidth, scanner.DesiredSize.Y)));
        inspector.Arrange(UIBox2.FromDimensions(inspectorPosition, new Vector2(inspectorWidth, inspector.DesiredSize.Y)));
        return finalSize;
    }
}
