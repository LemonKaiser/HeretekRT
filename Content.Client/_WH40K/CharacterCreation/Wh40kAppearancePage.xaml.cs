            var portrait = new PortraitPresentation(
                prototype,
                displayIndex,
                card,
                button,
                choiceBadge,
                selectedMarker,
                choiceLabel,
                cardStyle,
                choiceBadgeStyle);
            _portraits.Add(portrait);

            button.OnMouseEntered += _ =>
            {
                portrait.Hovered = true;
                portrait.VisualDirty = true;
                OnPortraitHoverChanged?.Invoke(portrait.Prototype);
            };
            button.OnMouseExited += _ =>
            {
                portrait.Hovered = false;
                portrait.VisualDirty = true;
                OnPortraitHoverChanged?.Invoke(
                    _portraits.FirstOrDefault(candidate => candidate.Hovered)?.Prototype);
            };
            button.OnPressed += _ => SelectPortrait(portrait);

            PortraitGrid.AddChild(card);
            displayIndex++;
        }

        UpdatePortraitStyles();
    }

    /// <summary>
    /// Uses five fractional portrait columns. The old fixed-width
    /// cards gave the grid a 700px minimum and let it escape the onboarding frame.
    /// The grid now owns their width and this preserves the original portrait ratio.
    /// </summary>
    private void UpdatePortraitCardSizing()
    {
        var gridWidth = PortraitGrid.Width;
        if (gridWidth <= 0f)
            return;

        var cardWidth = MathF.Max(
            1f,
            (gridWidth - PortraitGridHorizontalSeparation * (PortraitGridColumns - 1)) / PortraitGridColumns);
        var cardHeight = MathF.Round(cardWidth * PortraitAspectRatio);

        foreach (var portrait in _portraits)
        {
            if (MathF.Abs(portrait.Card.SetWidth - cardWidth) < 0.5f &&
                MathF.Abs(portrait.Card.SetHeight - cardHeight) < 0.5f)
            {
                continue;
            }

            portrait.Card.SetSize = new Vector2(cardWidth, cardHeight);
        }
    }

    private void SelectPortrait(PortraitPresentation portrait)
    {
        if (_draft is null)
            return;

        if (_selectedPortraitId == portrait.Id)
        {
            _selectedPortraitId = null;
            _draft.ClearPortrait();
        }
        else
        {
            _selectedPortraitId = portrait.Id;
            _draft.SelectPortrait(portrait.Id);
        }

        UpdatePortraitStyles();
        OnDraftChanged?.Invoke(_draft);
    }

    private void UpdatePortraitStyles()
    {
        foreach (var portrait in _portraits)
        {
            var selected = _draft is not null && _selectedPortraitId == portrait.Id;
            if (portrait.Selected != selected)
            {
                portrait.Selected = selected;
                portrait.VisualDirty = true;
            }

            portrait.ChoiceLabel.Text = Loc.GetString(selected
                ? "heretek-onboarding-portrait-selected-badge"
                : "heretek-onboarding-portrait-choice");
            portrait.ChoiceLabel.FontColorOverride = selected ? Color.FromHex("#F5E1A0") : Color.FromHex("#DFD7C3");
            portrait.SelectedMarker.Visible = selected;
        }

        var selectedPortrait = _portraits.FirstOrDefault(portrait => portrait.Selected);
        SelectedPortraitLabel.Text = selectedPortrait is not null
            ? Loc.GetString(
                "heretek-onboarding-portrait-selected-number",
                ("number", selectedPortrait.DisplayIndex.ToString("D2")))
            : Loc.GetString("heretek-onboarding-portrait-select-prompt");
    }

    public void UpdatePortraitVisualEffects(float deltaSeconds, bool reducedMotion)
    {
        if (!IsPortraitSectionVisible)
            return;

        foreach (var portrait in _portraits)
        {
            var hovered = portrait.Button.IsHovered;
            if (portrait.Hovered != hovered)
            {
                portrait.Hovered = hovered;
                portrait.VisualDirty = true;
            }

            var previous = portrait.HoverAmount;
            var target = hovered || portrait.Selected ? 1f : 0f;
            portrait.HoverAmount = ApproachPresentation(previous, target, deltaSeconds, reducedMotion);
            if (portrait.HoverAmount == previous && !portrait.VisualDirty)
                continue;

            ApplyPortraitVisual(portrait);
        }
    }

    private static void ApplyPortraitVisual(PortraitPresentation portrait)
    {
        var emphasis = portrait.HoverAmount;
        var choiceAmount = portrait.Selected ? 1f : emphasis;

        portrait.CardStyle.BackgroundColor = LerpColor(
            Color.FromHex("#0D0E0B"),
            Color.FromHex("#483817"),
            emphasis);
        portrait.CardStyle.BorderColor = LerpColor(
            Color.FromHex("#B6975466"),
            Color.FromHex("#E5C879"),
            emphasis);
        portrait.Card.Margin = new Thickness(
            0f,
            -PortraitHoverLift * emphasis,
            0f,
            PortraitHoverLift * emphasis);

        portrait.ChoiceBadgeStyle.BackgroundColor = LerpColor(
            Color.FromHex("#080907E0"),
            Color.FromHex("#271F0DF2"),
            choiceAmount);
        portrait.ChoiceBadge.Modulate = Color.White.WithAlpha(choiceAmount);
        var badgeOffset = 10f * (1f - choiceAmount);
        LayoutContainer.SetMarginTop(
            portrait.ChoiceBadge,
            -PortraitChoiceBadgeHeight + badgeOffset);
        LayoutContainer.SetMarginBottom(portrait.ChoiceBadge, badgeOffset);
        portrait.VisualDirty = false;
    }

    private static float ApproachPresentation(float value, float target, float deltaSeconds, bool reducedMotion)
    {
        if (reducedMotion)
            return target;

        var speed = Math.Clamp(deltaSeconds / 0.16f, 0f, 1f);
        var approached = value + (target - value) * speed;
        return MathF.Abs(approached - target) <= 0.002f ? target : approached;
    }

    private static Color LerpColor(Color from, Color to, float progress)
    {
        progress = Math.Clamp(progress, 0f, 1f);
        return new Color(
            from.R + (to.R - from.R) * progress,
            from.G + (to.G - from.G) * progress,
            from.B + (to.B - from.B) * progress,
            from.A + (to.A - from.A) * progress);
    }

    private sealed class PortraitPresentation
    {
        public Wh40kPortraitPrototype Prototype { get; }
        public string Id => Prototype.ID;
        public int DisplayIndex { get; }
        public PanelContainer Card { get; }
        public TextureButton Button { get; }
        public PanelContainer ChoiceBadge { get; }
        public TextureRect SelectedMarker { get; }
        public Label ChoiceLabel { get; }
        public StyleBoxFlat CardStyle { get; }
        public StyleBoxFlat ChoiceBadgeStyle { get; }
        public bool Hovered { get; set; }
        public bool Selected { get; set; }
        public float HoverAmount { get; set; }
        public bool VisualDirty { get; set; } = true;

        public PortraitPresentation(
            Wh40kPortraitPrototype prototype,
            int displayIndex,
            PanelContainer card,
            TextureButton button,
            PanelContainer choiceBadge,
            TextureRect selectedMarker,
            Label choiceLabel,
            StyleBoxFlat cardStyle,
            StyleBoxFlat choiceBadgeStyle)
        {
            Prototype = prototype;
            DisplayIndex = displayIndex;
            Card = card;
            Button = button;
            ChoiceBadge = choiceBadge;
            SelectedMarker = selectedMarker;
            ChoiceLabel = choiceLabel;
            CardStyle = cardStyle;
            ChoiceBadgeStyle = choiceBadgeStyle;
        }
    }
}

