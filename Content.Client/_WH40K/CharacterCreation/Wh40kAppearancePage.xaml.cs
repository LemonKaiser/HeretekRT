        }
    }

    private static StyleBoxFlat CreateOnboardingFieldStyle(string background, string border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex(background),
            BorderColor = Color.FromHex(border),
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 9,
            ContentMarginRightOverride = 9,
            ContentMarginTopOverride = 6,
            ContentMarginBottomOverride = 6,
        };
    }

    public void SetDraft(Wh40kOnboardingDraft draft)
    {
        if (_portraits.Count == 0)
            CreatePortraitsFromPrototypes();

        _draft = draft;
        if (draft.PortraitId is { } portraitId &&
            !_portraits.Any(portrait => portrait.Id == portraitId))
        {
            draft.ClearPortrait();
        }

        _selectedPortraitId = draft.PortraitId;
        // MarkingPicker queries MarkingManager in this setter. Setting it from XAML happens while the
        // lobby screen is constructed, before MarkingManager has cached prototypes.
        AppearanceMarkings.IgnoreCategories = "Hair,FacialHair";
        _loadingControls = true;
        RefreshAllControls();
        _loadingControls = false;
        UpdatePortraitStyles();
    }

    public void ClearDraft()
    {
        _draft = null;
        _selectedPortraitId = null;
        OnPortraitHoverChanged?.Invoke(null);
        UpdatePortraitStyles();
    }

    public void SelectSection(Wh40kAppearanceSection section)
    {
        PortraitsSection.Visible = section == Wh40kAppearanceSection.Portraits;
        BasicsSection.Visible = section == Wh40kAppearanceSection.Basics;
        HairSection.Visible = section == Wh40kAppearanceSection.Hair;
        EyesSection.Visible = section == Wh40kAppearanceSection.Eyes;
        MarkingsSection.Visible = section == Wh40kAppearanceSection.Markings;
        FlavorTextSection.Visible = section == Wh40kAppearanceSection.FlavorText &&
                                    _cfg.GetCVar(CCVars.FlavorText);
    }

    private void RefreshAllControls()
    {
        if (_draft is null)
            return;

        RefreshSpecies();
        UpdateSexControls();
        PronounsButton.SelectId((int) _draft.Profile.Gender);
        SpawnPriorityButton.SelectId((int) _draft.Profile.SpawnPriority);
        ShowClothesButton.Pressed = _draft.ShowClothes;
        AgeEdit.Text = _draft.Profile.Age.ToString();
        HeightSlider.Value = _draft.Profile.Appearance.Height;
        WidthSlider.Value = _draft.Profile.Appearance.Width;
        UpdateSkinColorControls();
        UpdateEyeControls();
        UpdateHairPickers();
        UpdateMarkings();
        OnboardingFlavorText.CFlavorTextInput.TextRope = new Rope.Leaf(_draft.Profile.FlavorText);
        UpdateFlavorTextCharacterCount();
    }

    private void UpdateFlavorTextCharacterCount()
    {
        OnboardingFlavorTextCount.Text = $"{OnboardingFlavorText.CFlavorTextInput.TextLength} / {FlavorTextMaxLength}";
    }

    private void RefreshSpecies()
    {
        SpeciesButton.Clear();
        _species.Clear();
        _species.AddRange(_prototypeManager
            .EnumeratePrototypes<SpeciesPrototype>()
            .Where(species => species.RoundStart && !HiddenOnboardingSpecies.Contains(species.ID)));

        for (var index = 0; index < _species.Count; index++)
        {
            SpeciesButton.AddItem(Loc.GetString(_species[index].Name), index);
            if (_draft?.Profile.Species == _species[index].ID)
                SpeciesButton.SelectId(index);
        }
    }

    private void UpdateSexControls()
    {
        if (_draft is null)
            return;

        SexButton.Clear();
        IEnumerable<Sex> sexes = _prototypeManager.TryIndex<SpeciesPrototype>(_draft.Profile.Species, out var species)
            ? species.Sexes
            : new[] { Sex.Unsexed };

        foreach (var sex in sexes)
        {
            SexButton.AddItem(Loc.GetString($"humanoid-profile-editor-sex-{sex.ToString().ToLower()}-text"), (int) sex);
        }

        SexButton.SelectId((int) _draft.Profile.Sex);
    }

    private void UpdateSkinColorControls()
    {
        if (_draft is null || !_prototypeManager.TryIndex<SpeciesPrototype>(_draft.Profile.Species, out var species))
            return;

        var skinColor = _draft.Profile.Appearance.SkinColor;
        switch (species.SkinColoration)
        {
            case HumanoidSkinColor.HumanToned:
                SkinToneSlider.Visible = true;
                RgbSkinColorContainer.Visible = false;
                SkinToneSlider.Value = SkinColor.HumanSkinToneFromColor(skinColor);
                break;
            case HumanoidSkinColor.AnimalFur:
                SkinToneSlider.Visible = false;
                RgbSkinColorContainer.Visible = true;
                _rgbSkinColorSelector.Color = SkinColor.ClosestAnimalFurColor(skinColor);
                break;
            case HumanoidSkinColor.Hues:
            case HumanoidSkinColor.TintedHues:
                SkinToneSlider.Visible = false;
                RgbSkinColorContainer.Visible = true;
                _rgbSkinColorSelector.Color = skinColor;
                break;
            case HumanoidSkinColor.VoxFeathers:
                SkinToneSlider.Visible = false;
                RgbSkinColorContainer.Visible = true;
                _rgbSkinColorSelector.Color = SkinColor.ClosestVoxColor(skinColor);
                break;
        }
    }

    private void UpdateEyeControls()
    {
        if (_draft is null)
            return;

        EyeColorPicker.SetData(_draft.Profile.Appearance.EyeColor);
        AppearanceMarkings.SetEyeColor(_draft.Profile.Appearance.EyeColor);
    }

    private void UpdateHairPickers()
    {
        if (_draft is null)
            return;

        var appearance = _draft.Profile.Appearance;
        var hair = appearance.HairStyleId == HairStyles.DefaultHairStyle
            ? new List<Marking>()
            : new List<Marking> { new(appearance.HairStyleId, new List<Color> { appearance.HairColor }) };
        var facialHair = appearance.FacialHairStyleId == HairStyles.DefaultFacialHairStyle
            ? new List<Marking>()
            : new List<Marking> { new(appearance.FacialHairStyleId, new List<Color> { appearance.FacialHairColor }) };

        HairStylePicker.UpdateData(hair, _draft.Profile.Species, 1);
        FacialHairPicker.UpdateData(facialHair, _draft.Profile.Species, 1);
    }

    private void UpdateMarkings()
    {
        if (_draft is null)
            return;

        var profile = _draft.Profile;
        AppearanceMarkings.SetData(
            profile.Appearance.Markings,
            profile.Species,
            profile.Sex,
            profile.Appearance.SkinColor,
            profile.Appearance.EyeColor);

        AppearanceMarkings.HairMarking = profile.Appearance.HairStyleId == HairStyles.DefaultHairStyle
            ? null
            : new Marking(profile.Appearance.HairStyleId, new List<Color> { profile.Appearance.HairColor });
        AppearanceMarkings.FacialHairMarking = profile.Appearance.FacialHairStyleId == HairStyles.DefaultFacialHairStyle
            ? null
            : new Marking(profile.Appearance.FacialHairStyleId, new List<Color> { profile.Appearance.FacialHairColor });
    }

    private void SetAge(int age)
    {
        UpdateProfile(profile => profile.WithAge(age));
    }

    private void SetSpecies(string species)
    {
        if (!_prototypeManager.TryIndex<SpeciesPrototype>(species, out var speciesPrototype))
            return;

        UpdateProfile(profile => NormalizeProfileForSpecies(profile, speciesPrototype, profile.Sex));
        _loadingControls = true;
        UpdateSexControls();
        AgeEdit.Text = _draft!.Profile.Age.ToString();
        UpdateSkinColorControls();
        UpdateHairPickers();
        UpdateMarkings();
        _loadingControls = false;
    }

    private void SetSex(Sex sex)
    {
        UpdateProfile(profile =>
        {
            var updated = profile.WithSex(sex);
            updated = sex switch
            {
                Sex.Male => updated.WithGender(Gender.Male),
                Sex.Female => updated.WithGender(Gender.Female),
                _ => updated.WithGender(Gender.Epicene),
            };

            return _prototypeManager.TryIndex<SpeciesPrototype>(updated.Species, out var species)
                ? NormalizeProfileForSpecies(updated, species, sex)
                : updated;
        });

        _loadingControls = true;
        PronounsButton.SelectId((int) _draft!.Profile.Gender);
        UpdateHairPickers();
        UpdateMarkings();
        _loadingControls = false;
    }

    /// <summary>
    ///     Applies the same profile constraints that the shared character validator applies before save,
    ///     so the onboarding controls and preview never retain values that the selected species cannot use.
    /// </summary>
    private HumanoidCharacterProfile NormalizeProfileForSpecies(
        HumanoidCharacterProfile profile,
        SpeciesPrototype species,
        Sex requestedSex)
    {
        var sex = species.Sexes.Contains(requestedSex)
            ? requestedSex
            : species.Sexes.Count > 0
                ? species.Sexes[0]
                : Sex.Unsexed;

        var appearance = HumanoidCharacterAppearance.EnsureValid(profile.Appearance, species.ID, sex);
        var supportedHair = _markingManager.MarkingsByCategoryAndSpeciesAndSex(
            MarkingCategories.Hair,
            species.ID,
            sex);
        var supportedFacialHair = _markingManager.MarkingsByCategoryAndSpeciesAndSex(
            MarkingCategories.FacialHair,
            species.ID,
            sex);

        if (!supportedHair.ContainsKey(appearance.HairStyleId))
            appearance = appearance.WithHairStyleName(HairStyles.DefaultHairStyle);

        if (!supportedFacialHair.ContainsKey(appearance.FacialHairStyleId))
            appearance = appearance.WithFacialHairStyleName(HairStyles.DefaultFacialHairStyle);

        return profile
            .WithSpecies(species.ID)
            .WithSex(sex)
            .WithAge(Math.Clamp(profile.Age, species.MinAge, species.MaxAge))
            .WithCharacterAppearance(appearance);
    }

    private void SetGender(Gender gender)
    {
        UpdateProfile(profile => profile.WithGender(gender));
    }

    private void SetSpawnPriority(SpawnPriorityPreference priority)
    {
        UpdateProfile(profile => profile.WithSpawnPriorityPreference(priority));
    }

    private void SetHeight(float height)
    {
        if (_loadingControls)
            return;

        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithHeight(height)));
    }

    private void SetWidth(float width)
    {
        if (_loadingControls)
            return;

        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithWidth(width)));
    }

    private void UpdateSkinColorFromControls()
    {
        if (_loadingControls || _draft is null ||
            !_prototypeManager.TryIndex<SpeciesPrototype>(_draft.Profile.Species, out var species))
            return;

        var color = species.SkinColoration switch
        {
            HumanoidSkinColor.HumanToned => SkinColor.HumanSkinTone((int) SkinToneSlider.Value),
            HumanoidSkinColor.AnimalFur => SkinColor.ClosestAnimalFurColor(_rgbSkinColorSelector.Color),
            HumanoidSkinColor.Hues => _rgbSkinColorSelector.Color,
            HumanoidSkinColor.TintedHues => SkinColor.TintedHues(_rgbSkinColorSelector.Color),
            HumanoidSkinColor.VoxFeathers => SkinColor.ClosestVoxColor(_rgbSkinColorSelector.Color),
            _ => _draft.Profile.Appearance.SkinColor,
        };

        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithSkinColor(color)));
        AppearanceMarkings.SetSkinColor(color);
    }

    private void SetHairStyle(string style)
    {
        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithHairStyleName(style)));
        UpdateMarkings();
    }

    private void SetHairColor(Color color)
    {
        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithHairColor(color)));
        UpdateMarkings();
    }

    private void SetFacialHairStyle(string style)
    {
        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithFacialHairStyleName(style)));
        UpdateMarkings();
    }

    private void SetFacialHairColor(Color color)
    {
        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithFacialHairColor(color)));
        UpdateMarkings();
    }

    private void AddHair()
    {
        if (_draft is null)
            return;

        var style = _markingManager.MarkingsByCategoryAndSpecies(MarkingCategories.Hair, _draft.Profile.Species)
            .Keys.FirstOrDefault();
        if (!string.IsNullOrEmpty(style))
            SetHairStyle(style);

        UpdateHairPickers();
    }

    private void AddFacialHair()
    {
        if (_draft is null)
            return;

        var style = _markingManager.MarkingsByCategoryAndSpecies(MarkingCategories.FacialHair, _draft.Profile.Species)
            .Keys.FirstOrDefault();
        if (!string.IsNullOrEmpty(style))
            SetFacialHairStyle(style);

        UpdateHairPickers();
    }

    private void RemoveHair()
    {
        SetHairStyle(HairStyles.DefaultHairStyle);
        UpdateHairPickers();
    }

    private void RemoveFacialHair()
    {
        SetFacialHairStyle(HairStyles.DefaultFacialHairStyle);
        UpdateHairPickers();
    }

    private void SetEyeColor(Color color)
    {
        if (_loadingControls)
            return;

        UpdateProfile(profile => profile.WithCharacterAppearance(profile.Appearance.WithEyeColor(color)));
        AppearanceMarkings.SetEyeColor(color);
    }

    private void SetMarkings(MarkingSet markings)
    {
        UpdateProfile(profile => profile.WithCharacterAppearance(
            profile.Appearance.WithMarkings(markings.GetForwardEnumerator().ToList())));
    }

    private void UpdateProfile(Func<HumanoidCharacterProfile, HumanoidCharacterProfile> update)
    {
        if (_loadingControls || _draft is null)
            return;

        _draft.UpdateProfile(update(_draft.Profile));
        NotifyDraftChanged();
    }

    private void NotifyDraftChanged()
    {
        if (_draft is not null)
            OnDraftChanged?.Invoke(_draft);
    }

