    public Wh40kAppearancePage()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ApplyOnboardingControlTheme();

        FlavorNote.Text = Loc.GetString("heretek-onboarding-appearance-flavor-note");

        RgbSkinColorContainer.AddChild(_rgbSkinColorSelector = new ColorSelectorSliders
        {
            SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv,
            HorizontalExpand = true,
        });

        _rgbSkinColorSelector.OnColorChanged += _ => UpdateSkinColorFromControls();
        SkinToneSlider.OnValueChanged += _ => UpdateSkinColorFromControls();
        HeightSlider.OnValueChanged += _ => SetHeight(HeightSlider.Value);
        WidthSlider.OnValueChanged += _ => SetWidth(WidthSlider.Value);

        AgeEdit.OnTextChanged += args =>
        {
            if (!_loadingControls && int.TryParse(args.Text, out var age))
                SetAge(age);
        };

        SpeciesButton.OnItemSelected += args =>
        {
            SpeciesButton.SelectId(args.Id);
            if (!_loadingControls && args.Id >= 0 && args.Id < _species.Count)
                SetSpecies(_species[args.Id].ID);
        };

        SexButton.OnItemSelected += args =>
        {
            SexButton.SelectId(args.Id);
            if (!_loadingControls)
                SetSex((Sex) args.Id);
        };

        PronounsButton.AddItem(Loc.GetString("humanoid-profile-editor-pronouns-male-text"), (int) Gender.Male);
        PronounsButton.AddItem(Loc.GetString("humanoid-profile-editor-pronouns-female-text"), (int) Gender.Female);
        PronounsButton.AddItem(Loc.GetString("humanoid-profile-editor-pronouns-epicene-text"), (int) Gender.Epicene);
        PronounsButton.AddItem(Loc.GetString("humanoid-profile-editor-pronouns-neuter-text"), (int) Gender.Neuter);
        PronounsButton.OnItemSelected += args =>
        {
            PronounsButton.SelectId(args.Id);
            if (!_loadingControls)
                SetGender((Gender) args.Id);
        };

        foreach (var priority in Enum.GetValues<SpawnPriorityPreference>())
        {
            SpawnPriorityButton.AddItem(
                Loc.GetString($"humanoid-profile-editor-preference-spawn-priority-{priority.ToString().ToLower()}"),
                (int) priority);
        }

        SpawnPriorityButton.OnItemSelected += args =>
        {
            SpawnPriorityButton.SelectId(args.Id);
            if (!_loadingControls)
                SetSpawnPriority((SpawnPriorityPreference) args.Id);
        };

        ShowClothesButton.OnToggled += args =>
        {
            if (_loadingControls || _draft is null)
                return;

            _draft.ShowClothes = args.Pressed;
            NotifyDraftChanged();
        };

        HairStylePicker.OnMarkingSelect += marking => SetHairStyle(marking.id);
        HairStylePicker.OnColorChanged += marking => SetHairColor(marking.marking.MarkingColors[0]);
        HairStylePicker.OnSlotRemove += _ => RemoveHair();
        HairStylePicker.OnSlotAdd += AddHair;

        FacialHairPicker.OnMarkingSelect += marking => SetFacialHairStyle(marking.id);
        FacialHairPicker.OnColorChanged += marking => SetFacialHairColor(marking.marking.MarkingColors[0]);
        FacialHairPicker.OnSlotRemove += _ => RemoveFacialHair();
        FacialHairPicker.OnSlotAdd += AddFacialHair;

        EyeColorPicker.OnEyeColorPicked += SetEyeColor;
        AppearanceMarkings.OnMarkingAdded += SetMarkings;
        AppearanceMarkings.OnMarkingRemoved += SetMarkings;
        AppearanceMarkings.OnMarkingColorChange += SetMarkings;
        AppearanceMarkings.OnMarkingRankChange += SetMarkings;
        OnboardingFlavorText.OnFlavorTextChanged += flavorText =>
        {
            if (flavorText.Length > FlavorTextMaxLength)
            {
                OnboardingFlavorText.CFlavorTextInput.TextRope = new Rope.Leaf(flavorText[..FlavorTextMaxLength]);
                return;
            }

            if (!_loadingControls)
                UpdateProfile(profile => profile.WithFlavorText(flavorText));
        };
        OnboardingFlavorText.CFlavorTextInput.OnTextChanged += _ => UpdateFlavorTextCharacterCount();
        UpdateFlavorTextCharacterCount();
        FlavorTextSection.Visible = false;

        PortraitGrid.OnResized += UpdatePortraitCardSizing;

        RefreshSpecies();
        SelectSection(Wh40kAppearanceSection.Portraits);
    }

