using Robust.Shared.Timing;

namespace Content.Client._WH40K.Economy;

[GenerateTypedNameReferences]
public sealed partial class MaterialMarketPanel : BoxContainer
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IResourceCache _resources = default!;
    private static readonly Color Rising = Color.FromHex("#9ed1aa");
    private static readonly Color Falling = Color.FromHex("#ea9393");
    private static readonly Color Neutral = Color.FromHex("#a9b6c3");
    private static readonly Color Gold = Color.FromHex("#ddc389");
    private readonly Font _bodyFont;
    private readonly Font _smallFont;
    private readonly Font _headingFont;
    private readonly StyleBoxFlat _sellStyle = new() { BackgroundColor = Color.FromHex("#46513e"),
        ContentMarginTopOverride = 8, ContentMarginBottomOverride = 8 };
    private readonly StyleBoxFlat _disabledStyle = new() { BackgroundColor = Color.FromHex("#30343a"),
        ContentMarginTopOverride = 8, ContentMarginBottomOverride = 8 };
    private readonly List<MarketRow> _rows = new();
    private TimeSpan _cycleAt;
    private bool _cycles;
    private bool _canSell;
    private bool _pending;
    private int _displayedSeconds = -2;

    public event Action? SellRequested;

    public MaterialMarketPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _bodyFont = _resources.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 11);
        _smallFont = _resources.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 9);
        _headingFont = _resources.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        ApplyTypography(this);
        NetLabel.FontOverride = _resources.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 28);
        SellButton.Label.FontOverride = _headingFont;
        SellButton.ModulateSelfOverride = Color.White;
        SaleBackground.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#25272b") };
        MarketBackground.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#1c1f23") };
        ShowAllCheckBox.OnToggled += _ => UpdateVisibleRows();
        SellButton.OnPressed += _ =>
        {
            _pending = true;
            UpdateSellButton();
            SellRequested?.Invoke();
        };
    }

    public void UpdateState(CargoPalletConsoleInterfaceState state)
    {
        _pending = false;
        _cycles = state.MarketDemandCycles;
        _cycleAt = _timing.CurTime + TimeSpan.FromSeconds(state.MarketCycleSeconds);
        _canSell = state.Enabled && state.Appraisal > 0 && state.Count > 0;
        TerminalLabel.Text = $"×{state.OtherMultiplier:0.00}";
        GoodsLabel.Text = state.Count > 0 ? Loc.GetString("wh40k-market-goods", ("count", state.Count)) :
            Loc.GetString("wh40k-market-cargo-empty");
        GrossLabel.Text = Money(state.MarketBeforeCoefficient);
        CoefficientTitle.Text = Loc.GetString("wh40k-market-coefficient", ("coefficient", state.OtherMultiplier.ToString("0.00")));
        var adjustment = state.MarketGross - state.MarketBeforeCoefficient;
        CoefficientLabel.Text = (adjustment > 0 ? "+" : adjustment < 0 ? "−" : "") + Money(Math.Abs(adjustment));
        FeesLabel.Text = (state.MarketTax > 0 ? "−" : "") + Money(state.MarketTax);
        NetLabel.Text = Money(state.Appraisal);
        NetLabel.ToolTip = NetLabel.Text;
        SellButton.Text = state.Appraisal > 0
            ? Loc.GetString("wh40k-market-sell-amount", ("amount", Money(state.Appraisal)))
            : Loc.GetString("wh40k-market-sell-empty");
        SpecialLabel.Visible = state.MarketSpecial > 0;
        SpecialLabel.Text = Loc.GetString("wh40k-market-special", ("amount", Money(state.MarketSpecial)));

        if (_rows.Count != state.MarketEntries.Count)
        {
            Entries.DisposeAllChildren();
            _rows.Clear();
            foreach (var _ in state.MarketEntries)
            {
                var row = new MarketRow(_prototypes, _entities.System<SpriteSystem>(), _bodyFont, _smallFont);
                _rows.Add(row);
                Entries.AddChild(row);
            }
        }
        var entries = state.MarketEntries.OrderByDescending(entry => Math.Round((entry.Factor - 1) * 100) > 0)
            .ThenBy(entry => Math.Round((entry.Factor - 1) * 100) < 0 ? 0 : 1)
            .ThenBy(entry => entry.Material, StringComparer.Ordinal).ToArray();
        for (var i = 0; i < _rows.Count; i++)
            _rows[i].Update(entries[i]);
        UpdateVisibleRows();
        _displayedSeconds = -2;
        UpdateCountdown();
    }

    public void ShowSaleResult(MaterialMarketSaleResultMessage result)
    {
        _pending = false;
        ReceiptLabel.Visible = true;
        ReceiptLabel.SetMessage(result.Success
            ? Loc.GetString("wh40k-market-receipt", ("count", result.Count),
                ("amount", Money(result.Amount)))
            : Loc.GetString(string.IsNullOrEmpty(result.Reason) ? "wh40k-market-unavailable" : result.Reason),
            result.Success ? Rising : Neutral);
        ReceiptLabel.ToolTip = result.Success ? Loc.GetString("wh40k-market-sale-tax",
            ("amount", Money(result.Fees))) : null;
        UpdateSellButton();
    }

    private void ApplyTypography(Control control)
    {
        if (control is Label label)
        {
            var heading = label.HasStyleClass("LabelHeading");
            var small = label.HasStyleClass("LabelSubText");
            label.FontOverride = heading ? _headingFont : small ? _smallFont : _bodyFont;
            label.FontColorOverride ??= heading ? Gold : small ? Neutral : Color.FromHex("#e7e9ed");
        }
        if (control is RichTextLabel)
            control.Stylesheet = new Stylesheet(new[]
            {
                new StyleRule(new SelectorElement(typeof(RichTextLabel), null, null, null),
                    new[] { new StyleProperty("font", _bodyFont) }),
            });
        foreach (var child in control.Children)
            ApplyTypography(child);
    }

    private void UpdateSellButton()
    {
        SellButton.Disabled = !_canSell || _pending;
        SellButton.StyleBoxOverride = SellButton.Disabled ? _disabledStyle : _sellStyle;
    }

    private static string Money(int amount) => Loc.GetString("wh40k-market-price-value", ("price", amount.ToString("N0")));

    private void UpdateVisibleRows()
    {
        var any = false;
        foreach (var row in _rows)
        {
            row.Visible = ShowAllCheckBox.Pressed || row.HasChange;
            any |= row.Visible;
        }
        QuietLabel.Visible = !any;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCountdown();
    }

    private void UpdateCountdown()
    {
        var seconds = _cycles ? Math.Max(0, (int) Math.Ceiling((_cycleAt - _timing.CurTime).TotalSeconds)) : -1;
        if (seconds == _displayedSeconds)
            return;
        _displayedSeconds = seconds;
        CycleLabel.Text = seconds < 0 ? Loc.GetString("wh40k-market-cycle-disabled") : seconds == 0
            ? Loc.GetString("wh40k-market-cycle-refreshing")
            : Loc.GetString("wh40k-market-cycle", ("time", $"{seconds / 60:00}:{seconds % 60:00}"));
        UpdateSellButton();
    }

    private static string Signed(int value) => value > 0 ? $"+{value}" : value.ToString();

    private sealed class MarketRow : PanelContainer
    {
        private readonly IPrototypeManager _prototypes;
        private readonly SpriteSystem _sprites;
        private readonly TextureRect _icon = new() { MinSize = new Vector2(32, 32), MaxSize = new Vector2(32, 32),
            Stretch = TextureRect.StretchMode.KeepAspectCentered, VerticalAlignment = VAlignment.Center };
        private readonly Label _name = new() { HorizontalExpand = true, ClipText = true };
        private readonly Label _unit = new() { HorizontalExpand = true, ClipText = true, FontColorOverride = Neutral };
        private readonly Label _price = new() { MinWidth = 84, MaxWidth = 84, ClipText = true, Align = Label.AlignMode.Right };
        private readonly Label _demand = new() { MinWidth = 78, MaxWidth = 78, Align = Label.AlignMode.Right };
        private string? _material;
        public bool HasChange { get; private set; }

        public MarketRow(IPrototypeManager prototypes, SpriteSystem sprites, Font bodyFont, Font smallFont)
        {
            _prototypes = prototypes;
            _sprites = sprites;
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.Transparent,
                BorderColor = Color.FromHex("#2b3036"), BorderThickness = new Thickness(0, 0, 0, 1),
                ContentMarginTopOverride = 8, ContentMarginBottomOverride = 8 };
            var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 12 };
            var material = new BoxContainer { Orientation = LayoutOrientation.Horizontal, MinWidth = 128,
                HorizontalExpand = true, SeparationOverride = 8 };
            var names = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 0 };
            _name.FontOverride = _price.FontOverride = _demand.FontOverride = bodyFont;
            _unit.FontOverride = smallFont;
            var tile = new PanelContainer { PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#282d34"),
                ContentMarginLeftOverride = 2, ContentMarginRightOverride = 2,
                ContentMarginTopOverride = 2, ContentMarginBottomOverride = 2 }, VerticalAlignment = VAlignment.Center };
            tile.AddChild(_icon);
            names.AddChild(_name);
            names.AddChild(_unit);
            material.AddChild(tile);
            material.AddChild(names);
            row.AddChild(material);
            row.AddChild(_price);
            row.AddChild(_demand);
            AddChild(row);
        }

        public void Update(MaterialMarketEntry entry)
        {
            var name = Loc.GetString(entry.Name);
            _name.Text = string.IsNullOrEmpty(name) ? name : string.Concat(char.ToUpper(name[0], CultureInfo.CurrentCulture).ToString(), name[1..]);
            _name.ToolTip = _name.Text;
            _unit.Text = Loc.GetString(entry.Unit switch
            {
                "materials-unit-sheet" => "wh40k-market-unit-sheet",
                "materials-unit-bar" => "wh40k-market-unit-bar",
                "materials-unit-plank" => "wh40k-market-unit-plank",
                "materials-unit-roll" => "wh40k-market-unit-roll",
                "materials-unit-piece" => "wh40k-market-unit-piece",
                _ => entry.Unit,
            });
            if (_material != entry.Material)
            {
                _material = entry.Material;
                _icon.Texture = _prototypes.TryIndex<MaterialPrototype>(entry.Material, out var material)
                    ? _sprites.Frame0(material.Icon) : null;
            }
            var change = (int) Math.Round((entry.Factor - 1) * 100);
            HasChange = change != 0 || entry.Demand != 1;
            _demand.Text = change == 0 ? Loc.GetString("wh40k-market-demand-normal") :
                Loc.GetString("wh40k-market-demand-change", ("direction", change > 0 ? "↑" : "↓"), ("change", Signed(change)));
            _demand.FontColorOverride = change > 0 ? Rising : change < 0 ? Falling : Neutral;
            _price.Text = Loc.GetString("wh40k-market-price-value", ("price", entry.UnitPrice.ToString("N2")));
            _price.ToolTip = _price.Text;
            ToolTip = Loc.GetString("wh40k-market-entry-hint", ("material", _name.Text),
                ("event", Signed((int) Math.Round((entry.Demand - 1) * 100))));
        }
    }
}
