namespace Content.Client._WH40K.FactionStorage;

[GenerateTypedNameReferences]
public sealed partial class FactionDepotPanel : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPlayerManager _players = default!;
    [Dependency] private IGameTiming _timing = default!;

    private static readonly Color Gold = Color.FromHex("#c4a269");
    private static readonly Color Muted = Color.FromHex("#7d8b96");
    private readonly List<DepotCell> _cells = new();
    private readonly string[] _searchNames = new string[FactionStorageComponent.Capacity];
    private FactionDepotState? _state;
    private TimeSpan _localRequestUntil;
    private bool? _buttonsDisabled;
    private FactionDepotStatus? _displayedStatus;
    private int _displayedCooldown = -1;
    public event Action<int, Guid, bool>? Transfer;
    public event Action? Refresh;

    public FactionDepotPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        HeaderPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#141b21"), BorderColor = Color.FromHex("#655337"),
            BorderThickness = new Thickness(1, 3, 1, 1),
            ContentMarginLeftOverride = 12, ContentMarginRightOverride = 12,
            ContentMarginTopOverride = 10, ContentMarginBottomOverride = 10,
        };
        CapacityBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#0b1014") };
        CapacityBar.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Gold };
        RefreshButton.OnPressed += _ =>
        {
            if (TryRequest(refresh: true))
                Refresh?.Invoke();
        };
        SearchInput.OnTextChanged += _ => FilterCells();
        OccupiedOnly.OnToggled += _ => FilterCells();
        for (var i = 0; i < FactionStorageComponent.Capacity; i++)
        {
            var slot = i;
            var cell = new DepotCell(i);
            cell.OnPressed += _ =>
            {
                if (_state is not { Status: FactionDepotStatus.Ready } state || slot >= state.Slots.Length || !TryRequest())
                    return;
                var entry = state.Slots[slot];
                Transfer?.Invoke(entry.Index, entry.Revision, entry.Prototype == null);
            };
            _cells.Add(cell);
            Slots.AddChild(cell);
        }
    }

    public void Apply(FactionDepotState state)
    {
        var previous = _state;
        _state = state;
        UpdateInteraction();
        if (previous != null && previous.Faction == state.Faction && previous.Slots.SequenceEqual(state.Slots))
            return;
        FactionLabel.Text = _prototypes.TryIndex<CompanyPrototype>(state.Faction, out var company) ? company.Name : state.Faction;
        var used = state.Slots.Count(slot => slot.Prototype != null);
        CapacityLabel.Text = Loc.GetString("wh40k-faction-storage-capacity", ("used", used), ("capacity", FactionStorageComponent.Capacity));
        FreeLabel.Text = Loc.GetString("wh40k-faction-storage-free", ("count", FactionStorageComponent.Capacity - used));
        CapacityBar.Value = used;
        var sprites = _entities.System<SpriteSystem>();
        for (var i = 0; i < _cells.Count; i++)
        {
            var cell = _cells[i];
            if (previous != null && i < previous.Slots.Length && i < state.Slots.Length && previous.Slots[i] == state.Slots[i])
                continue;
            if (i >= state.Slots.Length)
            {
                cell.SetItem(null, 0, false);
                _searchNames[i] = string.Empty;
                continue;
            }
            var entry = state.Slots[i];
            EntityPrototype? prototype = null;
            if (entry.Prototype != null)
                _prototypes.TryIndex(entry.Prototype, out prototype);
            cell.SetItem(prototype == null ? null : sprites.GetPrototypeIcon(prototype.ID).Default, entry.Count, entry.Prototype != null);
            var name = entry.Name ?? prototype?.Name ?? entry.Prototype ?? Loc.GetString("wh40k-faction-storage-empty");
            var action = Loc.GetString(entry.Prototype == null ? "wh40k-faction-storage-deposit" : "wh40k-faction-storage-withdraw");
            var item = entry.Prototype == null ? name : Loc.GetString("wh40k-faction-storage-item-count", ("name", name), ("count", entry.Count));
            cell.ToolTip = $"{i + 1:D3}: {item}\n{entry.Description ?? prototype?.Description}\n{action}";
            _searchNames[i] = $"{i + 1:D3} {name} {entry.Description ?? prototype?.Description}";
        }
        FilterCells();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateInteraction();
    }

    private TimeSpan RequestRemaining()
    {
        var until = _localRequestUntil;
        if (_players.LocalEntity is { } user && _entities.System<UseDelaySystem>()
                .TryGetDelayInfo(user, out var info, FactionStorageComponent.RequestDelayId) && info.EndTime > until)
            until = info.EndTime;
        return until > _timing.CurTime ? until - _timing.CurTime : TimeSpan.Zero;
    }

    private bool TryRequest(bool refresh = false)
    {
        if (_state == null || _state.Status is FactionDepotStatus.Loading or FactionDepotStatus.Busy || RequestRemaining() > TimeSpan.Zero)
            return false;
        _localRequestUntil = _timing.CurTime + (refresh ? FactionStorageComponent.RefreshCooldown : FactionStorageComponent.RequestCooldown);
        UpdateInteraction();
        return true;
    }

    private void UpdateInteraction()
    {
        var remaining = RequestRemaining();
        var status = _state?.Status;
        var disabled = status != FactionDepotStatus.Ready || remaining > TimeSpan.Zero;
        if (_buttonsDisabled != disabled)
        {
            _buttonsDisabled = disabled;
            for (var i = 0; i < _cells.Count; i++)
                _cells[i].Disabled = disabled || i >= (_state?.Slots.Length ?? 0);
        }
        RefreshButton.Disabled = status == null || status is FactionDepotStatus.Loading or FactionDepotStatus.Busy || remaining > TimeSpan.Zero;
        var tenths = (int) Math.Ceiling(remaining.TotalSeconds * 10);
        if (_displayedStatus == status && _displayedCooldown == tenths)
            return;
        _displayedStatus = status;
        _displayedCooldown = tenths;
        ConnectionLabel.Text = status == FactionDepotStatus.Ready && tenths > 0
            ? Loc.GetString("wh40k-faction-storage-cooldown", ("seconds", (tenths / 10f).ToString("0.0")))
            : Loc.GetString(status == FactionDepotStatus.Ready ? "wh40k-faction-storage-ready" : "wh40k-faction-storage-waiting");
        ConnectionLabel.FontColorOverride = !disabled ? Color.FromHex("#8dbc97") : Gold;
        ConnectionLabel.ToolTip = Loc.GetString(status switch
        {
            FactionDepotStatus.Ready => "wh40k-faction-storage-ready",
            FactionDepotStatus.Unavailable => "wh40k-faction-storage-unavailable",
            FactionDepotStatus.Busy => "wh40k-faction-storage-busy",
            _ => "wh40k-faction-storage-loading",
        });
    }

    private void FilterCells()
    {
        var search = SearchInput.Text.Trim();
        var shown = 0;
        for (var i = 0; i < _cells.Count; i++)
        {
            var visible = (!OccupiedOnly.Pressed || _cells[i].Occupied) &&
                          (search.Length == 0 || (_searchNames[i]?.Contains(search, StringComparison.CurrentCultureIgnoreCase) ?? false));
            _cells[i].Visible = visible;
            if (visible)
                shown++;
        }
        ShownLabel.Text = Loc.GetString("wh40k-faction-storage-shown", ("count", shown));
        NoMatchesLabel.Visible = shown == 0;
    }

    private sealed class DepotCell : ContainerButton
    {
        private readonly TextureRect _icon;
        private readonly Label _count;
        public bool Occupied { get; private set; }

        public DepotCell(int index)
        {
            MinSize = new Vector2(62, 74);
            MaxSize = new Vector2(62, 74);
            Disabled = true;
            StyleBoxOverride = new StyleBoxFlat
            {
                BorderThickness = new Thickness(1), ContentMarginLeftOverride = 4, ContentMarginRightOverride = 4,
                ContentMarginTopOverride = 3, ContentMarginBottomOverride = 3,
            };
            var content = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 0 };
            content.AddChild(new Label { Text = $"{index + 1:D3}", MinHeight = 18, MaxHeight = 18,
                FontColorOverride = Muted, StyleClasses = { "LabelSubText" } });
            _icon = new TextureRect
            {
                MinSize = new Vector2(32), MaxSize = new Vector2(32), Stretch = TextureRect.StretchMode.KeepAspectCentered,
                HorizontalAlignment = HAlignment.Center,
            };
            _count = new Label { MinHeight = 18, MaxHeight = 18, FontColorOverride = Gold,
                HorizontalExpand = true, Align = Label.AlignMode.Right, ClipText = true };
            content.AddChild(_icon);
            content.AddChild(_count);
            AddChild(content);
            UpdateStyle();
        }

        public void SetItem(Texture? icon, int count, bool occupied)
        {
            Occupied = occupied;
            _icon.Texture = icon;
            _count.Text = count > 1 ? $"×{count}" : string.Empty;
            UpdateStyle();
        }

        protected override void DrawModeChanged()
        {
            base.DrawModeChanged();
            UpdateStyle();
        }

        private void UpdateStyle()
        {
            if (StyleBoxOverride is not StyleBoxFlat style)
                return;
            var hover = DrawMode is DrawModeEnum.Hover or DrawModeEnum.Pressed;
            style.BackgroundColor = Color.FromHex(hover ? "#303b42" : Occupied ? "#202b33" : "#141b20");
            style.BorderColor = hover ? Gold : Color.FromHex(Occupied ? "#756040" : "#303b42");
        }
    }
}
