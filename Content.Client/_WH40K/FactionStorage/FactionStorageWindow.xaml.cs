using System.Linq;
using System.Numerics;
using Content.Shared._Mono.Company;
using Content.Shared._WH40K.FactionStorage;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.FactionStorage;

[GenerateTypedNameReferences]
public sealed partial class FactionStorageWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IEntityManager _entities = default!;

    public event Action<int, Guid, bool>? OnTransfer;
    public event Action? OnRefresh;

    public FactionStorageWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        RulesLabel.SetMessage(Loc.GetString("wh40k-faction-storage-rules"));
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
    }

    public void UpdateState(FactionStorageStateMessage state)
    {
        FactionLabel.Text = _prototypes.TryIndex<CompanyPrototype>(state.Faction, out var company)
            ? company.Name : state.Faction;
        CapacityLabel.Text = Loc.GetString("wh40k-faction-storage-capacity",
            ("used", state.Slots.Count(slot => slot.Prototype != null)), ("capacity", FactionStorageComponent.Capacity));
        BusyLabel.Visible = state.Busy;
        RefreshButton.Disabled = state.Busy && state.Slots.Count != 0;
        Slots.DisposeAllChildren();
        var sprites = _entities.System<SpriteSystem>();
        foreach (var slot in state.Slots)
        {
            var occupied = slot.Prototype != null;
            EntityPrototype? prototype = null;
            if (slot.Prototype != null)
                _prototypes.TryIndex(slot.Prototype, out prototype);
            var name = slot.Name ?? prototype?.Name ?? slot.Prototype ?? Loc.GetString("wh40k-faction-storage-empty");
            var description = slot.Description ?? prototype?.Description;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, Margin = new Thickness(4, 5) };
            row.AddChild(new Label { Text = (slot.Slot + 1).ToString("D3"), MinWidth = 36 });
            if (prototype != null)
                row.AddChild(new TextureRect
                {
                    Texture = sprites.GetPrototypeIcon(prototype.ID).Default,
                    MinSize = new Vector2(32), MaxSize = new Vector2(32),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                });
            var text = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true,
                Margin = new Thickness(8, 0),
            };
            text.AddChild(new Label
            {
                Text = occupied ? Loc.GetString("wh40k-faction-storage-item-count", ("name", name), ("count", slot.Count)) : name,
                ClipText = true, ToolTip = name,
            });
            if (!string.IsNullOrWhiteSpace(description))
            {
                var details = new RichTextLabel { MaxWidth = 470 };
                details.SetMessage(FormattedMessage.FromUnformatted(description));
                text.AddChild(details);
            }
            row.AddChild(text);
            var button = new Button
            {
                Text = Loc.GetString(occupied ? "wh40k-faction-storage-withdraw" : "wh40k-faction-storage-deposit"),
                Disabled = state.Busy, MinWidth = 110,
            };
            button.OnPressed += _ => OnTransfer?.Invoke(slot.Slot, slot.Revision, !occupied);
            row.AddChild(button);
            Slots.AddChild(row);
        }
    }
}
