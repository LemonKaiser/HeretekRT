using System.Globalization;
using Content.Client._WH40K.UserInterface;
using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Company;
using Content.Shared._NF.Bank;
using Content.Shared._WH40K.Factions.Capture;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._WH40K.Factions.Capture;

[GenerateTypedNameReferences]
public sealed partial class FactionCaptureWindow : FancyWindow
{
    private readonly IPrototypeManager _prototypes = IoCManager.Resolve<IPrototypeManager>();
    private readonly List<SiteCard> _cards = new();

    public FactionCaptureWindow()
    {
        RobustXamlLoader.Load(this);
        SchedulePanel.PanelOverride = Wh40kInterfaceTheme.Surface("#251C12", "#80643A", 12, 9);
        WindowStatus.FontColorOverride = Wh40kInterfaceTheme.Gold;
        Schedule.FontColorOverride = Wh40kInterfaceTheme.Text;
    }

    public void ShowCaptureState(FactionCaptureUiState state)
    {
        WindowStatus.Text = state.WindowSeconds > 0
            ? Loc.GetString("wh40k-capture-window-open", ("time", TimeText(state.WindowSeconds)))
            : Loc.GetString("wh40k-capture-window-closed");
        Schedule.Text = Loc.GetString("wh40k-capture-next-activation", ("time", TimeText(state.NextActivationSeconds)));
        Empty.Visible = state.Sites.Length == 0;
        SitesScroll.Visible = !Empty.Visible;

        while (_cards.Count > state.Sites.Length)
        {
            _cards[^1].Dispose();
            _cards.RemoveAt(_cards.Count - 1);
        }

        foreach (var site in state.Sites.AsSpan(_cards.Count))
        {
            var card = new SiteCard();
            _cards.Add(card);
            Sites.AddChild(card);
        }

        for (var i = 0; i < state.Sites.Length; i++)
        {
            var site = state.Sites[i];
            _cards[i].Update(site, state.HoldSeconds, FactionName(site.Owner), FactionName(site.Challenger));
        }
    }

    private string FactionName(string? id) => id == null ? Loc.GetString("wh40k-capture-unclaimed") :
        _prototypes.TryIndex<CompanyPrototype>(id, out var faction) ? faction.Name : id;

    private static string TimeText(int seconds) => TimeSpan.FromSeconds(seconds).ToString(@"hh\:mm\:ss", CultureInfo.InvariantCulture);

    private sealed class SiteCard : PanelContainer
    {
        private readonly Label _name = new() { HorizontalExpand = true, ClipText = true };
        private readonly Label _status = new();
        private readonly Label _holder = new() { HorizontalExpand = true, ClipText = true };
        private readonly Label _reward = new() { FontColorOverride = Wh40kInterfaceTheme.Gold };
        private readonly Label _activity = new() { FontColorOverride = Wh40kInterfaceTheme.MutedText, ClipText = true };
        private readonly ProgressBar _progress = new() { HorizontalExpand = true, MinHeight = 6, MaxHeight = 6 };

        public SiteCard()
        {
            PanelOverride = Wh40kInterfaceTheme.Card(9);
            _name.FontColorOverride = Wh40kInterfaceTheme.Gold;
            _name.AddStyleClass("LabelHeading");
            _holder.FontColorOverride = Wh40kInterfaceTheme.Text;
            _progress.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Wh40kInterfaceTheme.TableHeader };
            _progress.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Wh40kInterfaceTheme.Gold };

            var contents = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 5 };
            AddChild(contents);
            AddRow(contents, _name, _status);
            AddRow(contents, _holder, _reward);
            contents.AddChild(_activity);
            contents.AddChild(_progress);
        }

        public void Update(FactionCaptureSite site, int hold, string holder, string challenger)
        {
            _name.Text = site.Name ?? Loc.GetString("wh40k-capture-point-number", ("number", site.Number));
            _status.Text = Loc.GetString(site.Status switch
            {
                FactionCaptureStatus.Available => "wh40k-capture-available",
                FactionCaptureStatus.Capturing => "wh40k-capture-capturing",
                FactionCaptureStatus.Contested => "wh40k-capture-contested",
                FactionCaptureStatus.Held => "wh40k-capture-held",
                FactionCaptureStatus.Offline => "wh40k-capture-offline",
                _ => "wh40k-capture-cooldown",
            });
            _status.FontColorOverride = site.Status switch
            {
                FactionCaptureStatus.Contested => Color.FromHex("#EE804A"),
                FactionCaptureStatus.Held => Color.FromHex("#93C39C"),
                FactionCaptureStatus.Cooldown or FactionCaptureStatus.Offline => Wh40kInterfaceTheme.MutedText,
                _ => Wh40kInterfaceTheme.Gold,
            };
            _holder.Text = Loc.GetString("wh40k-capture-holder", ("faction", holder));
            _reward.Text = Loc.GetString("wh40k-capture-reward", ("amount", BankSystemExtensions.ToSpesoString(site.Reward)));
            var active = site.Status is FactionCaptureStatus.Capturing or FactionCaptureStatus.Contested;
            _progress.Visible = active && site.Challenger != null;
            _activity.Visible = _progress.Visible || site.Status == FactionCaptureStatus.Available;
            if (_progress.Visible)
            {
                _activity.Text = Loc.GetString("wh40k-capture-hold-remaining", ("faction", challenger), ("time", TimeText(site.CaptureSeconds)));
                _progress.MaxValue = Math.Max(1, hold);
                _progress.Value = hold - site.CaptureSeconds;
            }
            else if (_activity.Visible)
            {
                _activity.Text = Loc.GetString("wh40k-capture-required-time", ("time", TimeText(hold)));
            }
        }

        private static void AddRow(BoxContainer contents, Control left, Control right)
        {
            var row = new BoxContainer { SeparationOverride = 12 };
            row.AddChild(left);
            row.AddChild(right);
            contents.AddChild(row);
        }
    }
}
