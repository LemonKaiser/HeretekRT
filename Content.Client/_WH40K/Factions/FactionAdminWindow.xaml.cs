using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Company;
using Content.Shared._WH40K.Factions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Factions;

[GenerateTypedNameReferences]
public sealed partial class FactionAdminWindow : FancyWindow
{
    private FactionAdminEuiState _state = new();
    private readonly List<FactionAdminSummary> _visibleFactions = new();
    private readonly List<FactionAdminMember> _visibleMembers = new();
    private Guid? _member;
    private Guid? _application;
    private bool _applying;
    private bool _pending;
    private bool _relationSavePending;
    public event Action<string>? FactionSelected;
    public event Action<FactionAdminRequest>? ActionRequested;

    public FactionAdminWindow()
    {
        RobustXamlLoader.Load(this);
        Rank.AddItem(FactionUiPresentation.Role(FactionRole.Member), (int) FactionRole.Member);
        Rank.AddItem(FactionUiPresentation.Role(FactionRole.Officer), (int) FactionRole.Officer);
        Rank.SelectId((int) FactionRole.Member);
        Rank.OnItemSelected += args => { Rank.SelectId(args.Id); ResetConfirmations(); UpdateButtons(); };
        FactionSearch.OnTextChanged += _ => RenderFactions();
        MemberSearch.OnTextChanged += _ => RenderMembers();
        FactionList.OnItemSelected += args =>
        {
            if (_applying || _pending || _state.Busy)
                return;
            SetPending();
            FactionSelected?.Invoke(_visibleFactions[args.ItemIndex].Id);
        };
        Members.OnItemSelected += args =>
        {
            _member = _visibleMembers[args.ItemIndex].UserId;
            if (!_applying)
                Rank.SelectId((int) (_visibleMembers[args.ItemIndex].Role == FactionRole.Leader
                    ? FactionRole.Officer : _visibleMembers[args.ItemIndex].Role));
            ResetConfirmations();
            RenderMemberInfo();
            UpdateButtons();
        };
        Applications.OnItemSelected += args =>
        {
            _application = _state.Applications[args.ItemIndex].UserId;
            ApplicationId.Text = _application?.ToString() ?? string.Empty;
            UpdateButtons();
        };
        AddTarget.OnTextChanged += _ => UpdateButtons();
        Relations.SaveRequested += relation =>
        {
            if (_pending || _state.Busy || _state.SelectedFaction == null)
                return;
            SetPending();
            _relationSavePending = true;
            ActionRequested?.Invoke(new FactionAdminRequest(_state.SelectedFaction, FactionAdminAction.SetRelation, relation: relation));
        };
        AddTarget.OnTextEntered += _ => AddMember();
        AddButton.OnPressed += _ => AddMember();
        RefreshButton.OnPressed += _ => Request(FactionAdminAction.Refresh);
        RemoveButton.OnPressed += _ => Request(FactionAdminAction.RemoveMember, _member);
        AssignLeaderButton.OnPressed += _ => Request(FactionAdminAction.AssignLeader, _member);
        SetRankButton.OnPressed += _ => Request(Rank.SelectedId == (int) FactionRole.Officer
            ? FactionAdminAction.SetOfficer : FactionAdminAction.SetMember, _member);
        AcceptButton.OnPressed += _ => Request(FactionAdminAction.AcceptApplication, _application);
        RejectButton.OnPressed += _ => Request(FactionAdminAction.RejectApplication, _application);
        RemoveButton.AddStyleClass(StyleNano.ButtonCaution);
        AssignLeaderButton.AddStyleClass(StyleNano.ButtonCaution);
        Apply(new FactionAdminEuiState());
    }

    public void Apply(FactionAdminEuiState state)
    {
        var changedFaction = _state.SelectedFaction != state.SelectedFaction;
        _state = state;
        _pending = false;
        _applying = true;
        if (changedFaction)
        {
            _member = null;
            _application = null;
            MemberSearch.Text = string.Empty;
            AddTarget.Text = string.Empty;
        }
        ResetConfirmations();
        RenderFactions();
        var faction = state.Factions.FirstOrDefault(f => f.Id == state.SelectedFaction);
        FactionName.Text = faction?.Name ?? Loc.GetString("wh40k-faction-admin-select-faction");
        FactionInfo.TextRope = new Rope.Leaf(faction == null ? string.Empty : Loc.GetString("wh40k-faction-admin-summary",
            ("id", faction.Id), ("enabled", YesNo(!faction.Disabled)), ("applications", YesNo(faction.JoinRequired)),
            ("whitelist", YesNo(faction.Whitelisted)), ("members", faction.Members), ("officers", faction.Officers),
            ("leaders", faction.Leaders.Length == 0 ? Loc.GetString("wh40k-faction-no-leader") : string.Join(", ", faction.Leaders))));
        Message.Visible = !string.IsNullOrEmpty(state.Message) || state.Busy;
        Message.SetMessage(state.Busy ? Loc.GetString("wh40k-faction-loading") : state.Message);
        Tabs.SetTabTitle(0, Loc.GetString("wh40k-faction-roster-count", ("count", state.Members.Length)));
        Tabs.SetTabTitle(1, Loc.GetString("wh40k-faction-requests-count", ("count", state.Applications.Length)));
        Tabs.SetTabTitle(2, Loc.GetString("wh40k-faction-rel-tab"));
        Relations.UpdateRelations(state.SelectedFaction, state.Relations, true, state.Busy,
            _relationSavePending && !state.Busy && state.Message == Loc.GetString("wh40k-faction-rel-saved"), admin: true);
        if (!state.Busy)
            _relationSavePending = false;
        RenderMembers();
        Applications.Clear();
        foreach (var application in state.Applications)
        {
            Applications.AddItem($"{application.Name} · {application.CreatedAt:yyyy-MM-dd HH:mm} UTC");
            if (application.UserId == _application)
                Applications[Applications.Count - 1].Selected = true;
        }
        if (!state.Applications.Any(a => a.UserId == _application))
            _application = null;
        ApplicationId.Text = _application?.ToString() ?? string.Empty;
        _applying = false;
        UpdateButtons();
    }

    public void SetPending()
    {
        _pending = true;
        ResetConfirmations();
        UpdateButtons();
    }

    private void RenderFactions()
    {
        var applying = _applying;
        _applying = true;
        FactionList.Clear();
        _visibleFactions.Clear();
        var search = FactionSearch.Text.Trim();
        foreach (var faction in _state.Factions.Where(f => f.Id.Contains(search, StringComparison.OrdinalIgnoreCase) ||
                     f.Name.Contains(search, StringComparison.OrdinalIgnoreCase)))
        {
            _visibleFactions.Add(faction);
            FactionList.AddItem($"{faction.Name} ({faction.Members})", metadata: faction.Id);
            FactionList[_visibleFactions.Count - 1].Disabled = _pending || _state.Busy;
            if (faction.Id == _state.SelectedFaction)
                FactionList[_visibleFactions.Count - 1].Selected = true;
        }
        _applying = applying;
    }

    private void RenderMembers()
    {
        Members.Clear();
        _visibleMembers.Clear();
        var search = MemberSearch.Text.Trim();
        foreach (var member in _state.Members.Where(m => m.Name.Contains(search, StringComparison.OrdinalIgnoreCase) ||
                     m.UserId.ToString().Contains(search, StringComparison.OrdinalIgnoreCase)))
        {
            _visibleMembers.Add(member);
            Members.AddItem($"{member.Name} · {RankName(member.Role)} · {Loc.GetString(member.Online ? "wh40k-faction-online" : "wh40k-faction-offline")}");
            if (member.UserId == _member)
                Members[_visibleMembers.Count - 1].Selected = true;
        }
        if (!_visibleMembers.Any(m => m.UserId == _member))
            _member = null;
        RenderMemberInfo();
        UpdateButtons();
    }

    private void RenderMemberInfo()
    {
        var member = _state.Members.FirstOrDefault(m => m.UserId == _member);
        MemberInfo.TextRope = new Rope.Leaf(member == null ? Loc.GetString("wh40k-faction-admin-select-member")
            : Loc.GetString("wh40k-faction-admin-member-info", ("name", member.Name), ("id", member.UserId.ToString()),
                ("role", RankName(member.Role)), ("online", YesNo(member.Online))));
        LeaderWarning.Visible = member?.Role == FactionRole.Leader;
    }

    private void AddMember()
    {
        if (!AddButton.Disabled)
            Request(FactionAdminAction.AddMember, target: AddTarget.Text.Trim());
    }

    private void Request(FactionAdminAction action, Guid? user = null, string target = "")
    {
        if (_pending || _state.Busy || action != FactionAdminAction.Refresh && _state.SelectedFaction == null)
            return;
        var request = new FactionAdminRequest(_state.SelectedFaction ?? string.Empty, action, user ?? default, target);
        SetPending();
        ActionRequested?.Invoke(request);
    }

    private void ResetConfirmations()
    {
        foreach (var button in new[] { SetRankButton, AssignLeaderButton, RemoveButton })
        {
            button.IsConfirming = false;
            button.Text = button.Text;
        }
    }

    private void UpdateButtons()
    {
        var busy = _pending || _state.Busy;
        Relations.SetPending(busy);
        var member = _state.Members.FirstOrDefault(m => m.UserId == _member);
        for (var index = 0; index < FactionList.Count; index++)
            FactionList[index].Disabled = busy;
        RefreshButton.Disabled = busy;
        AddButton.Disabled = busy || _state.SelectedFaction == null || string.IsNullOrWhiteSpace(AddTarget.Text) || AddTarget.Text.Length > 128;
        Rank.Disabled = busy || member == null;
        SetRankButton.Disabled = busy || member == null || (int) member.Role == Rank.SelectedId;
        AssignLeaderButton.Disabled = busy || member == null || member.Role == FactionRole.Leader &&
            _state.Factions.FirstOrDefault(f => f.Id == _state.SelectedFaction)?.Leaders.Length == 1;
        RemoveButton.Disabled = busy || member == null;
        AcceptButton.Disabled = busy || _application == null;
        RejectButton.Disabled = busy || _application == null;
    }

    private static string YesNo(bool value) => Loc.GetString(value ? "wh40k-faction-admin-yes" : "wh40k-faction-admin-no");

    private string RankName(FactionRole role)
    {
        var canonical = FactionUiPresentation.Role(role);
        var custom = FactionUiPresentation.Role(role, _state.Profile);
        return canonical == custom ? canonical : $"{canonical} ({custom})";
    }
}
