using Content.Client.PDA;
using Content.Shared._Mono.Company;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Factions;

[GenerateTypedNameReferences]
public sealed partial class FactionCard : PanelContainer, IFactionCatalogCard
{
    public Control Root => this;
    public event Action? DetailsPressed;
    public event Action? ActionPressed;

    public FactionCard()
    {
        RobustXamlLoader.Load(this);
        DetailsButton.OnPressed += _ => DetailsPressed?.Invoke();
        ActionButton.OnPressed += _ => ActionPressed?.Invoke();
        ActionButton.StyleBoxOverride = PdaTerminalPalette.CreateButton(accented: true);
    }

    public void SetFaction(CompanyPrototype faction, string membership, string action, bool disabled, bool selected)
    {
        PanelOverride = FactionUiPresentation.Panel(FactionUiPresentation.Gold, selected);
        Emblem.Visible = faction.Image != null;
        if (faction.Image is { } image)
            Emblem.TexturePath = image;
        FactionName.Text = faction.Name;
        FactionName.FontColorOverride = faction.Color;
        Summary.SetMessage(FactionUiPresentation.Summary(faction), FactionUiPresentation.Text);
        Membership.Text = membership;
        ActionButton.Text = action;
        ActionButton.Disabled = disabled;
    }

    public void UpdateOverview(string overview) =>
        Overview.SetMessage(FormattedMessage.FromUnformatted(overview), FactionUiPresentation.Muted);
}
