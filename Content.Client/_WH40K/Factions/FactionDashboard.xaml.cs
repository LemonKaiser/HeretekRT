[GenerateTypedNameReferences]
public sealed partial class FactionDashboard : BoxContainer
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    private Wh40kFactionUiSnapshot? _snapshot;
    private bool _pending;
    private float _pendingSeconds;
    private FactionProfileEditorWindow? _editor;
    private FactionProfile CurrentProfile => _snapshot?.AvailableFactions.FirstOrDefault(f => f.Id == _snapshot.FactionId)?.Profile ?? new FactionProfile();

    public event Action<Wh40kFactionUiAction, string, Guid>? OnAction;
    public event Action<string, FactionProfile>? ProfileSaveRequested;
    public event Action<string, Guid, FactionBankPayout>? PayoutRequested;
    public event Action<Wh40kFactionUiAction, string, FactionSocialRequest>? SocialRequested;

    public FactionDashboard()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;
        var resources = IoCManager.Resolve<IResourceCache>();
        CurrentName.FontOverride = Wh40kOnboardingTypography.Display(resources, 24);
        CurrentRole.FontOverride = Wh40kOnboardingTypography.Text(resources, 12);
        Overview.AddStyleClass("Wh40kOnboardingBodyCompact");
        MembershipInfo.AddStyleClass("Wh40kOnboardingBodyText");
        PermissionsHint.AddStyleClass("Wh40kOnboardingBodyCompact");
        FactionDescription.AddStyleClass("Wh40kOnboardingBodyText");
        StyleDanger(LeaveButton);
        RefreshButton.OnPressed += _ => OnAction?.Invoke(Wh40kFactionUiAction.Refresh, "", default);
        LeaveButton.OnPressed += _ => OnAction?.Invoke(Wh40kFactionUiAction.Leave, "", default);
        Catalog.Request += (action, faction) => OnAction?.Invoke(action, faction, default);
        MemberSearch.OnTextChanged += _ => RenderMembers();
        EditProfileButton.OnPressed += _ => OpenProfileEditor();
        Communications.Request += (action, request) =>
        {
            if (_snapshot?.FactionId is { } faction)
                SocialRequested?.Invoke(action, faction, request);
        };
        Relations.SaveRequested += request =>
        {
            if (_snapshot?.FactionId is { } faction)
                SocialRequested?.Invoke(Wh40kFactionUiAction.SetRelation, faction, request);
        };
        Treasury.PayoutRequested += (recipient, payout) =>
        {
            if (_snapshot?.FactionId is { } faction)
                PayoutRequested?.Invoke(faction, recipient, payout);
        };
        UpdateSnapshot(null, Wh40kFactionUiOperationStatus.None);
    }

    public void SetPending(bool pending)
    {
        _pending = pending;
        _pendingSeconds = 0;
        StatusLabel.Visible = pending;
        if (pending)
            StatusLabel.SetMessage(Loc.GetString("wh40k-faction-loading"), FactionUiPresentation.Muted);
        RenderMembers();
        RenderRequests();
        UpdateButtons();
    }

    public void UpdateSnapshot(Wh40kFactionUiSnapshot? snapshot, Wh40kFactionUiOperationStatus status,
        bool pending = false)
    {
        var wasMember = _snapshot?.FactionId != null;
        _snapshot = snapshot;
        if (pending && !_pending)
            _pendingSeconds = 0;
        _pending = pending;
        StatusLabel.Visible = pending || status != Wh40kFactionUiOperationStatus.None;
        StatusLabel.SetMessage(pending ? Loc.GetString("wh40k-faction-loading") : FactionUiPresentation.Status(status), FactionUiPresentation.Gold);
        var hasFaction = snapshot?.FactionId != null;
        DirectoryRoot.Visible = !hasFaction;
        ManagementTabs.Visible = hasFaction;
        EmblemFrame.Visible = hasFaction;
        Overview.Visible = hasFaction;
        CurrentRole.Visible = hasFaction;
        CurrentName.Text = Loc.GetString(snapshot == null ? "wh40k-faction-loading" : "wh40k-faction-directory");
        HeadingLabel.Text = Loc.GetString(!hasFaction ? "wh40k-faction-profile-label"
            : snapshot!.ViewerRole is FactionRole.Leader or FactionRole.Officer ? "wh40k-faction-management-title" : "wh40k-faction-your-faction");
        CurrentRole.Text = string.Empty;
        if (hasFaction && _prototypes.TryIndex<CompanyPrototype>(snapshot!.FactionId!, out var faction))
        {
            CurrentName.Text = faction.Name;
            CurrentEmblem.Visible = faction.Image != null;
            if (faction.Image is { } image)
                CurrentEmblem.TexturePath = image;
            CurrentRole.Text = Loc.GetString("wh40k-faction-your-role", ("role", FactionUiPresentation.Role(snapshot.ViewerRole ?? FactionRole.Member, CurrentProfile)));
            CurrentRole.ToolTip = CurrentRole.Text;
            Overview.SetMessage(FormattedMessage.FromUnformatted(FactionUiPresentation.Overview(
                snapshot.AvailableFactions.FirstOrDefault(f => f.Id == faction.ID), detailed: true)), Color.FromHex("#C7BDAB"));
            MembershipInfo.SetMessage(Loc.GetString("wh40k-faction-membership-info", ("faction", faction.Name)), Color.FromHex("#DDD8E2"));
            FactionDescription.SetMessage(string.IsNullOrEmpty(faction.Description)
                ? Loc.GetString("humanoid-profile-editor-company-no-description") : Loc.GetString(faction.Description), Color.FromHex("#C7C3CC"));
        }
        var helpKey = !hasFaction ? "wh40k-faction-pda-help" : snapshot!.ViewerRole switch
        {
            FactionRole.Leader => "wh40k-faction-leader-help",
            FactionRole.Officer => "wh40k-faction-officer-help",
            _ => "wh40k-faction-member-help",
        };
        PermissionsHint.SetMessage(Loc.GetString(helpKey), FactionUiPresentation.Muted);
        ManagementTabs.SetTabTitle(0, Loc.GetString("wh40k-faction-overview-tab"));
        ManagementTabs.SetTabTitle(1, Loc.GetString("wh40k-faction-roster-count", ("count", snapshot?.Members.Count ?? 0)));
        ManagementTabs.SetTabTitle(2, Loc.GetString("wh40k-faction-requests-count", ("count", snapshot?.Requests.Count ?? 0)));
        ManagementTabs.SetTabTitle(3, Loc.GetString("wh40k-faction-bank-tab"));
        ManagementTabs.SetTabTitle(4, Loc.GetString("wh40k-faction-comms-tab"));
        ManagementTabs.SetTabTitle(5, Loc.GetString("wh40k-faction-rel-tab"));
        ManagementTabs.SetTabVisible(1, hasFaction);
        ManagementTabs.SetTabVisible(2, hasFaction && snapshot!.ViewerRole is FactionRole.Leader or FactionRole.Officer);
        ManagementTabs.SetTabVisible(3, hasFaction && FactionBankRules.CanManage(snapshot!.ViewerRole));
        if (!hasFaction)
            ManagementTabs.CurrentTab = 0;
        else if (!wasMember || ManagementTabs.CurrentTab == 2 && snapshot!.ViewerRole is not (FactionRole.Leader or FactionRole.Officer) ||
                 ManagementTabs.CurrentTab == 3 && !FactionBankRules.CanManage(snapshot!.ViewerRole))
            ManagementTabs.CurrentTab = 0;
        Treasury.UpdateSnapshot(snapshot, pending);
        Treasury.CompleteOperation(status);
        Communications.UpdateSnapshot(snapshot, status, pending);
        Relations.UpdateRelations(snapshot?.FactionId, snapshot?.Relations ?? [],
            FactionSocialRules.CanSetRelations(snapshot?.ViewerRole), pending, status == Wh40kFactionUiOperationStatus.RelationSaved,
            snapshot?.RelationCooldownSeconds ?? 0);
        LeaveButton.Visible = hasFaction && FactionPermissions.CanLeave(snapshot!.ViewerRole);
        LeaveHint.Visible = LeaveButton.Visible;
        LeaveButton.ToolTip = Loc.GetString("wh40k-faction-leave-hint");
        ProfileSections.UpdateProfile(CurrentProfile);
        _editor?.UpdateState(snapshot?.FactionId, snapshot?.ViewerRole, CurrentProfile, status);
        RenderMembers();
        RenderRequests();
        UpdateButtons();
    }

    private void RenderMembers()
    {
        MemberList.RemoveAllChildren();
        if (_snapshot == null)
            return;
        foreach (var member in _snapshot.Members.Where(m => m.Ckey.Contains(MemberSearch.Text.Trim(), StringComparison.OrdinalIgnoreCase)))
        {
            var panel = NewPanel();
            var contents = new FactionMemberRow { SeparationOverride = 14 };
            var identity = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
            var name = new Label { Text = member.Ckey, ClipText = true, ToolTip = member.Ckey, FontColorOverride = FactionUiPresentation.Text };
            identity.AddChild(name);
            var status = new RichTextLabel();
            status.SetMessage(Loc.GetString("wh40k-faction-member-status",
                ("role", FactionUiPresentation.Role(member.Role, CurrentProfile)),
                ("self", member.IsSelf ? " " + Loc.GetString("wh40k-faction-self") : string.Empty),
                ("connection", Loc.GetString(member.IsOnline ? "wh40k-faction-online" : "wh40k-faction-offline"))),
                member.IsOnline ? Color.FromHex("#A8C6A6") : Color.FromHex("#AAA4AF"));
            status.AddStyleClass("Wh40kOnboardingBodySmall");
            identity.AddChild(status);
            contents.AddChild(identity);
            var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8, VerticalAlignment = VAlignment.Center };
            if (_snapshot.ViewerRole == FactionRole.Leader && !member.IsSelf && member.Role != FactionRole.Leader)
            {
                var demote = member.Role == FactionRole.Officer;
                var rank = NewButton(demote ? "wh40k-faction-demote" : "wh40k-faction-promote");
                rank.ToolTip = Loc.GetString("wh40k-faction-rank-action-hint", ("rank", FactionUiPresentation.Role(
                    demote ? FactionRole.Member : FactionRole.Officer, CurrentProfile)));
                rank.OnPressed += _ => OnAction?.Invoke(demote ? Wh40kFactionUiAction.DemoteOfficer : Wh40kFactionUiAction.PromoteOfficer, "", member.UserId);
                actions.AddChild(rank);
            }
            if (FactionPermissions.CanRemove(_snapshot.ViewerRole, member.Role, member.IsSelf))
            {
                var remove = new ConfirmButton
                {
                    Text = Loc.GetString("wh40k-faction-remove"),
                    ConfirmationText = Loc.GetString("wh40k-faction-remove-confirm"),
                    ResetTime = TimeSpan.FromSeconds(5),
                    MinHeight = 32,
                    ToolTip = Loc.GetString("wh40k-faction-remove-person", ("name", member.Ckey)),
                };
                StyleDanger(remove);
                remove.OnPressed += _ => OnAction?.Invoke(Wh40kFactionUiAction.RemoveMember, "", member.UserId);
                actions.AddChild(remove);
            }
            if (actions.ChildCount > 0)
                contents.AddChild(actions);
            panel.AddChild(contents);
            MemberList.AddChild(panel);
        }
        if (MemberList.ChildCount == 0)
            AddEmpty(MemberList, "wh40k-faction-no-members-found");
        SetButtonsDisabled(MemberList, _pending);
    }

    private void RenderRequests()
    {
        RequestList.RemoveAllChildren();
        if (_snapshot?.ViewerRole is not (FactionRole.Leader or FactionRole.Officer))
            return;
        foreach (var request in _snapshot.Requests)
        {
            var panel = NewPanel();
            var contents = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 14 };
            contents.AddChild(new Label { Text = request.Ckey, ClipText = true, ToolTip = request.Ckey,
                FontColorOverride = FactionUiPresentation.Text, HorizontalExpand = true, VerticalAlignment = VAlignment.Center });
            var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 8 };
            var accept = NewButton("wh40k-faction-accept", true);
            accept.OnPressed += _ => OnAction?.Invoke(Wh40kFactionUiAction.AcceptRequest, "", request.UserId);
            var reject = NewButton("wh40k-faction-reject");
            reject.OnPressed += _ => OnAction?.Invoke(Wh40kFactionUiAction.RejectRequest, "", request.UserId);
            actions.AddChild(accept);
            actions.AddChild(reject);
            contents.AddChild(actions);
            panel.AddChild(contents);
            RequestList.AddChild(panel);
        }
        if (RequestList.ChildCount == 0)
            AddEmpty(RequestList, "wh40k-faction-no-requests");
    }

    private static PanelContainer NewPanel() => new()
    {
        PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#242424"),
            ContentMarginLeftOverride = 12, ContentMarginRightOverride = 12,
            ContentMarginTopOverride = 10, ContentMarginBottomOverride = 10,
        },
    };
    private static Button NewButton(string key, bool accent = false) => new LobbyFactionButton
    {
        Text = Loc.GetString(key), Primary = accent,
    };

    private static void StyleDanger(ConfirmButton button)
    {
        button.AddStyleClass(StyleNano.ButtonCaution);
        button.Label.FontOverride = Wh40kOnboardingTypography.Text(IoCManager.Resolve<IResourceCache>(), 12);
        button.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.White, BorderColor = Color.FromHex("#D0C6C6"), BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 14, ContentMarginRightOverride = 14,
            ContentMarginTopOverride = 5, ContentMarginBottomOverride = 5,
        };
    }

    private static void AddEmpty(Control parent, string key)
    {
        var label = new RichTextLabel { Margin = new Thickness(10, 18) };
        label.SetMessage(Loc.GetString(key), FactionUiPresentation.Muted);
        parent.AddChild(label);
    }

    private void UpdateButtons()
    {
        EditProfileButton.Visible = FactionProfile.CanEdit(_snapshot?.ViewerRole);
        EditProfileButton.Disabled = _pending;
        RefreshButton.Disabled = _pending;
        LeaveButton.Disabled = _pending;
        Catalog.Update(_snapshot, _pending);
        SetButtonsDisabled(MemberList, _pending);
        SetButtonsDisabled(RequestList, _pending);
        Treasury.SetPending(_pending);
        Communications.SetPending(_pending);
        Relations.SetPending(_pending);
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        var compact = ManagementTabs.Visible && ManagementTabs.CurrentTab != 0 && availableSize.Y < 600;
        Overview.Visible = _snapshot?.FactionId != null && !compact;
        var emblemSize = compact || ManagementTabs.Visible && ManagementTabs.CurrentTab >= 3 ? 96 : availableSize.X < 740 ? 128 : 160;
        EmblemFrame.SetSize = new Vector2(emblemSize, emblemSize);
        HeaderRow.MinHeight = _snapshot?.FactionId == null ? 48 : emblemSize;
        var measured = base.MeasureOverride(availableSize);
        return float.IsFinite(availableSize.X) ? new Vector2(availableSize.X, measured.Y) : measured;
    }

    private void OpenProfileEditor()
    {
        if (_pending || !FactionProfile.CanEdit(_snapshot?.ViewerRole) ||
            !_prototypes.TryIndex<CompanyPrototype>(_snapshot!.FactionId!, out var faction))
            return;
        _editor?.Close();
        _editor = new FactionProfileEditorWindow(faction, CurrentProfile);
        _editor.OnClose += () => _editor = null;
        _editor.SaveRequested += profile => ProfileSaveRequested?.Invoke(faction.ID, profile);
        _editor.OpenCentered();
    }

    protected override void ExitedTree()
    {
        _editor?.Close();
        base.ExitedTree();
    }

    private static void SetButtonsDisabled(Control control, bool disabled)
    {
        foreach (var child in control.Children)
        {
            if (child is Button button)
                button.Disabled = disabled;
            SetButtonsDisabled(child, disabled);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_pending)
            return;
        _pendingSeconds += args.DeltaSeconds;
        if (_pendingSeconds < 12)
            return;
        _pending = false;
        StatusLabel.SetMessage(Loc.GetString("wh40k-faction-timeout"), FactionUiPresentation.Gold);
        UpdateButtons();
    }
}

internal sealed class FactionMemberRow : BoxContainer
{
    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        var stacked = availableSize.X < 720;
        Orientation = stacked ? LayoutOrientation.Vertical : LayoutOrientation.Horizontal;
        if (ChildCount == 2)
        {
            var actions = GetChild(1);
            actions.HorizontalAlignment = stacked ? HAlignment.Right : HAlignment.Stretch;
            actions.Measure(new Vector2(float.PositiveInfinity, availableSize.Y));
            // Reserve the full action width before measuring a potentially long custom rank.
            GetChild(0).MaxWidth = stacked ? float.PositiveInfinity
                : Math.Max(0, availableSize.X - actions.DesiredSize.X - (SeparationOverride ?? 0));
        }
        return base.MeasureOverride(availableSize);
    }
}
