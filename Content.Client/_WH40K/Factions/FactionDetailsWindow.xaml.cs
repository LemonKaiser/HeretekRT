using Content.Client.PDA;
using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Company;
using Content.Shared._WH40K.Factions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Factions;

[GenerateTypedNameReferences]
public sealed partial class FactionDetailsWindow : FancyWindow, IFactionProfileWindow
{
    private readonly string _factionId;
    public event Action? ActionPressed;

    public void Show() => OpenCentered();

    public void UpdateProfile(FactionProfile profile) => ProfileSections.UpdateProfile(profile);
    public void UpdateRelations(FactionRelation[] relations) => PublicRelations.UpdateRelations(_factionId, relations);

    public FactionDetailsWindow(CompanyPrototype faction)
    {
        RobustXamlLoader.Load(this);
        _factionId = faction.ID;
        ProfileTabs.SetTabTitle(0, Loc.GetString("wh40k-faction-about"));
        ProfileTabs.SetTabTitle(1, Loc.GetString("wh40k-faction-rel-tab"));
        UpdateRelations([]);
        Title = faction.Name;
        HeaderPanel.PanelOverride = FactionUiPresentation.Panel(FactionUiPresentation.Gold);
        Emblem.Visible = faction.Image != null;
        if (faction.Image is { } image)
            Emblem.TexturePath = image;
        FactionName.SetMessage(faction.Name, faction.Color);
        Summary.SetMessage(FactionUiPresentation.Summary(faction), FactionUiPresentation.Text);
        Description.SetMessage(string.IsNullOrEmpty(faction.Description)
            ? Loc.GetString("humanoid-profile-editor-company-no-description")
            : Loc.GetString(faction.Description), FactionUiPresentation.Text);
        DismissButton.OnPressed += _ => Close();
        ActionButton.StyleBoxOverride = PdaTerminalPalette.CreateButton(accented: true);
        ActionButton.OnPressed += _ => ActionPressed?.Invoke();
    }

    public void UpdateAction(string membership, string action, string hint, bool disabled)
    {
        Membership.SetMessage(membership, FactionUiPresentation.Gold);
        ActionHint.SetMessage(hint, FactionUiPresentation.Muted);
        ActionButton.Text = FactionUiPresentation.ProfileAction(action);
        ActionButton.Disabled = disabled;
    }

    public void UpdateOverview(string overview) =>
        Overview.SetMessage(FormattedMessage.FromUnformatted(overview), FactionUiPresentation.Text);
}
