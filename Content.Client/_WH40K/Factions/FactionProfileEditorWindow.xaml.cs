using System.Linq;
using Content.Client._WH40K.CharacterCreation;
using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Company;
using Content.Shared._WH40K.Factions;
using Content.Shared._WH40K.Progression;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Factions;

[GenerateTypedNameReferences]
public sealed partial class FactionProfileEditorWindow : FancyWindow
{
    private readonly CompanyPrototype _faction;
    private readonly FactionProfile _original;
    private readonly List<(LineEdit Title, TextEdit Text, Label Count)> _sections = [];
    private readonly Dictionary<FactionRole, LineEdit> _ranks = new();
    private LobbyFactionProfileWindow? _preview;
    private bool _saving;
    private bool _submitted;
    private bool _blocked;
    private float _saveSeconds;

    public event Action<FactionProfile>? SaveRequested;

    public FactionProfileEditorWindow(CompanyPrototype faction, FactionProfile profile)
    {
        RobustXamlLoader.Load(this);
        _faction = faction;
        _original = profile;
        FactionName.Text = faction.Name;
        FactionName.FontOverride = Wh40kOnboardingTypography.Display(IoCManager.Resolve<IResourceCache>(), 25);
        Tabs.SetTabTitle(0, Loc.GetString("wh40k-faction-editor-profile-tab"));
        Tabs.SetTabTitle(1, Loc.GetString("wh40k-faction-editor-ranks-tab"));
        Admission.TextRope = new Rope.Leaf(profile.Admission);
        Admission.Placeholder = new Rope.Leaf(Loc.GetString("wh40k-faction-editor-admission-placeholder"));
        Admission.OnTextChanged += _ => ValidateDraft();
        for (var i = 0; i < FactionProfile.MaxSections; i++)
        {
            var group = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 6 };
            group.AddChild(new Label { Text = Loc.GetString("wh40k-faction-editor-section-number", ("number", i + 1)), FontColorOverride = FactionUiPresentation.Gold });
            var section = profile.Sections.ElementAtOrDefault(i);
            var title = new LineEdit { Text = section?.Title ?? "", PlaceHolder = Loc.GetString("wh40k-faction-editor-section-title"), MinHeight = 32 };
            var text = new TextEdit { TextRope = new Rope.Leaf(section?.Text ?? ""), SetHeight = 110 };
            text.Placeholder = new Rope.Leaf(Loc.GetString("wh40k-faction-editor-section-text"));
            var count = new Label { HorizontalAlignment = HAlignment.Right };
            count.AddStyleClass("LabelSubText");
            _sections.Add((title, text, count));
            title.OnTextChanged += _ => ValidateDraft();
            text.OnTextChanged += _ => ValidateDraft();
            group.AddChild(title);
            group.AddChild(text);
            group.AddChild(count);
            Sections.AddChild(group);
        }
        foreach (var role in new[] { FactionRole.Leader, FactionRole.Officer, FactionRole.Member })
        {
            var group = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 6 };
            group.AddChild(new Label { Text = FactionUiPresentation.Role(role), FontColorOverride = FactionUiPresentation.Gold });
            var input = new LineEdit { Text = profile.RankTitle(role), PlaceHolder = FactionUiPresentation.Role(role), MinHeight = 34 };
            input.OnTextChanged += _ => ValidateDraft();
            _ranks.Add(role, input);
            group.AddChild(input);
            var permissions = new RichTextLabel();
            permissions.AddStyleClass("Wh40kOnboardingBodySmall");
            permissions.SetMessage(Loc.GetString(role switch
            {
                FactionRole.Leader => "wh40k-faction-editor-leader-permissions",
                FactionRole.Officer => "wh40k-faction-editor-officer-permissions",
                _ => "wh40k-faction-editor-member-permissions",
            }), FactionUiPresentation.Muted);
            group.AddChild(permissions);
            Ranks.AddChild(group);
        }
        ResetRanksButton.OnPressed += _ =>
        {
            foreach (var input in _ranks.Values)
                input.Text = "";
            ValidateDraft();
        };
        CancelButton.OnPressed += _ => Close();
        SaveButton.OnPressed += _ =>
        {
            if (_saving || _blocked || !Draft().TryValidate(out var draft))
                return;
            _saving = true;
            _submitted = true;
            _saveSeconds = 0;
            SetEditable(false);
            ShowStatus(Loc.GetString("wh40k-faction-loading"));
            SaveRequested?.Invoke(draft);
        };
        PreviewButton.OnPressed += _ =>
        {
            if (!Draft().TryValidate(out var draft))
                return;
            _preview?.Close();
            _preview = new LobbyFactionProfileWindow(faction);
            _preview.UpdateProfile(draft);
            _preview.UpdateOverview(Loc.GetString("wh40k-faction-editor-preview-hint"));
            _preview.UpdateAction(Loc.GetString("wh40k-faction-application-required"), Loc.GetString("wh40k-faction-submit-application"),
                Loc.GetString("wh40k-faction-apply-hint"), true);
            _preview.OpenCentered();
        };
        ValidateDraft();
    }

    private FactionProfile Draft() => new(_original.Revision, Rope.Collapse(Admission.TextRope),
        _sections.Select(s => new FactionProfileSection(s.Title.Text, Rope.Collapse(s.Text.TextRope))).ToArray(),
        _ranks[FactionRole.Leader].Text, _ranks[FactionRole.Officer].Text, _ranks[FactionRole.Member].Text);

    private void ValidateDraft()
    {
        var draft = Draft();
        AdmissionCount.Text = Loc.GetString("wh40k-faction-editor-count", ("count", draft.Admission.Length), ("max", FactionProfile.MaxAdmissionLength));
        foreach (var section in _sections)
            section.Count.Text = Loc.GetString("wh40k-faction-editor-section-count", ("title", section.Title.Text.Length),
                ("titleMax", FactionProfile.MaxSectionTitleLength), ("text", Rope.Collapse(section.Text.TextRope).Length), ("textMax", FactionProfile.MaxSectionTextLength));
        var valid = draft.TryValidate(out _);
        SaveButton.Disabled = PreviewButton.Disabled = _saving || _blocked || !valid;
        if (!_saving && !_blocked)
        {
            StatusLabel.Visible = !valid;
            if (!valid)
                ShowStatus(Loc.GetString("wh40k-faction-profile-invalid"));
        }
    }

    public void UpdateState(string? factionId, FactionRole? role, FactionProfile? profile, Wh40kFactionUiOperationStatus status)
    {
        if (factionId != _faction.ID || !FactionProfile.CanEdit(role))
        {
            Close();
            return;
        }
        if (_submitted && status == Wh40kFactionUiOperationStatus.ProfileSaved)
        {
            Close();
            return;
        }
        if (_saving && status != Wh40kFactionUiOperationStatus.None)
        {
            _saving = false;
            _submitted = false;
            SetEditable(true);
            ValidateDraft();
            ShowStatus(FactionUiPresentation.Status(status));
        }
        if (!_saving && profile != null && profile.Revision != _original.Revision)
        {
            _blocked = true;
            SetEditable(false);
            ShowStatus(Loc.GetString("wh40k-faction-profile-conflict"));
        }
    }

    private void SetEditable(bool editable)
    {
        Admission.Editable = editable;
        foreach (var section in _sections)
        {
            section.Title.Editable = editable;
            section.Text.Editable = editable;
        }
        foreach (var input in _ranks.Values)
            input.Editable = editable;
        ResetRanksButton.Disabled = !editable;
        SaveButton.Disabled = PreviewButton.Disabled = !editable;
        CancelButton.Disabled = _saving;
    }

    private void ShowStatus(string text)
    {
        StatusLabel.Visible = true;
        StatusLabel.SetMessage(FormattedMessage.FromUnformatted(text), FactionUiPresentation.Gold);
    }

    protected override void FrameUpdate(Robust.Shared.Timing.FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_saving || (_saveSeconds += args.DeltaSeconds) < 12)
            return;
        _saving = false;
        // A timed-out save may have succeeded. Refresh before editing again to avoid overwriting it.
        _blocked = true;
        SetEditable(false);
        ShowStatus(Loc.GetString("wh40k-faction-editor-timeout"));
    }

    protected override void ExitedTree()
    {
        _preview?.Close();
        base.ExitedTree();
    }
}
