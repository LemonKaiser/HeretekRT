namespace Content.Client._WH40K.Factions;

[GenerateTypedNameReferences]
public sealed partial class FactionTreasuryPanel : BoxContainer
{
    private Wh40kFactionMemberUiSnapshot[] _members = [];
    private FactionBankSnapshot? _treasury;
    private Guid? _recipient;
    private bool _pending;
    private Guid _requestId = Guid.NewGuid();
    public event Action<Guid, FactionBankPayout>? PayoutRequested;

    public FactionTreasuryPanel()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        VerticalExpand = true;
        // OptionButton's selected label does not clip long account names by default.
        foreach (var row in Recipient.Children.OfType<BoxContainer>())
        {
            foreach (var caption in row.Children.OfType<Label>())
            {
                caption.ClipText = true;
                caption.RemoveStyleClass(OptionButton.StyleClassOptionButton);
                caption.Align = Label.AlignMode.Left;
            }
        }
        Balance.FontOverride = Wh40kOnboardingTypography.Text(IoCManager.Resolve<IResourceCache>(), 24);
        PayButton.Label.FontOverride = Wh40kOnboardingTypography.Text(IoCManager.Resolve<IResourceCache>(), 12);
        PayButton.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#705B35"), BorderColor = Color.FromHex("#BFA36D"), BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 14, ContentMarginRightOverride = 14, ContentMarginTopOverride = 6, ContentMarginBottomOverride = 6,
        };
        Recipient.OnItemSelected += args =>
        {
            Recipient.SelectId(args.Id);
            if (_recipient != _members[args.Id].UserId)
                _requestId = Guid.NewGuid();
            _recipient = _members[args.Id].UserId;
            ResetConfirmation();
            UpdateForm();
        };
        SelfButton.OnPressed += _ =>
        {
            var index = Array.FindIndex(_members, m => m.IsSelf);
            if (index < 0)
                return;
            if (_recipient != _members[index].UserId)
                _requestId = Guid.NewGuid();
            _recipient = _members[index].UserId;
            Recipient.SelectId(index);
            ResetConfirmation();
            UpdateForm();
        };
        Amount.OnTextChanged += _ => { _requestId = Guid.NewGuid(); ResetConfirmation(); UpdateForm(); };
        Memo.OnTextChanged += _ => { _requestId = Guid.NewGuid(); ResetConfirmation(); UpdateForm(); };
        MaxButton.OnPressed += _ => { Amount.Text = Math.Min(_treasury?.Balance ?? 0, int.MaxValue).ToString(CultureInfo.InvariantCulture); _requestId = Guid.NewGuid(); ResetConfirmation(); UpdateForm(); };
        PayButton.OnPressed += _ =>
        {
            if (_recipient is not { } recipient || !ValidAmount(out var amount) || _pending || _treasury?.Available != true)
                return;
            SetPending(true);
            PayoutRequested?.Invoke(recipient, new FactionBankPayout(amount, Memo.Text.Trim(), _requestId));
        };
    }

    public void UpdateSnapshot(Wh40kFactionUiSnapshot? snapshot, bool pending)
    {
        var previousRecipient = _recipient;
        _treasury = snapshot?.Treasury;
        _members = snapshot?.Members.ToArray() ?? [];
        _pending = pending;
        Recipient.Clear();
        if (!_members.Any(m => m.UserId == _recipient))
            _recipient = _members.FirstOrDefault(m => m.IsSelf)?.UserId;
        for (var i = 0; i < _members.Length; i++)
        {
            var member = _members[i];
            Recipient.AddItem(member.Ckey + (member.IsSelf ? " " + Loc.GetString("wh40k-faction-self") : "") +
                (member.IsOnline ? "" : " · " + Loc.GetString("wh40k-faction-bank-offline")), i);
            if (member.UserId == _recipient)
                Recipient.SelectId(i);
        }
        Balance.Text = _treasury?.Available == true ? BankSystemExtensions.ToSpesoString(_treasury.Balance)
            : Loc.GetString("wh40k-faction-bank-unavailable");
        Balance.ToolTip = Balance.Text;
        History.RemoveAllChildren();
        foreach (var entry in _treasury?.Entries ?? [])
        {
            var row = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4 };
            var text = new RichTextLabel();
            var time = entry.CreatedAt.ToLocalTime().ToString("g", CultureInfo.CurrentCulture);
            text.SetMessage(Loc.GetString(entry.Kind == FactionBankEntryKind.Income ? "wh40k-faction-bank-income-entry" : "wh40k-faction-bank-payout-entry",
                ("name", entry.Name), ("amount", BankSystemExtensions.ToSpesoString(entry.Amount)),
                ("gross", BankSystemExtensions.ToSpesoString(entry.Gross)), ("time", time)), FactionUiPresentation.Text);
            text.AddStyleClass("Wh40kOnboardingBodyCompact");
            row.AddChild(text);
            if (entry.Kind == FactionBankEntryKind.Payout)
            {
                var detail = new RichTextLabel();
                detail.AddStyleClass("Wh40kOnboardingBodySmall");
                detail.SetMessage(FormattedMessage.FromUnformatted((string.IsNullOrWhiteSpace(entry.Memo)
                    ? Loc.GetString("wh40k-faction-bank-no-memo") : entry.Memo) +
                    (entry.Pending ? " · " + Loc.GetString("wh40k-faction-bank-pending-delivery") : "")), FactionUiPresentation.Muted);
                row.AddChild(detail);
            }
            History.AddChild(row);
        }
        if (History.ChildCount == 0)
            History.AddChild(new Label { Text = Loc.GetString("wh40k-faction-bank-empty-history"), FontColorOverride = FactionUiPresentation.Muted });
        if (previousRecipient != _recipient || _pending)
        {
            ResetConfirmation();
            if (previousRecipient != _recipient)
                _requestId = Guid.NewGuid();
        }
        UpdateForm();
    }

    public void SetPending(bool pending)
    {
        if (_pending != pending)
            ResetConfirmation();
        _pending = pending;
        UpdateForm();
    }

    public void CompleteOperation(Wh40kFactionUiOperationStatus status)
    {
        if (status is not (Wh40kFactionUiOperationStatus.PayoutSent or Wh40kFactionUiOperationStatus.PayoutQueued))
            return;
        Amount.Text = "";
        _requestId = Guid.NewGuid();
        ResetConfirmation();
        UpdateForm();
    }

    private bool ValidAmount(out int amount) => int.TryParse(Amount.Text, NumberStyles.None, CultureInfo.InvariantCulture, out amount) &&
        amount > 0 && amount <= (_treasury?.Balance ?? 0) && Memo.Text.Length <= FactionBankRules.MaxMemoLength && !Memo.Text.Any(char.IsControl);

    private void UpdateForm()
    {
        var disabled = _pending || _treasury?.Available != true;
        Recipient.Disabled = SelfButton.Disabled = MaxButton.Disabled = disabled;
        Amount.Editable = Memo.Editable = !disabled;
        var canPay = !disabled && _recipient != null && ValidAmount(out _);
        if (!canPay)
            ResetConfirmation();
        PayButton.Disabled = !canPay;
        var member = _members.FirstOrDefault(m => m.UserId == _recipient);
        Recipient.ToolTip = member?.Ckey;
        PayoutSummary.SetMessage(member != null && ValidAmount(out var amount)
            ? Loc.GetString("wh40k-faction-bank-summary", ("name", member.Ckey), ("amount", BankSystemExtensions.ToSpesoString(amount)))
            : Loc.GetString("wh40k-faction-bank-form-hint"), FactionUiPresentation.Gold);
    }

    private void ResetConfirmation() { PayButton.IsConfirming = false; PayButton.Text = Loc.GetString("wh40k-faction-bank-pay"); }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        Balance.Measure(new Vector2(float.PositiveInfinity, availableSize.Y));
        BalanceRow.Orientation = availableSize.X < Math.Max(560, Balance.DesiredSize.X + 360)
            ? LayoutOrientation.Vertical : LayoutOrientation.Horizontal;
        PaymentFields.Orientation = availableSize.X < 460 ? LayoutOrientation.Vertical : LayoutOrientation.Horizontal;
        return base.MeasureOverride(availableSize);
    }
}

public sealed class FactionTreasuryColumns : BoxContainer
{
    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        var horizontal = float.IsFinite(availableSize.X) && availableSize.X >= 720;
        Orientation = horizontal ? LayoutOrientation.Horizontal : LayoutOrientation.Vertical;
        var width = Math.Max(0, availableSize.X - (SeparationOverride ?? 0));
        for (var i = 0; i < ChildCount; i++)
            GetChild(i).MaxWidth = horizontal ? width * (i == 0 ? 0.6f : 0.4f) : float.PositiveInfinity;
        return base.MeasureOverride(availableSize);
    }
}
