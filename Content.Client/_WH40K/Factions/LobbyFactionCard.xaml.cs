using System.Numerics;
using Content.Client._WH40K.CharacterCreation;
using Content.Shared._Mono.Company;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Factions;

[GenerateTypedNameReferences]
public sealed partial class LobbyFactionCard : PanelContainer, IFactionCatalogCard
{
    public Control Root => this;
    public event Action? DetailsPressed;
    public event Action? ActionPressed;

    public LobbyFactionCard()
    {
        RobustXamlLoader.Load(this);
        var resources = IoCManager.Resolve<IResourceCache>();
        FactionName.FontOverride = Wh40kOnboardingTypography.Display(resources, 23);
        Membership.FontOverride = Wh40kOnboardingTypography.Text(resources, 11);
        Summary.AddStyleClass("Wh40kOnboardingBodyCompact");
        Overview.AddStyleClass("Wh40kOnboardingBodySmall");
        DetailsButton.OnPressed += _ => DetailsPressed?.Invoke();
        ActionButton.OnPressed += _ => ActionPressed?.Invoke();
    }

    public void SetFaction(CompanyPrototype faction, string membership, string action, bool disabled, bool selected)
    {
        PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex(selected ? "#302D27" : "#242424"),
            BorderColor = Color.FromHex("#C0A66E"),
            BorderThickness = selected ? new Thickness(2, 0, 0, 0) : new Thickness(0),
            ContentMarginLeftOverride = 16,
            ContentMarginRightOverride = 16,
            ContentMarginTopOverride = 10,
            ContentMarginBottomOverride = 10,
        };
        Emblem.Visible = faction.Image != null;
        if (faction.Image is { } image)
            Emblem.TexturePath = image;
        FactionName.Text = faction.Name;
        Summary.SetMessage(FactionUiPresentation.Summary(faction), Color.FromHex("#C7C3CC"));
        Membership.Text = membership;
        Membership.Visible = membership != Loc.GetString("wh40k-faction-application-required");
        ActionButton.Text = action;
        ActionButton.Disabled = disabled;
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        EmblemFrame.SetSize = availableSize.X < 520 ? new Vector2(72, 72) : new Vector2(144, 144);
        return base.MeasureOverride(availableSize);
    }

    public void UpdateOverview(string overview) =>
        Overview.SetMessage(FormattedMessage.FromUnformatted(overview), Color.FromHex("#AAA4AF"));
}
