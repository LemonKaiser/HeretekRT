using System.Numerics;
using Content.Client._WH40K.CharacterCreation;
using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Company;
using Content.Shared._WH40K.Factions;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Factions;

[GenerateTypedNameReferences]
public sealed partial class LobbyFactionProfileWindow : FancyWindow, IFactionProfileWindow
{
    private readonly string _factionId;
    public event Action? ActionPressed;

    public LobbyFactionProfileWindow(CompanyPrototype faction)
    {
        RobustXamlLoader.Load(this);
        _factionId = faction.ID;
        ProfileTabs.SetTabTitle(0, Loc.GetString("wh40k-faction-about"));
        ProfileTabs.SetTabTitle(1, Loc.GetString("wh40k-faction-rel-tab"));
        UpdateRelations([]);
        var resources = IoCManager.Resolve<IResourceCache>();
        Title = faction.Name;
        FactionName.Text = faction.Name;
        FactionName.FontOverride = Wh40kOnboardingTypography.Display(resources, 29);
        Summary.AddStyleClass("Wh40kOnboardingBodyCompact");
        Overview.AddStyleClass("Wh40kOnboardingBodyCompact");
        Description.AddStyleClass("Wh40kOnboardingBodyText");
        ActionHint.AddStyleClass("Wh40kOnboardingBodySmall");
        Membership.FontOverride = Wh40kOnboardingTypography.Text(resources, 12);
        Divider.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#68604F") };
        ActionPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#2B2821"),
            BorderColor = Color.FromHex("#A88C50"),
            BorderThickness = new Thickness(2, 0, 0, 0),
            ContentMarginLeftOverride = 14,
            ContentMarginRightOverride = 14,
            ContentMarginTopOverride = 12,
            ContentMarginBottomOverride = 12,
        };
        Emblem.Visible = faction.Image != null;
        if (faction.Image is { } image)
            Emblem.TexturePath = image;
        Summary.SetMessage(FactionUiPresentation.Summary(faction), Color.FromHex("#BDB8C4"));
        Description.SetMessage(string.IsNullOrEmpty(faction.Description)
            ? Loc.GetString("humanoid-profile-editor-company-no-description")
            : Loc.GetString(faction.Description), Color.FromHex("#DDD8E2"));
        DismissButton.OnPressed += _ => Close();
        ActionButton.OnPressed += _ => ActionPressed?.Invoke();
    }

    public void Show() => OpenCentered();

    public void UpdateProfile(FactionProfile profile) => ProfileSections.UpdateProfile(profile);
    public void UpdateRelations(FactionRelation[] relations) => PublicRelations.UpdateRelations(_factionId, relations);

    public void UpdateAction(string membership, string action, string hint, bool disabled)
    {
        Membership.Text = membership;
        ActionHint.SetMessage(hint, Color.FromHex("#B8B2BF"));
        ActionButton.Text = FactionUiPresentation.ProfileAction(action);
        ActionButton.Disabled = disabled;
    }

    public void UpdateOverview(string overview) =>
        Overview.SetMessage(FormattedMessage.FromUnformatted(overview), Color.FromHex("#C7BDAB"));

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        EmblemFrame.SetSize = availableSize.X < 560 ? new Vector2(112, 112) : new Vector2(176, 176);
        var orientation = availableSize.X < 600
            ? BoxContainer.LayoutOrientation.Vertical : BoxContainer.LayoutOrientation.Horizontal;
        if (ActionLayout.Orientation != orientation)
            ActionLayout.Orientation = orientation;
        return base.MeasureOverride(availableSize);
    }
}
