using Content.Shared._WH40K.Lathe;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._WH40K.Lathe.UI;

[GenerateTypedNameReferences]
public sealed partial class Wh40kLatheSupplyStatus : BoxContainer
{
    [Dependency] private IEntityManager _entityManager = default!;

    private Wh40kFabricationSiloSystem? _silos;
    private EntityUid? _owner;
    private bool? _parts;
    private bool? _chemicals;

    public Wh40kLatheSupplyStatus()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SetLinks(false, false);
    }

    public void SetOwner(EntityUid owner)
    {
        _owner = owner;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_owner is not { } owner)
            return;

        _silos ??= _entityManager.System<Wh40kFabricationSiloSystem>();
        SetLinks(_silos.GetLinkedSilo(owner, Wh40kFabricationSiloKind.Parts) != null,
            _silos.GetLinkedSilo(owner, Wh40kFabricationSiloKind.Chemicals) != null);
    }

    private void SetLinks(bool parts, bool chemicals)
    {
        if (_parts == parts && _chemicals == chemicals)
            return;

        _parts = parts;
        _chemicals = chemicals;
        PartsSiloStatus.Text = Loc.GetString(parts ? "lathe-menu-parts-silo-online" : "lathe-menu-parts-silo-offline");
        ChemicalSiloStatus.Text = Loc.GetString(chemicals ? "lathe-menu-chemical-silo-online" : "lathe-menu-chemical-silo-offline");
    }
}
