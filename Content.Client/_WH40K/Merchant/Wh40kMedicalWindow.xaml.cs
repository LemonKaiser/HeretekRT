using Content.Shared._NF.Bank.Components;
using Content.Shared._WH40K.Merchant;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._WH40K.Merchant;

[GenerateTypedNameReferences]
public sealed partial class Wh40kMedicalWindow : DefaultWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IEntityManager _entities = default!;
    [Dependency] private readonly IPlayerManager _players = default!;

    private Wh40kMedicalQuoteMessage? _quote;
    private TimeSpan _cooldownAt;
    private bool _pending;
    private int? _displayedBalance;
    private int _displayedCooldown;

    public event Action? OnRefresh;
    public event Action? OnConfirm;

    public Wh40kMedicalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ConfirmButton.OnPressed += _ => OnConfirm?.Invoke();
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        ResultLabel.Text = string.Empty;
    }

    public void UpdateQuote(Wh40kMedicalQuoteMessage quote)
    {
        _quote = quote;
        _cooldownAt = _timing.CurTime + TimeSpan.FromSeconds(quote.Cooldown);
        UpdateLabels(force: true);
    }

    public void SetPending(bool pending)
    {
        _pending = pending;
        UpdateLabels(force: true);
    }

    public void ShowResult(string result)
    {
        ResultLabel.Text = Loc.GetString(result);
        ResultLabel.FontColorOverride = result == "wh40k-medical-success"
            ? Color.FromHex("#70c080")
            : Color.FromHex("#e06666");
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateLabels();
    }

    private void UpdateLabels(bool force = false)
    {
        if (_quote == null)
            return;

        var balance = _quote.Balance;
        if (_players.LocalEntity is { } body && _entities.TryGetComponent<BankAccountComponent>(body, out var bank))
            balance = bank.Balance;

        var seconds = Math.Max(0, (int) Math.Ceiling((_cooldownAt - _timing.CurTime).TotalSeconds));
        if (!force && balance == _displayedBalance && seconds == _displayedCooldown)
            return;
        _displayedBalance = balance;
        _displayedCooldown = seconds;

        // Diagnostic information
        var damage = _quote.Damage;
        DamageValue.Text = Loc.GetString("wh40k-medical-damage-val", ("amount", damage));
        DamageValue.FontColorOverride = damage > 0 ? Color.FromHex("#e06666") : Color.FromHex("#a0b0a0");

        // Financial information
        PriceValue.Text = Loc.GetString("wh40k-medical-credits-val", ("amount", _quote.Price));
        PriceValue.FontColorOverride = _quote.Price > 0 ? Color.FromHex("#e5c879") : Color.FromHex("#a0b0a0");
        BalanceValue.Text = Loc.GetString("wh40k-medical-credits-val", ("amount", $"{balance:N0}"));

        // Cooldown
        if (seconds > 0)
        {
            var remaining = $"{seconds / 60:D2}:{seconds % 60:D2}";
            CooldownBadge.Text = Loc.GetString("wh40k-medical-cooldown-badge", ("remaining", remaining));
            CooldownBadge.FontColorOverride = Color.FromHex("#e5c879");
        }
        else
        {
            CooldownBadge.Text = Loc.GetString("wh40k-medical-terminal-ready");
            CooldownBadge.FontColorOverride = Color.FromHex("#70c080");
        }

        // Assessment status message
        if (_pending)
        {
            StatusMessage.Text = Loc.GetString("wh40k-medical-pending");
            StatusMessage.FontColorOverride = Color.FromHex("#e5c879");
        }
        else if (_quote.Status == "wh40k-medical-cooldown")
        {
            if (seconds > 0)
            {
                var remaining = $"{seconds / 60:D2}:{seconds % 60:D2}";
                StatusMessage.Text = Loc.GetString("wh40k-medical-wait", ("remaining", remaining));
                StatusMessage.FontColorOverride = Color.FromHex("#e5c879");
            }
            else
            {
                StatusMessage.Text = Loc.GetString("wh40k-medical-reexamine");
                StatusMessage.FontColorOverride = Color.FromHex("#c0c0c0");
            }
        }
        else
        {
            StatusMessage.Text = Loc.GetString(_quote.Status);
            StatusMessage.FontColorOverride = _quote.Status switch
            {
                "wh40k-medical-ready" => Color.FromHex("#e06666"),
                "wh40k-medical-healthy" => Color.FromHex("#70c080"),
                _ => Color.FromHex("#c0c0c0"),
            };
        }

        // Action button states and labels
        StatusMessage.ToolTip = StatusMessage.Text;
        var canConfirm = !_pending && _quote.Quote != Guid.Empty && _quote.Status == "wh40k-medical-ready" && balance >= _quote.Price;
        ConfirmButton.Disabled = !canConfirm;

        if (_pending)
        {
            ConfirmButton.Text = Loc.GetString("wh40k-medical-pending");
        }
        else if (_quote.Status == "wh40k-medical-healthy")
        {
            ConfirmButton.Text = Loc.GetString("wh40k-medical-btn-healthy");
        }
        else if (_quote.Status == "wh40k-medical-cooldown" && seconds > 0)
        {
            var remaining = $"{seconds / 60:D2}:{seconds % 60:D2}";
            ConfirmButton.Text = Loc.GetString("wh40k-medical-btn-cooldown", ("remaining", remaining));
        }
        else if (balance < _quote.Price && _quote.Price > 0)
        {
            ConfirmButton.Text = Loc.GetString("wh40k-medical-btn-no-money", ("amount", _quote.Price));
        }
        else
        {
            ConfirmButton.Text = Loc.GetString("wh40k-medical-confirm-price", ("amount", _quote.Price));
        }
    }
}
