using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._WH40K.PersistentInventory;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using Robust.Shared.Prototypes;

namespace Content.Client._WH40K.PersistentInventory;

[GenerateTypedNameReferences]
public sealed partial class PersistentInventoryAdminWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    public event Action<string>? PlayerSelected;
    public event Action<Guid, Guid>? SnapshotSelected;
    public event Action<PersistentInventoryAdminRequest>? ActionRequested;

    private PersistentInventoryAdminEuiState? _state;
    private bool _pending;
    private readonly List<PersistentInventoryAdminItem> _visibleItems = new();

    public PersistentInventoryAdminWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Tabs.SetTabTitle(0, Loc.GetString("persistentinv-admin-overview"));
        Tabs.SetTabTitle(1, Loc.GetString("persistentinv-admin-snapshots"));
        Tabs.SetTabTitle(2, Loc.GetString("persistentinv-admin-history"));
        Tabs.SetTabTitle(3, Loc.GetString("persistentinv-admin-actions"));
        Load.OnPressed += _ => SelectPlayer(Target.Text);
        Target.OnTextEntered += _ => SelectPlayer(Target.Text);
        Target.OnTextChanged += _ => { ResetConfirmations(); UpdateButtons(); };
        Refresh.OnPressed += _ => SelectPlayer(_state?.UserId?.ToString() ?? Target.Text);
        Players.OnSelectionChanged += player =>
        {
            if (player != null)
                SelectPlayer(player.Username);
        };
        Snapshots.OnItemSelected += args =>
        {
            if (_pending || _state?.UserId is not { } user || args.Id < 0 || args.Id >= _state.Snapshots.Length)
                return;
            Snapshots.SelectId(args.Id);
            SetPending(true);
            SnapshotSelected?.Invoke(user, _state.Snapshots[args.Id].Id);
        };
        Items.OnItemSelected += args => SetText(ItemDetails, _visibleItems[args.ItemIndex].Details);
        ItemSearch.OnTextChanged += _ => PopulateItems();
        HistorySearch.OnTextChanged += _ => PopulateHistory();
        Reason.OnTextChanged += _ => { ResetConfirmations(); UpdateButtons(); };
        Force.OnPressed += _ => { ResetConfirmations(); UpdateButtons(); };
        Save.OnPressed += _ => Request(PersistentInventoryAdminAction.Save);
        Invalidate.OnPressed += _ => Request(PersistentInventoryAdminAction.Invalidate);
        Quarantine.OnPressed += _ => Request(PersistentInventoryAdminAction.Quarantine);
        Rollback.OnPressed += _ => Request(PersistentInventoryAdminAction.Rollback);
        Recover.OnPressed += _ => Request(PersistentInventoryAdminAction.RecoverLost);
        Validate.OnPressed += _ => Request(PersistentInventoryAdminAction.Validate);
        ReloadCache.OnPressed += _ => Request(PersistentInventoryAdminAction.ReloadCache);
        OpenLogs.OnPressed += _ => Request(PersistentInventoryAdminAction.OpenLogs);
        UpdateButtons();
    }

    private void SelectPlayer(string target)
    {
        if (_pending || string.IsNullOrWhiteSpace(target) || target.Length > 128)
            return;
        SetPending(true);
        PlayerSelected?.Invoke(target.Trim());
    }

    public void Apply(PersistentInventoryAdminEuiState state)
    {
        var previous = _state;
        _state = state;
        if (previous == null || previous.UserId != state.UserId || previous.Revision != state.Revision ||
            previous.SelectedSnapshot != state.SelectedSnapshot || state.Busy)
            ResetConfirmations();
        if (previous?.UserId != state.UserId)
        {
            Target.Text = state.PlayerName;
            ItemSearch.Text = string.Empty;
            HistorySearch.Text = string.Empty;
            Reason.Text = string.Empty;
            Force.Pressed = false;
        }
        if (!state.Busy && state.UserId != null)
            Target.Text = state.PlayerName;
        Identity.Text = state.UserId == null ? Loc.GetString("persistentinv-admin-select-player") :
            $"{state.PlayerName} · {state.UserId}";
        Identity.ToolTip = Identity.Text;
        SetText(Overview, state.Overview);
        SetText(SnapshotInfo, state.SnapshotDetails);
        SetText(Result, state.Message);
        if (previous == null || !previous.Snapshots.SequenceEqual(state.Snapshots) || previous.SelectedSnapshot != state.SelectedSnapshot)
        {
            Snapshots.Clear();
            for (var i = 0; i < state.Snapshots.Length; i++)
            {
                Snapshots.AddItem(state.Snapshots[i].Label, i);
                if (state.Snapshots[i].Id == state.SelectedSnapshot)
                    Snapshots.SelectId(i);
            }
        }
        if (previous == null || previous.SelectedSnapshot != state.SelectedSnapshot || !previous.Items.SequenceEqual(state.Items))
            PopulateItems();
        if (previous?.History != state.History)
            PopulateHistory();
        SetPending(state.Busy);
    }

    public void SetPending(bool pending)
    {
        _pending = pending;
        Busy.Visible = pending;
        UpdateButtons();
    }

    private void PopulateItems()
    {
        var id = Items.GetSelected().FirstOrDefault()?.Metadata as int?;
        Items.Clear();
        _visibleItems.Clear();
        if (_state == null)
            return;
        foreach (var item in _state.Items)
        {
            var name = _prototypes.TryIndex<EntityPrototype>(item.Prototype, out var prototype) ? prototype.Name : item.Prototype;
            var caption = $"#{item.Id} {name} ({item.Prototype}) · {item.Location}";
            if (!string.IsNullOrWhiteSpace(ItemSearch.Text) && !caption.Contains(ItemSearch.Text, StringComparison.OrdinalIgnoreCase))
                continue;
            _visibleItems.Add(item);
            Items.AddItem(caption, metadata: item.Id);
        }
        var index = _visibleItems.FindIndex(item => item.Id == id);
        if (index < 0 && _visibleItems.Count > 0)
            index = 0;
        if (index >= 0)
        {
            Items[index].Selected = true;
            SetText(ItemDetails, _visibleItems[index].Details);
        }
        else
            SetText(ItemDetails, Loc.GetString("persistentinv-admin-no-items"));
    }

    private void PopulateHistory()
    {
        var text = (_state?.History ?? string.Empty).Replace("\r\n", "\n", StringComparison.Ordinal);
        if (!string.IsNullOrWhiteSpace(HistorySearch.Text))
            text = string.Join("\n\n", text.Split("\n\n", StringSplitOptions.RemoveEmptyEntries)
                .Where(entry => entry.Contains(HistorySearch.Text, StringComparison.OrdinalIgnoreCase)));
        SetText(History, text);
    }

    private void Request(PersistentInventoryAdminAction action)
    {
        if (_pending || !TargetMatches || _state?.UserId is not { } user)
            return;
        SetPending(true);
        ActionRequested?.Invoke(new(user, _state.Revision, action, _state.SelectedSnapshot, Reason.Text.Trim(), Force.Pressed));
    }

    private void UpdateButtons()
    {
        var selected = TargetMatches;
        var reason = !string.IsNullOrWhiteSpace(Reason.Text) && Reason.Text.Length <= 512;
        Load.Disabled = _pending;
        Target.Editable = !_pending;
        Refresh.Disabled = _pending || !selected;
        Snapshots.Disabled = _pending || !selected || _state?.Snapshots.Length is not > 0;
        Validate.Disabled = _pending || !selected || _state?.SelectedSnapshot == null;
        ReloadCache.Disabled = _pending || !selected;
        OpenLogs.Disabled = _pending || !selected || _state?.CanViewLogs != true;
        Save.Disabled = _pending || !selected || !reason || _state?.CanSave != true;
        Invalidate.Disabled = _pending || !selected || !reason || _state?.CanInvalidate != true;
        Quarantine.Disabled = _pending || !selected || !reason || _state?.CanQuarantine != true;
        Rollback.Disabled = _pending || !selected || !reason || _state?.CanRollback != true || _state.SelectedSnapshot == null;
        Recover.Disabled = _pending || !selected || !reason || _state?.CanRecoverLost != true;
    }

    private bool TargetMatches => _state?.UserId is { } user &&
        (Target.Text.Trim().Equals(_state.PlayerName, StringComparison.OrdinalIgnoreCase) ||
         Target.Text.Trim().Equals(user.ToString(), StringComparison.OrdinalIgnoreCase));

    private void ResetConfirmations()
    {
        foreach (var button in new[] { Save, Invalidate, Quarantine, Rollback, Recover })
        {
            button.IsConfirming = false;
            button.Text = button.Text;
            button.Disabled = true;
        }
    }

    private static void SetText(TextEdit control, string text)
    {
        if (Rope.Collapse(control.TextRope) != text)
            control.TextRope = new Rope.Leaf(text);
    }
}
