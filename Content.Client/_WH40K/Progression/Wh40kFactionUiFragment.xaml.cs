using System.Linq;
using Content.Client._WH40K.Factions;
using Content.Client.PDA;
using Content.Shared._Mono.Company;
using Content.Shared._WH40K.Factions;
using Content.Shared._WH40K.Progression;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Progression;

[GenerateTypedNameReferences]
public sealed partial class Wh40kFactionUiFragment : BoxContainer
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    private Wh40kFactionUiSnapshot? _snapshot;
    private FactionDashboardWindow? _window;
    private bool _pending;
    private float _pendingSeconds;

    public event Action<Wh40kFactionUiAction, string, Guid>? OnAction;
    public event Action<string, FactionProfile>? ProfileSaveRequested;
    public event Action<string, Guid, FactionBankPayout>? PayoutRequested;
    public event Action<Wh40kFactionUiAction, string, FactionSocialRequest>? SocialRequested;

    public Wh40kFactionUiFragment()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        OpenButton.StyleBoxOverride = PdaTerminalPalette.CreateButton(accented: true);
        CurrentPanel.PanelOverride = FactionUiPresentation.Panel(FactionUiPresentation.Gold);
        OpenButton.OnPressed += _ => OpenFullWindow();
        UpdateSnapshot(null, Wh40kFactionUiOperationStatus.None);
    }

    public void OpenFullWindow()
    {
        _window?.Close();
        _window = new FactionDashboardWindow();
        _window.OnClose += () => _window = null;
        _window.Dashboard.OnAction += (action, faction, user) => OnAction?.Invoke(action, faction, user);
        _window.Dashboard.ProfileSaveRequested += (faction, profile) => ProfileSaveRequested?.Invoke(faction, profile);
        _window.Dashboard.PayoutRequested += (faction, recipient, payout) => PayoutRequested?.Invoke(faction, recipient, payout);
        _window.Dashboard.SocialRequested += (action, faction, social) => SocialRequested?.Invoke(action, faction, social);
        _window.UpdateSnapshot(_snapshot, Wh40kFactionUiOperationStatus.None, _pending);
        _window.OpenCentered();
        if (!_pending)
            OnAction?.Invoke(Wh40kFactionUiAction.Refresh, "", default);
    }

    public void SetPending(bool pending)
    {
        _pending = pending;
        _pendingSeconds = 0;
        OpenButton.Disabled = pending;
        StatusLabel.Visible = pending;
        if (pending)
            StatusLabel.SetMessage(Loc.GetString("wh40k-faction-loading"), FactionUiPresentation.Muted);
        _window?.Dashboard.SetPending(pending);
    }

    public void UpdateSnapshot(Wh40kFactionUiSnapshot? snapshot, Wh40kFactionUiOperationStatus status)
    {
        _snapshot = snapshot;
        _pending = false;
        OpenButton.Disabled = snapshot == null;
        StatusLabel.Visible = status != Wh40kFactionUiOperationStatus.None;
        StatusLabel.SetMessage(FactionUiPresentation.Status(status), FactionUiPresentation.Gold);
        var hasFaction = snapshot?.FactionId != null;
        var manager = snapshot?.ViewerRole is FactionRole.Leader or FactionRole.Officer;
        CurrentEmblem.Visible = hasFaction;
        CurrentRole.Visible = hasFaction;
        Overview.Visible = hasFaction;
        RequestCount.Visible = hasFaction && manager;
        CurrentName.Text = Loc.GetString(snapshot == null ? "wh40k-faction-loading" : "wh40k-faction-unaffiliated");
        CurrentName.FontColorOverride = FactionUiPresentation.Text;
        if (hasFaction && _prototypes.TryIndex<CompanyPrototype>(snapshot!.FactionId!, out var faction))
        {
            CurrentName.Text = faction.Name;
            CurrentName.FontColorOverride = faction.Color;
            CurrentEmblem.Visible = faction.Image != null;
            if (faction.Image is { } image)
                CurrentEmblem.TexturePath = image;
            CurrentRole.Text = Loc.GetString("wh40k-faction-your-role", ("role", FactionUiPresentation.Role(snapshot.ViewerRole ?? FactionRole.Member,
                snapshot.AvailableFactions.FirstOrDefault(f => f.Id == faction.ID)?.Profile)));
            Overview.SetMessage(FormattedMessage.FromUnformatted(FactionUiPresentation.Overview(
                snapshot.AvailableFactions.FirstOrDefault(f => f.Id == faction.ID))), FactionUiPresentation.Muted);
            RequestCount.Text = Loc.GetString("wh40k-faction-requests-count", ("count", snapshot.Requests.Count));
        }
        OpenButton.Text = Loc.GetString(!hasFaction ? "wh40k-faction-open-directory"
            : manager ? "wh40k-faction-open-management" : "wh40k-faction-open-overview");
        _window?.UpdateSnapshot(snapshot, status, false);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_pending)
            return;
        _pendingSeconds += args.DeltaSeconds;
        if (_pendingSeconds < 12)
            return;
        UpdateSnapshot(_snapshot, Wh40kFactionUiOperationStatus.Failed);
    }

    protected override void ExitedTree()
    {
        _window?.Close();
        _window = null;
        base.ExitedTree();
    }
}
