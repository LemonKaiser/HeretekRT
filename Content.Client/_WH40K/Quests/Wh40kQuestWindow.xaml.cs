using Content.Shared._WH40K.Npcs;
using Content.Shared._WH40K.Quests;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._WH40K.Quests;

[GenerateTypedNameReferences]
public sealed partial class Wh40kQuestWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    private Wh40kQuestUiRequest? _retry;
    private readonly List<Button> _actions = [];
    public event Action<Wh40kQuestUiRequest>? Request;

    public Wh40kQuestWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        RefreshButton.OnPressed += _ => Send(new(Wh40kQuestUiAction.Refresh, Guid.NewGuid()));
    }

    private void Send(Wh40kQuestUiRequest request)
    {
        _retry = request.Action == Wh40kQuestUiAction.Refresh ? null : request;
        foreach (var button in _actions) button.Disabled = true;
        RefreshButton.Disabled = true;
        ResultLabel.Text = Loc.GetString("wh40k-quest-result-pending");
        Request?.Invoke(request);
    }

    public void ShowSnapshot(Wh40kQuestUiSnapshot snapshot)
    {
        ResultLabel.Text = Loc.GetString("wh40k-quest-result-" + snapshot.Result.ToString().ToLowerInvariant());
        RefreshButton.Disabled = snapshot.Pending;
        if (snapshot.Pending)
        { foreach (var button in _actions) button.Disabled = true; return; }
        Rows.RemoveAllChildren();
        _actions.Clear();
        if (snapshot.Result == Wh40kQuestOperationResult.PersistenceUnavailable && _retry != null)
        {
            var retry = _retry;
            AddButton(Rows, "wh40k-quest-ui-retry", () => Send(retry));
        }
        else _retry = null;
        AddSection("wh40k-quest-ui-offers", snapshot.Offers, true);
        AddSection("wh40k-quest-ui-active", snapshot.Active, false);
        AddSection("wh40k-quest-ui-history", snapshot.History, false, true);
    }

    private void AddSection(string heading, List<Wh40kQuestUiRow> rows, bool offer, bool history = false)
    {
        Rows.AddChild(new Label { Text = Loc.GetString(heading), Margin = new Thickness(0, 12, 0, 4) });
        if (rows.Count == 0) Rows.AddChild(new Label { Text = Loc.GetString("wh40k-quest-ui-empty") });
        foreach (var row in rows)
        {
            var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, Margin = new Thickness(0, 4) };
            Rows.AddChild(box);
            box.AddChild(new Label { Text = Loc.GetString(row.Title) });
            var description = new RichTextLabel(); description.SetMessage(Loc.GetString(row.Description)); box.AddChild(description);
            box.AddChild(new Label { Text = Loc.GetString("wh40k-quest-ui-scope-" + row.OwnerScope.ToString().ToLowerInvariant()) + " · " +
                Loc.GetString("wh40k-quest-ui-state-" + row.State.ToString().ToLowerInvariant()) });
            if (row.Binding != Wh40kQuestBindingState.Bound)
                box.AddChild(new Label { Text = Loc.GetString("wh40k-quest-ui-binding-" + row.Binding.ToString().ToLowerInvariant()) });
            if (row.Issuer != null && _prototypes.TryIndex<Wh40kNpcAnchorPrototype>(row.Issuer, out var anchor) &&
                _prototypes.TryIndex(anchor.Profile, out var profile))
                box.AddChild(new Label { Text = Loc.GetString("wh40k-quest-ui-issuer", ("issuer", Loc.GetString(profile.Name))) });
            if (row.Deadline != null) box.AddChild(new Label { Text = Loc.GetString("wh40k-quest-ui-deadline", ("time", row.Deadline)) });
            if (offer && row.OfferExpiry != null) box.AddChild(new Label { Text = Loc.GetString("wh40k-quest-ui-offer-expiry", ("time", row.OfferExpiry)) });
            foreach (var objective in row.Objectives)
            {
                var line = new RichTextLabel();
                line.SetMessage(Loc.GetString("wh40k-quest-ui-objective", ("text", Loc.GetString(objective.Text)), ("count", objective.Count), ("required", objective.Required)));
                box.AddChild(line);
                if (!offer && !history && row.CanAct && objective.Kind.IsSubmission() && objective.Count < objective.Required)
                    AddButton(box, "wh40k-quest-ui-submit", () => Send(new(Wh40kQuestUiAction.Submit, Guid.NewGuid(), row.Id, row.Revision, objective.Id)));
            }
            foreach (var reward in history && row.State != Wh40kQuestState.Completed ? [] : row.Rewards)
            {
                var name = reward.Item is {} item && _prototypes.TryIndex<EntityPrototype>(item, out var prototype) ? prototype.Name :
                    Loc.GetString("wh40k-quest-ui-reward-" + reward.Kind.ToString().ToLowerInvariant());
                box.AddChild(new Label { Text = Loc.GetString("wh40k-quest-ui-reward", ("amount", reward.Amount), ("name", name),
                    ("state", Loc.GetString("wh40k-quest-ui-reward-state-" + reward.State.ToString().ToLowerInvariant()))) });
            }
            if (offer && row.CanAct) AddButton(box, "wh40k-quest-ui-accept", () => Send(new(Wh40kQuestUiAction.Accept, Guid.NewGuid(), row.Id)));
            if (!offer && !history)
            {
                if (row.CanAct && row.State == Wh40kQuestState.ReadyToTurnIn)
                    AddButton(box, "wh40k-quest-ui-turn-in", () => Send(new(Wh40kQuestUiAction.TurnIn, Guid.NewGuid(), row.Id, row.Revision)));
                AddButton(box, "wh40k-quest-ui-abandon", () => Send(new(Wh40kQuestUiAction.Abandon, Guid.NewGuid(), row.Id, row.Revision)));
            }
        }
    }

    private void AddButton(BoxContainer parent, string text, Action action)
    {
        var button = new Button { Text = Loc.GetString(text) };
        button.OnPressed += _ => action(); parent.AddChild(button); _actions.Add(button);
    }
}
