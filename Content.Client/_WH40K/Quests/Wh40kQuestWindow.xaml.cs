using Content.Shared._WH40K.Npcs;
using Content.Shared._WH40K.Quests;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client._WH40K.Quests;

[GenerateTypedNameReferences]
public sealed partial class Wh40kQuestWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    private Wh40kQuestUiRequest? _retry;
    private readonly List<Button> _actions = [];
    public event Action<Wh40kQuestUiRequest>? Request;

    public Wh40kQuestWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        QuestTabs.SetTabTitle(0, Loc.GetString("wh40k-quest-ui-offers"));
        QuestTabs.SetTabTitle(1, Loc.GetString("wh40k-quest-ui-active"));
        QuestTabs.SetTabTitle(2, Loc.GetString("wh40k-quest-ui-history"));

        RefreshButton.OnPressed += _ => Send(new(Wh40kQuestUiAction.Refresh, Guid.NewGuid()));
    }

    private void Send(Wh40kQuestUiRequest request)
    {
        _retry = request.Action == Wh40kQuestUiAction.Refresh ? null : request;
        foreach (var button in _actions) button.Disabled = true;
        RefreshButton.Disabled = true;
        ResultLabel.Text = Loc.GetString("wh40k-quest-result-pending");
        ResultLabel.FontColorOverride = Wh40kQuestPalette.ResultPending;
        Request?.Invoke(request);
    }

    public void ShowSnapshot(Wh40kQuestUiSnapshot snapshot)
    {
        var resultKey = "wh40k-quest-result-" + snapshot.Result.ToString().ToLowerInvariant();
        ResultLabel.Text = Loc.GetString(resultKey);
        ResultLabel.FontColorOverride = Wh40kQuestPalette.GetResultColor(snapshot.Result);
        RefreshButton.Disabled = snapshot.Pending;

        if (snapshot.Pending)
        {
            foreach (var button in _actions) button.Disabled = true;
            return;
        }

        OffersRows.RemoveAllChildren();
        ActiveRows.RemoveAllChildren();
        HistoryRows.RemoveAllChildren();
        _actions.Clear();

        if (snapshot.Result == Wh40kQuestOperationResult.PersistenceUnavailable && _retry != null)
        {
            var retry = _retry;
            OffersRows.AddChild(BuildRetryRow(retry));
        }
        else
            _retry = null;

        PopulateTab(OffersRows, snapshot.Offers, true);
        PopulateTab(ActiveRows, snapshot.Active, false);
        PopulateTab(HistoryRows, snapshot.History, false, true);

        QuestTabs.SetTabTitle(0,
            $"{Loc.GetString("wh40k-quest-ui-offers")} ({snapshot.Offers.Count})");
        QuestTabs.SetTabTitle(1,
            $"{Loc.GetString("wh40k-quest-ui-active")} ({snapshot.Active.Count})");
        QuestTabs.SetTabTitle(2,
            $"{Loc.GetString("wh40k-quest-ui-history")} ({snapshot.History.Count})");
    }

    private void PopulateTab(BoxContainer container, List<Wh40kQuestUiRow> rows,
        bool offer, bool history = false)
    {
        if (rows.Count == 0)
        {
            container.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-quest-ui-empty"),
                FontColorOverride = Wh40kQuestPalette.MutedText,
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 40),
            });
            return;
        }

        foreach (var row in rows)
            container.AddChild(BuildCard(row, offer, history));
    }

    private Control BuildCard(Wh40kQuestUiRow row, bool offer, bool history)
    {
        var accent = offer
            ? Wh40kQuestPalette.StateOffer
            : Wh40kQuestPalette.GetStateColor(row.State);

        var outer = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        outer.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = accent },
            MinWidth = 3,
            MaxWidth = 3,
            VerticalExpand = true,
        });

        var cardPanel = new PanelContainer
        {
            PanelOverride = Wh40kQuestPalette.CreateCardPanel(),
            HorizontalExpand = true,
        };

        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 8),
            SeparationOverride = 5,
        };
        cardPanel.AddChild(body);
        outer.AddChild(cardPanel);

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };
        body.AddChild(header);

        header.AddChild(new Label
        {
            Text = Loc.GetString(row.Title),
            ClipText = true,
            HorizontalExpand = true,
            FontColorOverride = Wh40kQuestPalette.TitleText,
        });

        header.AddChild(new Label
        {
            Text = Loc.GetString("wh40k-quest-ui-state-" +
                                 row.State.ToString().ToLowerInvariant()),
            FontColorOverride = accent,
        });

        if (offer && row.CanAct)
        {
            AddButton(header, "wh40k-quest-ui-accept", ButtonStyle.Good,
                () => Send(new(Wh40kQuestUiAction.Accept, Guid.NewGuid(), row.Id)));
        }
        else if (!offer && !history && row.CanAct
                 && row.State == Wh40kQuestState.ReadyToTurnIn)
        {
            AddButton(header, "wh40k-quest-ui-turn-in", ButtonStyle.Good,
                () => Send(new(Wh40kQuestUiAction.TurnIn, Guid.NewGuid(),
                    row.Id, row.Revision)));
        }

        var desc = new RichTextLabel { HorizontalExpand = true };
        desc.SetMessage(Loc.GetString(row.Description));
        body.AddChild(desc);

        var meta = Loc.GetString("wh40k-quest-ui-scope-" +
                                 row.OwnerScope.ToString().ToLowerInvariant());

        if (row.Issuer != null
            && _prototypes.TryIndex<Wh40kNpcAnchorPrototype>(row.Issuer, out var anchor)
            && _prototypes.TryIndex(anchor.Profile, out var profile))
        {
            meta += " · " + Loc.GetString("wh40k-quest-ui-issuer",
                ("issuer", Loc.GetString(profile.Name)));
        }

        if (row.Deadline != null)
            meta += " · " + Loc.GetString("wh40k-quest-ui-deadline",
                ("time", row.Deadline));

        if (offer && row.OfferExpiry != null)
            meta += " · " + Loc.GetString("wh40k-quest-ui-offer-expiry",
                ("time", row.OfferExpiry));

        body.AddChild(new Label
        {
            Text = meta,
            FontColorOverride = Wh40kQuestPalette.MutedText,
            ClipText = true,
        });

        if (row.Binding != Wh40kQuestBindingState.Bound)
        {
            var warning = new PanelContainer
            {
                PanelOverride = Wh40kQuestPalette.CreateWarningPanel(),
                HorizontalExpand = true,
            };
            warning.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-quest-ui-binding-" +
                                     row.Binding.ToString().ToLowerInvariant()),
                FontColorOverride = Wh40kQuestPalette.WarningBorder,
            });
            body.AddChild(warning);
        }

        if (row.Objectives.Count > 0)
        {
            body.AddChild(CreateSeparator());
            body.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-quest-ui-objectives-header"),
                FontColorOverride = Wh40kQuestPalette.HeaderText,
            });

            foreach (var obj in row.Objectives)
            {
                body.AddChild(BuildObjective(obj));

                if (!offer && !history && row.CanAct
                    && obj.Kind.IsSubmission() && obj.Count < obj.Required)
                {
                    AddButton(body, "wh40k-quest-ui-submit", ButtonStyle.Default,
                        () => Send(new(Wh40kQuestUiAction.Submit, Guid.NewGuid(),
                            row.Id, row.Revision, obj.Id)));
                }
            }
        }

        var rewards = history && row.State != Wh40kQuestState.Completed
            ? []
            : row.Rewards;

        if (rewards.Count > 0)
        {
            body.AddChild(CreateSeparator());
            body.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-quest-ui-rewards-header"),
                FontColorOverride = Wh40kQuestPalette.HeaderText,
            });

            foreach (var reward in rewards)
            {
                var name = reward.Item is { } item
                           && _prototypes.TryIndex<EntityPrototype>(item, out var proto)
                    ? proto.Name
                    : Loc.GetString("wh40k-quest-ui-reward-" +
                                    reward.Kind.ToString().ToLowerInvariant());

                body.AddChild(new Label
                {
                    Text = Loc.GetString("wh40k-quest-ui-reward",
                        ("amount", reward.Amount), ("name", name),
                        ("state", Loc.GetString("wh40k-quest-ui-reward-state-" +
                                                reward.State.ToString()
                                                    .ToLowerInvariant()))),
                    FontColorOverride = Wh40kQuestPalette.RewardText,
                });
            }
        }

        if (!offer && !history)
        {
            body.AddChild(CreateSeparator());
            var footer = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Right,
            };
            AddButton(footer, "wh40k-quest-ui-abandon", ButtonStyle.Caution,
                () => Send(new(Wh40kQuestUiAction.Abandon, Guid.NewGuid(),
                    row.Id, row.Revision)));
            body.AddChild(footer);
        }

        return outer;
    }

    private static Control BuildObjective(Wh40kQuestUiObjective obj)
    {
        var complete = obj.Count >= obj.Required;
        var wrapper = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        var textRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        textRow.AddChild(new Label
        {
            Text = complete ? "✓" : "○",
            FontColorOverride = complete
                ? Wh40kQuestPalette.ProgressComplete
                : Wh40kQuestPalette.MutedText,
            MinWidth = 16,
        });

        textRow.AddChild(new Label
        {
            Text = Loc.GetString(obj.Text),
            HorizontalExpand = true,
            ClipText = true,
            FontColorOverride = complete
                ? Wh40kQuestPalette.ProgressComplete
                : Wh40kQuestPalette.BodyText,
        });

        textRow.AddChild(new Label
        {
            Text = $"{obj.Count}/{obj.Required}",
            FontColorOverride = complete
                ? Wh40kQuestPalette.ProgressComplete
                : Wh40kQuestPalette.MutedText,
        });

        wrapper.AddChild(textRow);

        if (obj.Required > 1)
        {
            var bar = new ProgressBar
            {
                HorizontalExpand = true,
                MinHeight = 6,
                MaxHeight = 6,
                MinValue = 0,
                MaxValue = obj.Required,
                Value = Math.Min(obj.Count, obj.Required),
                BackgroundStyleBoxOverride = Wh40kQuestPalette.CreateProgressBg(),
                ForegroundStyleBoxOverride = Wh40kQuestPalette.CreateProgressFill(complete),
            };
            wrapper.AddChild(bar);
        }

        return wrapper;
    }

    private Control BuildRetryRow(Wh40kQuestUiRequest retryRequest)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(0, 8),
        };
        AddButton(row, "wh40k-quest-ui-retry", ButtonStyle.Default,
            () => Send(retryRequest));
        return row;
    }

    private static Control CreateSeparator()
    {
        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = Wh40kQuestPalette.Separator },
            MinHeight = 1,
            MaxHeight = 1,
            HorizontalExpand = true,
            Margin = new Thickness(0, 2),
        };
    }

    private enum ButtonStyle { Default, Good, Caution }

    private void AddButton(Control parent, string locKey, ButtonStyle style, Action action)
    {
        var button = new Button { Text = Loc.GetString(locKey) };

        switch (style)
        {
            case ButtonStyle.Good:
                button.AddStyleClass("ButtonColorGreen");
                break;
            case ButtonStyle.Caution:
                button.AddStyleClass("ButtonColorRed");
                break;
        }

        button.OnPressed += _ => action();
        parent.AddChild(button);
        _actions.Add(button);
    }
}
