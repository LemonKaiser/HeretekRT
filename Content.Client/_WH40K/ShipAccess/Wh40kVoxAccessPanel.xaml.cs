using System.Linq;
using Content.Client._WH40K.ShipPa.UI;
using Content.Shared._WH40K.ShipAccess;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._WH40K.ShipAccess;

[GenerateTypedNameReferences]
public sealed partial class Wh40kVoxAccessPanel : BoxContainer
{
    [Dependency] private IEntityManager _entities = default!;

    private const float RefreshInterval = 2f;
    private Wh40kShipAccessSnapshot? _snapshot;
    private NetEntity? _selectedDoor;
    private float _refreshRemaining;

    public event Action<BoundUserInterfaceMessage>? AccessMessage;
    public Wh40kShipAlarmPanel AlarmPanel => VoxPanel;

    public Wh40kVoxAccessPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ProtectShip.OnPressed += _ => Request(Wh40kShipAccessAction.ProtectShip);
        RestoreShip.OnPressed += _ => Request(Wh40kShipAccessAction.RestoreShip);
        FitMap.OnPressed += _ => DoorMap.FitGrid();
        OwnerGrants.OnToggled += args => Request(args.Pressed ? Wh40kShipAccessAction.RestrictGuestGrant : Wh40kShipAccessAction.AllowGuestSelfGrant);
        DoorMap.DoorSelected += SelectDoor;
        DoorPicker.OnItemSelected += args =>
        {
            if (args.Id == 0)
            {
                _selectedDoor = null;
                UpdateSelectedDoor();
            }
            else if (_snapshot is { } snapshot && args.Id > 0 && args.Id <= snapshot.Doors.Length)
                SelectDoor(snapshot.Doors[args.Id - 1].Id);
        };
        DoorAction.OnPressed += _ =>
        {
            if (GetSelectedDoor() is { } door)
                Request(door.Protected ? Wh40kShipAccessAction.RestoreDoor : Wh40kShipAccessAction.ProtectDoor, door.Id);
        };

        Registration.Text = Loc.GetString("wh40k-ship-access-loading");
        MapHint.Text = Registration.Text;
        ProtectShip.Disabled = RestoreShip.Disabled = FitMap.Disabled = DoorPicker.Disabled = true;
        GuestPanel.Visible = false;
        RebuildDoorPicker();
        UpdateSelectedDoor();
    }

    public void RefreshAccess()
    {
        _refreshRemaining = RefreshInterval;
        AccessMessage?.Invoke(new Wh40kShipAccessRefresh());
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        _refreshRemaining -= args.DeltaSeconds;
        if (VisibleInTree && _refreshRemaining <= 0f)
            RefreshAccess();
    }

    public void UpdateAccess(Wh40kShipAccessSnapshot snapshot)
    {
        var previous = _snapshot;
        _snapshot = snapshot;
        var sameShip = previous != null && previous.Grid == snapshot.Grid;
        if (!sameShip)
            _selectedDoor = null;

        var grid = _entities.GetEntity(snapshot.Grid);
        DoorMap.SetGrid(grid);
        DoorMap.Doors = snapshot.Doors;
        FitMap.Disabled = grid == null;
        ProtectShip.Disabled = !snapshot.CanManage || snapshot.ProtectedReaders == snapshot.TotalReaders;
        RestoreShip.Disabled = !snapshot.CanManage || snapshot.ProtectedReaders == 0;
        GuestPanel.Visible = snapshot.CanManage;
        OwnerGrants.Pressed = snapshot.OwnerGrantsOnly;

        Registration.Text = snapshot.Grid == null
            ? Loc.GetString("wh40k-ship-access-unavailable")
            : Loc.GetString("wh40k-ship-access-registered", ("owner", snapshot.RegisteredTo ?? "—"));
        Registration.ToolTip = Registration.Text;
        AccessHint.Text = snapshot.CanManage ? string.Empty : Loc.GetString("wh40k-ship-access-read-only");
        AccessHint.ToolTip = AccessHint.Text;
        AccessHint.Visible = snapshot.Grid != null && !snapshot.CanManage;
        ShipProtection.Text = snapshot.TotalReaders == 0 ? string.Empty : Loc.GetString("wh40k-ship-access-reader-count",
            ("active", snapshot.ProtectedReaders), ("total", snapshot.TotalReaders));
        ShipProtection.FontColorOverride = snapshot.ProtectedReaders > 0 ? Wh40kShipDoorMap.ProtectedColor : Wh40kShipDoorMap.DefaultColor;

        MapHint.Visible = grid == null || snapshot.Doors.Length == 0;
        MapHint.Text = Loc.GetString(grid == null ? "wh40k-ship-access-no-diagram" : "wh40k-ship-access-no-doors");

        if (!sameShip || previous == null || !SameDoorOptions(previous.Doors, snapshot.Doors))
            RebuildDoorPicker();
        UpdateSelectedDoor();

        if (!sameShip || previous == null || !previous.Guests.SequenceEqual(snapshot.Guests))
            PopulateGuests(GuestList, snapshot.Guests, false);
        if (!sameShip || previous == null || !previous.Nearby.SequenceEqual(snapshot.Nearby))
            PopulateGuests(NearbyList, snapshot.Nearby, true);
    }

    private static bool SameDoorOptions(Wh40kShipAccessDoor[] previous, Wh40kShipAccessDoor[] current)
    {
        return previous.Length == current.Length && previous.Zip(current).All(pair =>
            pair.First.Id == pair.Second.Id && pair.First.Name == pair.Second.Name && pair.First.Position == pair.Second.Position);
    }

    private void RebuildDoorPicker()
    {
        DoorPicker.Clear();
        DoorPicker.AddItem(Loc.GetString("wh40k-ship-access-select-door"), 0);

        if (_snapshot == null)
            return;

        var doors = _snapshot.Doors;
        var duplicateNames = doors.GroupBy(door => door.Name).Where(group => group.Count() > 1).Select(group => group.Key).ToHashSet();
        for (var i = 0; i < doors.Length; i++)
        {
            var door = doors[i];
            var name = duplicateNames.Contains(door.Name)
                ? Loc.GetString("wh40k-ship-access-door-at", ("name", door.Name), ("x", (int) MathF.Floor(door.Position.X)), ("y", (int) MathF.Floor(door.Position.Y)))
                : door.Name;
            DoorPicker.AddItem(name, i + 1);
        }

        DoorPicker.Disabled = doors.Length == 0;
    }

    private void SelectDoor(NetEntity door)
    {
        _selectedDoor = door;
        UpdateSelectedDoor();
    }

    private Wh40kShipAccessDoor? GetSelectedDoor()
    {
        if (_snapshot == null || _selectedDoor == null)
            return null;

        foreach (var door in _snapshot.Doors)
        {
            if (door.Id == _selectedDoor)
                return door;
        }

        return null;
    }

    private void UpdateSelectedDoor()
    {
        if (_snapshot is not { } snapshot || GetSelectedDoor() is not { } door)
        {
            _selectedDoor = DoorMap.SelectedDoor = null;
            DoorPicker.SelectId(0);
            DoorStatus.Text = Loc.GetString("wh40k-ship-access-select-hint");
            DoorStatus.FontColorOverride = null;
            DoorAction.Visible = false;
            return;
        }

        DoorMap.SelectedDoor = door.Id;
        DoorPicker.SelectId(Array.IndexOf(snapshot.Doors, door) + 1);
        DoorStatus.Text = Loc.GetString(door.Protected ? "wh40k-ship-access-door-protected" : "wh40k-ship-access-door-normal");
        DoorStatus.FontColorOverride = door.Protected ? Wh40kShipDoorMap.ProtectedColor : Wh40kShipDoorMap.DefaultColor;
        DoorAction.Visible = snapshot.CanManage;
        DoorAction.Text = Loc.GetString(door.Protected ? "wh40k-ship-access-restore-door" : "wh40k-ship-access-protect-door");
    }

    private void PopulateGuests(BoxContainer container, Wh40kShipAccessGuest[] entries, bool nearby)
    {
        container.RemoveAllChildren();
        if (entries.Length == 0)
        {
            container.AddChild(new Label
            {
                Text = Loc.GetString(nearby ? "wh40k-ship-access-empty-nearby" : "wh40k-ship-access-empty-guests"),
                ClipText = true,
            });
            return;
        }

        foreach (var entry in entries)
        {
            var row = new BoxContainer { SeparationOverride = 6 };
            row.AddChild(new Label { Text = entry.Name, ToolTip = entry.Name, HorizontalExpand = true, ClipText = true });
            var button = new Button { Text = Loc.GetString(nearby ? "wh40k-ship-access-grant" : "wh40k-ship-access-revoke"), MinHeight = 28 };
            button.AddStyleClass("ButtonSquare");
            button.OnPressed += _ => Request(nearby ? Wh40kShipAccessAction.GrantGuest : Wh40kShipAccessAction.RevokeGuest, entry.Id);
            row.AddChild(button);
            container.AddChild(row);
        }
    }

    private void Request(Wh40kShipAccessAction action, NetEntity target = default)
    {
        if (_snapshot is { CanManage: true })
            AccessMessage?.Invoke(new Wh40kShipAccessRequest(action, target));
    }
}
