using System.Globalization;
using Content.Shared._WH40K.ShipFuel;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WH40K.ShipFuel;

[GenerateTypedNameReferences]
public sealed partial class Wh40kShipFuelGauge : PanelContainer
{
    private static readonly Color Muted = Color.FromHex("#8B806E");
    private static readonly Color Normal = Color.FromHex("#85CC8A");
    private static readonly Color Amber = Color.FromHex("#E5AD52");
    private static readonly Color Red = Color.FromHex("#FF7166");
    private Wh40kShipFuelReading _reading;

    public Wh40kShipFuelGauge()
    {
        RobustXamlLoader.Load(this);
        ApplyReading();
    }

    public void SetReading(Wh40kShipFuelReading reading)
    {
        if (_reading == reading)
            return;

        _reading = reading;
        ApplyReading();
    }

    private void ApplyReading()
    {
        var color = _reading.Critical ? Red : _reading.Low ? Amber : _reading.Available ? Normal : Muted;
        Readout.Text = _reading.Available
            ? Loc.GetString("wh40k-ship-fuel-percent", ("percent", (_reading.Fraction * 100f).ToString("0.#", CultureInfo.CurrentCulture)))
            : Loc.GetString("wh40k-ship-fuel-no-signal");
        Readout.FontColorOverride = color;
        Scale.Fraction = _reading.Available ? _reading.Fraction : 0f;
        Scale.FillColor = color;

        ToolTip = _reading.Available
            ? Loc.GetString("wh40k-ship-fuel-reserve-tooltip", ("sources", _reading.Sources))
            : _reading.UnknownSources > 0
                ? Loc.GetString("wh40k-ship-fuel-incomplete-tooltip", ("unknown", _reading.UnknownSources), ("sources", _reading.Sources))
                : Loc.GetString("wh40k-ship-fuel-no-sources-tooltip");
    }
}
