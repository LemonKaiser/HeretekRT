using System.Linq;
using Content.Shared._WH40K.ShipPa;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._WH40K.ShipPa.UI;

/// <summary>
/// WH40K Heritage-styled ship Vox-PA control panel for alert codes, General Quarters klaxon,
/// SOS distress beacons, PA volume, and crew-wide announcements.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class Wh40kShipAlarmPanel : BoxContainer
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _protoManager = default!;

    private const float PollInterval = 0.25f;

    private static readonly Color ReadoutColor = Color.FromHex("#E1C17E");
    private static readonly Color OnlineColor = Color.FromHex("#79D47E");
    private static readonly Color OfflineColor = Color.FromHex("#E5534B");
    private static readonly Color AlarmColor = Color.FromHex("#FF8080");
    private static readonly Color DistressColor = Color.FromHex("#FFB060");

    private readonly Dictionary<string, Button> _codeButtons = new();
    private Button? _codeProbe;

    private EntityUid? _grid;
    private bool _generalQuarters;
    private bool _distress;
    private float _pollAccumulator;

    public event Action<string>? CodeRequested;
    public event Action<bool>? GeneralQuartersRequested;
    public event Action<bool>? DistressRequested;
    public event Action<string>? AnnounceRequested;
    public event Action<float>? VolumeRequested;

    public Wh40kShipAlarmPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        BuildCodeButtons();

        GeneralQuartersButton.OnPressed += _ => GeneralQuartersRequested?.Invoke(!_generalQuarters);
        DistressButton.OnPressed += _ => DistressRequested?.Invoke(!_distress);
        AnnounceButton.OnPressed += _ => Announce();
        AnnounceEdit.OnTextEntered += _ => Announce();
        AnnounceEdit.OnTextChanged += args => AnnounceButton.Disabled = string.IsNullOrWhiteSpace(args.Text);
        AnnounceButton.Disabled = true;

        VolumeSlider.OnValueChanged += _ => UpdateVolumeLabel();
        VolumeSlider.OnReleased += _ => VolumeRequested?.Invoke(VolumeSlider.Value / 100f);

        Refresh(null);
    }

    public void SetGrid(EntityUid? grid)
    {
        _grid = grid;
        Poll();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_codeProbe is { Label.FontColorOverride: null })
            ApplyCodeColours();

        _pollAccumulator += args.DeltaSeconds;
        if (_pollAccumulator < PollInterval)
            return;

        Poll();
    }

    private void BuildCodeButtons()
    {
        var protos = _protoManager.EnumeratePrototypes<Wh40kShipAlertCodePrototype>()
            .Where(proto => proto.Selectable)
            .OrderBy(proto => proto.Order)
            .ThenBy(proto => proto.ID);

        foreach (var proto in protos)
        {
            var button = new Button
            {
                Text = Loc.GetString(proto.Name),
                HorizontalExpand = true,
                MinHeight = 32,
            };

            button.AddStyleClass("ButtonSquare");
            button.Label.FontColorOverride = proto.Color;

            if (proto.Description != null)
                button.ToolTip = Loc.GetString(proto.Description.Value);

            var id = proto.ID;
            button.OnPressed += _ => CodeRequested?.Invoke(id);

            CodeContainer.AddChild(button);
            _codeButtons[id] = button;
            _codeProbe ??= button;
        }
    }

    private void ApplyCodeColours()
    {
        foreach (var (id, button) in _codeButtons)
        {
            if (_protoManager.TryIndex<Wh40kShipAlertCodePrototype>(id, out var codeProto))
                button.Label.FontColorOverride = codeProto.Color;
        }
    }

    private void Poll()
    {
        _pollAccumulator = 0f;
        Refresh(_entManager.TryGetComponent<Wh40kShipAlertComponent>(_grid, out var alert) ? alert : null);
    }

    private void Refresh(Wh40kShipAlertComponent? alert)
    {
        var code = alert?.Code;

        if (code != null && _protoManager.TryIndex(code.Value, out var proto))
        {
            ConditionLabel.Text = Loc.GetString(proto.Name);
            ConditionLabel.FontColorOverride = proto.Color;
        }
        else
        {
            ConditionLabel.Text = "-";
            ConditionLabel.FontColorOverride = ReadoutColor;
        }

        foreach (var (id, button) in _codeButtons)
            button.Disabled = code != null && code.Value.Id == id;

        ApplyCodeColours();

        _generalQuarters = alert?.GeneralQuarters ?? false;
        GeneralQuartersButton.Text = Loc.GetString(_generalQuarters
            ? "wh40k-shuttle-console-ship-general-quarters-secure"
            : "wh40k-shuttle-console-ship-general-quarters-sound");
        GeneralQuartersButton.Modulate = _generalQuarters ? AlarmColor : Color.White;

        _distress = alert?.Distress ?? false;
        DistressButton.Text = Loc.GetString(_distress
            ? "wh40k-shuttle-console-ship-distress-cancel"
            : "wh40k-shuttle-console-ship-distress-send");
        DistressButton.Modulate = _distress ? DistressColor : Color.White;

        if (!VolumeSlider.Grabbed)
            VolumeSlider.SetValueWithoutEvent(MathF.Round((alert?.Volume ?? 1f) * 100f));
        VolumeSlider.Disabled = alert == null;
        UpdateVolumeLabel();

        SpeakersCaption.Text = Loc.GetString(alert is { SpeakersFallback: true }
            ? "wh40k-shuttle-console-ship-speakers-fallback"
            : "wh40k-shuttle-console-ship-speakers");

        if (alert == null)
        {
            SpeakersLabel.Text = "-";
            SpeakersLabel.FontColorOverride = ReadoutColor;
            return;
        }

        if (alert.SpeakersOnline == 0)
        {
            SpeakersLabel.Text = Loc.GetString("wh40k-shuttle-console-ship-speakers-none");
            SpeakersLabel.FontColorOverride = OfflineColor;
            return;
        }

        SpeakersLabel.Text = Loc.GetString(
            "wh40k-shuttle-console-ship-speakers-count",
            ("online", alert.SpeakersOnline),
            ("total", alert.SpeakersTotal));
        SpeakersLabel.FontColorOverride = OnlineColor;
    }

    private void UpdateVolumeLabel()
    {
        VolumeLabel.Text = Loc.GetString("wh40k-shuttle-console-ship-volume-value", ("percent", (int) VolumeSlider.Value));
    }

    private void Announce()
    {
        var text = AnnounceEdit.Text.Trim();
        if (string.IsNullOrEmpty(text))
            return;

        AnnounceRequested?.Invoke(text);
        AnnounceEdit.Clear();
        AnnounceButton.Disabled = true;
    }
}
