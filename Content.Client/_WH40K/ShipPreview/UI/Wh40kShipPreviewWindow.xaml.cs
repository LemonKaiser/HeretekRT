using Content.Client._WH40K.UserInterface;
using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Shipyard.Prototypes;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WH40K.ShipPreview.UI;

/// <summary>
/// WH40K Heritage-styled client ship schematic preview window.
/// </summary>
[GenerateTypedNameReferences]
[UsedImplicitly]
public sealed partial class Wh40kShipPreviewWindow : FancyWindow
{
    private VesselPrototype? _vessel;

    public Wh40kShipPreviewWindow()
    {
        RobustXamlLoader.Load(this);
        Wh40kWindowViewport.ClampInitialSize(this, UserInterfaceManager.RootControl.Size);

        Preview.PreviewUpdated += UpdateInfo;
        ResetViewButton.OnPressed += _ => Preview.FitToGrid();

        OnClose += () =>
        {
            Preview.PreviewUpdated -= UpdateInfo;
            Preview.Release();
        };

        UpdateInfo();
    }

    public static Wh40kShipPreviewWindow Open(VesselPrototype vessel)
    {
        var window = new Wh40kShipPreviewWindow();
        window.SetVessel(vessel);
        window.OpenCentered();
        return window;
    }

    public void SetVessel(VesselPrototype? vessel)
    {
        _vessel = vessel;
        Preview.SetVessel(vessel);
        UpdateInfo();
    }

    private void UpdateInfo()
    {
        ResetViewButton.Disabled = !Preview.HasPreview;
        VesselLabel.Text = _vessel == null
            ? Loc.GetString("wh40k-ship-preview-no-vessel")
            : _vessel.Name;

        InfoLabel.Text = Preview.HasPreview
            ? Loc.GetString("wh40k-ship-preview-info",
                ("width", Preview.GridSize.X),
                ("height", Preview.GridSize.Y),
                ("count", Preview.TileCount))
            : string.Empty;

        LiftLabel.Text = !Preview.HasPreview
            ? string.Empty
            : (Preview.MaxLiftGravity > 0f
                  ? Loc.GetString("wh40k-ship-preview-planet-lift", ("gravity", Preview.MaxLiftGravity.ToString("0.00")))
                  : Loc.GetString("wh40k-ship-preview-planet-none"))
              + "\n" + Loc.GetString("wh40k-ship-preview-rated-load", ("tonnes", (int) Wh40kShipPreviewLift.RatedLoad(Preview.TileCount)));
    }
}
