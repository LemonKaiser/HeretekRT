using System.Globalization;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Client.Stylesheets;
using Content.Shared._WH40K.ShuttleStorage;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.ShuttleStorage;

[GenerateTypedNameReferences]
public sealed partial class ShuttleStorageWindow : FancyWindow
{
    public event Action<ShuttleStorageRequest>? OnTransfer;
    private ShuttleStorageSnapshot? Snapshot { get; set; }
    private NetEntity? SelectedShip { get; set; }
    private NetEntity? _confirmedShip;
    private long _confirmedRevision;
    private bool _pending;
    private Guid _pendingRequest;
    private string? _listSignature;
    private bool _showStored;
    private readonly Dictionary<NetEntity, Button> _rows = new();

    public ShuttleStorageWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("wh40k-shuttle-storage-title");
        Plain(LimitsLabel, Loc.GetString("wh40k-shuttle-storage-limits"));
        ViewSwitchButton.OnPressed += _ =>
        {
            _showStored = !_showStored;
            CancelConfirmation();
            UpdateActions();
        };
        StoreButton.OnPressed += _ =>
        {
            if (_confirmedShip != null) ConfirmTransfer();
            else ConfirmDeposit();
        };
        RetrieveButton.OnPressed += _ =>
        {
            if (Snapshot?.State == ShuttleStorageState.Stored && !RetrieveButton.Disabled)
                Submit(null);
        };
    }

    public void Apply(ShuttleStorageSnapshot snapshot)
    {
        if (Snapshot != null && snapshot.Sequence <= Snapshot.Sequence)
            return;
        if (snapshot.Operation == _pendingRequest && snapshot.Result != ShuttleStorageResult.Busy ||
            snapshot.Result == ShuttleStorageResult.Busy && snapshot.Operation != _pendingRequest ||
            snapshot.Result is not (ShuttleStorageResult.Ready or ShuttleStorageResult.Busy or ShuttleStorageResult.Stored or ShuttleStorageResult.Retrieved))
            _pending = false;
        if (Snapshot?.Revision != snapshot.Revision || snapshot.Result is ShuttleStorageResult.Busy or ShuttleStorageResult.Disabled)
            CancelConfirmation();
        if (Snapshot?.State != snapshot.State)
            _showStored = snapshot.State != ShuttleStorageState.Empty;
        Snapshot = snapshot;
        StationLabel.Text = snapshot.Station;
        StationLabel.ToolTip = snapshot.Station;
        OccupancyLabel.Text = Loc.GetString("wh40k-shuttle-storage-occupancy", ("used", snapshot.State == ShuttleStorageState.Empty ? 0 : 1));

        var signature = string.Join("\n", snapshot.Ships.Select(ship => $"{ship.Entity}:{ship.Name}:{ship.Width}:{ship.Height}:{ship.Result}"));
        if (signature != _listSignature)
        {
            CancelConfirmation();
            _listSignature = signature;
            ShipsList.DisposeAllChildren();
            _rows.Clear();
            if (!snapshot.Ships.Any(ship => ship.Entity == SelectedShip))
            {
                SelectedShip = null;
                CancelConfirmation();
            }
            if (SelectedShip == null && snapshot.Ships.Length > 0)
                SelectedShip = snapshot.Ships[0].Entity;
            if (snapshot.Ships.Length == 0)
                ShipsList.AddChild(new Label { Text = Loc.GetString("wh40k-shuttle-storage-no-ships"), ClipText = true });
            foreach (var ship in snapshot.Ships)
            {
                var button = new Button
                {
                    Text = $"{ship.Name}  ·  {ship.Width} × {ship.Height}",
                    ToolTip = ship.Name + "\n" + ResultText(ship.Result),
                    ToggleMode = true,
                    Pressed = SelectedShip == ship.Entity,
                    HorizontalExpand = true,
                    MinHeight = 34,
                    ClipText = true,
                };
                button.OnPressed += _ => SelectShip(ship.Entity);
                _rows.Add(ship.Entity, button);
                ShipsList.AddChild(button);
            }
        }

        Plain(StoredDetailsLabel, snapshot.State == ShuttleStorageState.Empty
            ? Loc.GetString("wh40k-shuttle-storage-empty-info")
            : Loc.GetString("wh40k-shuttle-storage-saved-info", ("width", snapshot.Width), ("height", snapshot.Height),
                ("bytes", snapshot.Bytes), ("date", snapshot.SavedAt?.ToLocalTime().ToString("g", CultureInfo.CurrentCulture) ?? "—")));
        UpdateActions();
    }

    private void SelectShip(NetEntity entity)
    {
        if (Snapshot == null || !Snapshot.Ships.Any(ship => ship.Entity == entity))
            return;
        SelectedShip = entity;
        CancelConfirmation();
        foreach (var (key, button) in _rows)
            button.Pressed = key == entity;
        UpdateActions();
    }

    private bool CanAct() => !_pending && Snapshot != null && Snapshot.Result is not
        (ShuttleStorageResult.Busy or ShuttleStorageResult.ServiceBusy or ShuttleStorageResult.Disabled or ShuttleStorageResult.Unavailable or ShuttleStorageResult.Cooldown);

    private bool CanDeposit() => !_showStored && CanAct() && Snapshot!.State == ShuttleStorageState.Empty &&
        Snapshot.Ships.Any(ship => ship.Entity == SelectedShip && ship.Result == ShuttleStorageResult.Ready);

    private void UpdateActions()
    {
        if (Snapshot == null)
            return;
        var selected = Snapshot.Ships.FirstOrDefault(ship => ship.Entity == SelectedShip);
        UpdateProjection(selected);
        Plain(SelectedLabel, selected == null ? Loc.GetString("wh40k-shuttle-storage-select")
            : Loc.GetString("wh40k-shuttle-storage-selected-info",
                ("width", selected.Width), ("height", selected.Height), ("entities", selected.Entities)) +
              "\n" + (selected.Result == ShuttleStorageResult.Ready
                  ? Loc.GetString("wh40k-shuttle-storage-eligible") : ResultText(selected.Result)));
        StoreButton.Disabled = !CanDeposit();
        RetrieveButton.Disabled = !CanAct() || Snapshot.State != ShuttleStorageState.Stored;
        if (StoreButton.Disabled)
            CancelConfirmation();
        var result = _pending ? ShuttleStorageResult.Busy : Snapshot.Result;
        if (Snapshot.State == ShuttleStorageState.RecoveryRequired)
            result = ShuttleStorageResult.RecoveryRequired;
        OperationResultLabel.Visible = result is not (ShuttleStorageResult.Ready or ShuttleStorageResult.Stored or ShuttleStorageResult.Retrieved);
        Plain(OperationResultLabel, ResultText(result));
        BayStateLabel.ToolTip = ResultText(result);
    }

    private void UpdateProjection(ShuttleStorageShip? selected)
    {
        var snapshot = Snapshot!;
        var stored = snapshot.State != ShuttleStorageState.Empty;
        var preview = _showStored ? snapshot.Preview : selected?.Preview;
        BayPreview.SetPreview(preview);
        ViewSwitchButton.Text = Loc.GetString(_showStored ? "wh40k-shuttle-storage-berth-view" : "wh40k-shuttle-storage-hangar-view");
        ShipPicker.Visible = !_showStored && snapshot.Ships.Length > 1;
        SelectedLabel.Visible = !_showStored;
        StoredDetailsLabel.Visible = _showStored;
        var name = _showStored ? stored ? snapshot.Name : Loc.GetString("wh40k-shuttle-storage-slot-empty") : selected?.Name;
        ManifestName.Text = name ?? Loc.GetString(_showStored
            ? "wh40k-shuttle-storage-slot-empty" : "wh40k-shuttle-storage-no-ships-title");
        ManifestName.ToolTip = name;
        ManifestCaption.Text = Loc.GetString(_showStored ? "wh40k-shuttle-storage-manifest-stored" : "wh40k-shuttle-storage-manifest-berth");
        var width = _showStored ? snapshot.Width : selected?.Width ?? 0;
        var height = _showStored ? snapshot.Height : selected?.Height ?? 0;
        var dimensions = width > 0 && height > 0 ? $"{width} × {height}" : "—";
        ProjectionDimensions.Text = dimensions;
        ProjectionPlaceholder.Visible = preview?.Valid != true;
        ProjectionPlaceholder.Text = Loc.GetString(_showStored && snapshot.PreviewPending
            ? "wh40k-shuttle-storage-projection-loading" : _showStored && !stored || !_showStored && selected == null
                ? "wh40k-shuttle-storage-projection-empty" : "wh40k-shuttle-storage-projection-unavailable");
        BayStateLabel.Text = Loc.GetString(snapshot.State == ShuttleStorageState.RecoveryRequired && _showStored
            ? "wh40k-shuttle-storage-bay-recovery" : snapshot.Result == ShuttleStorageResult.Busy
                ? "wh40k-shuttle-storage-bay-moving" : _showStored
                    ? stored ? "wh40k-shuttle-storage-bay-stored" : "wh40k-shuttle-storage-bay-empty"
                    : selected == null ? "wh40k-shuttle-storage-bay-empty" : "wh40k-shuttle-storage-bay-berth");
    }

    private void ConfirmDeposit()
    {
        if (!CanDeposit())
            return;
        var ship = Snapshot!.Ships.First(ship => ship.Entity == SelectedShip);
        _confirmedShip = ship.Entity;
        _confirmedRevision = Snapshot.Revision;
        StoreButton.Text = Loc.GetString("wh40k-shuttle-storage-confirm");
        StoreButton.AddStyleClass(StyleNano.ButtonCaution);
    }

    private void ConfirmTransfer()
    {
        if (Snapshot == null || _confirmedShip == null || _confirmedShip != SelectedShip ||
            _confirmedRevision != Snapshot.Revision || !CanDeposit())
            return;
        Submit(_confirmedShip);
    }

    private void CancelConfirmation()
    {
        _confirmedShip = null;
        StoreButton.Text = Loc.GetString("wh40k-shuttle-storage-store");
        StoreButton.RemoveStyleClass(StyleNano.ButtonCaution);
    }

    private void Submit(NetEntity? ship)
    {
        if (Snapshot == null)
            return;
        var request = new ShuttleStorageRequest(Guid.NewGuid(), Snapshot.Revision, ship);
        _pendingRequest = request.RequestId;
        _pending = true;
        CancelConfirmation();
        UpdateActions();
        OnTransfer?.Invoke(request);
    }

    private static string ResultText(ShuttleStorageResult result)
        => Loc.GetString($"wh40k-shuttle-storage-result-{result.ToString().ToLowerInvariant()}");

    private static void Plain(RichTextLabel label, string text)
    {
        var message = new FormattedMessage();
        message.AddText(text);
        label.SetMessage(message);
    }
}
