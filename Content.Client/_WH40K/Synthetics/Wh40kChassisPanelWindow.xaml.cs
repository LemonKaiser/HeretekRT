    public void Update(Wh40kChassisPanelState state)
    {
        _lowPower = state.LowPower;
        _bayOpen = state.BayOpen;
        _tableReady = state.OnAugmentTable && state.AugmentTablePowered;

        if (state.AugmentFocusSeq > _lastFocusSeq)
        {
            _lastFocusSeq = state.AugmentFocusSeq;
            if (state.OnAugmentTable)
                CurrentTab = 2;
        }

        StatusLabel.Text = state.Status.Length > 0 ? Loc.GetString(state.Status) : string.Empty;
        StatusLabel.Visible = state.Status.Length > 0;
        StatusLabel.FontColorOverride = state.Dead || state.LowPower ? Alert
            : state.BayOpen || state.Overclocked || state.Rebooting ? AmberBright
            : Good;

        if (state.OnAugmentTable && state.AugmentTablePowered)
        {
            DockStatusLabel.Text = Loc.GetString("wh40k-chassis-ui-dock-ready");
            DockStatusLabel.FontColorOverride = Good;
        }
        else if (state.OnAugmentTable)
        {
            DockStatusLabel.Text = Loc.GetString("wh40k-chassis-ui-dock-offline");
            DockStatusLabel.FontColorOverride = Alert;
        }
        else
        {
            DockStatusLabel.Text = Loc.GetString("wh40k-chassis-ui-dock-field");
            DockStatusLabel.FontColorOverride = AmberDim;
        }

        SetGauge(PowerLabel, "wh40k-chassis-ui-row-power", state.Power, state.Power >= 0f);
        SetGauge(IntegrityLabel, "wh40k-chassis-ui-row-integrity", state.Integrity, true);
        SetGauge(SensorLabel, "wh40k-chassis-ui-row-sensors", state.Sensors, true);

        CoreLabel.Visible = state.CoreTemperature >= 0f;
        CoreLabel.Text = Loc.GetString("wh40k-chassis-ui-row-core") + " " +
                         Loc.GetString("wh40k-chassis-ui-row-core-temp", ("value", (int) MathF.Round(state.CoreTemperature)));
        CoreLabel.FontColorOverride = state.CoreTemperature is >= 0f and < 180f ? Cyan
            : state.CoreTemperature > 350f ? Alert
            : Amber;

        UpdateRadiationAndHeat(state);
        SyncParts(state.Parts);
        SyncOrgans(state.Organs);
        if (_state == null ||
            _state.OnAugmentTable != state.OnAugmentTable ||
            _state.AugmentTablePowered != state.AugmentTablePowered ||
            _state.Dead != state.Dead ||
            !_state.AugmentOptions.SequenceEqual(state.AugmentOptions) ||
            !_state.InstalledAugments.SequenceEqual(state.InstalledAugments))
        {
            SyncAugments(state);
        }

        _state = state;
        SyncDoll(state.Parts);

        _updatingControls = true;
        OpenBayButton.Text = Loc.GetString(state.BayOpen ? "wh40k-chassis-ui-bay-close" : "wh40k-chassis-ui-bay-open");
        OpenBayButton.ToolTip = Loc.GetString(state.BayOpen ? "wh40k-chassis-ui-tip-bay-close" : "wh40k-chassis-ui-tip-bay-open");
        OpenBayButton.Label.FontColorOverride = state.BayOpen ? Alert : Amber;

        var rebootArmed = IsArmed(new ArmKey("reboot", null));
        RebootButton.Text = Loc.GetString(rebootArmed ? "wh40k-chassis-ui-confirm" : "wh40k-chassis-ui-reboot");
        RebootButton.Label.FontColorOverride = rebootArmed ? Alert : Amber;

        OverclockButton.Pressed = state.Overclocked;
        OverclockButton.Text = Loc.GetString(state.Overclocked ? "wh40k-chassis-ui-overclock-on" : "wh40k-chassis-ui-overclock-off");
        OverclockButton.Label.FontColorOverride = state.Overclocked ? Alert : Amber;
        _updatingControls = false;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_armed == null || _timing.RealTime < _armedUntil)
            return;

        _armed = null;
        if (_state != null)
            Update(_state);
    }

    private void SyncParts(List<Wh40kChassisPartEntry> entries)
    {
        if (_partRows.Count != entries.Count)
        {
            foreach (var row in _partRows)
            {
                foreach (var cell in row.Cells)
                    _partsGrid.RemoveChild(cell);
            }

            _partRows.Clear();
            for (var i = 0; i < entries.Count; i++)
            {
                var row = new PartRow();
                row.Isolate.OnPressed += _ => PressIsolate(row);
                row.Detach.OnPressed += _ => PressDetach(row);
                foreach (var cell in row.Cells)
                {
                    cell.OnKeyBindDown += args =>
                    {
                        if (args.Function == EngineKeyFunctions.UIClick && row.Entry is { } entry)
                            SelectPart(entry.Slot);
                    };
                    _partsGrid.AddChild(cell);
                }

                _partRows.Add(row);
            }
        }

        for (var i = 0; i < entries.Count; i++)
            ApplyPart(_partRows[i], entries[i]);

        PaintParts();
    }

    private void SyncDoll(List<Wh40kChassisPartEntry> entries)
    {
        if (_doll == null)
            return;

        var next = BuildDoll(entries);
        if (_dollState != null && _dollState.Count == next.Count && !next.Except(_dollState).Any())
            return;

        _dollState = next;
        _doll.SetBody(next);
        _doll.SetSelected(_selected);
    }

    public void PickFromDoll(TargetBodyPart part) =>
        SelectPart(part == TargetBodyPart.Groin ? TargetBodyPart.Torso : part, scroll: true);

    public void SelectPart(TargetBodyPart? part, bool scroll = false)
    {
        _selected = part != null && part == _selected ? null : part;
        _doll?.SetSelected(_selected);
        PaintParts();

        if (scroll && _selected != null && _partRows.Find(row => row.Entry?.Slot == _selected) is { } picked)
            ScrollTo(picked.Cells[0]);
    }

    private void PaintParts()
    {
        for (var i = 0; i < _partRows.Count; i++)
        {
            var row = _partRows[i];
            var picked = _selected != null && row.Entry?.Slot == _selected;
            row.Paint(picked ? SelectedBox : i % 2 == 0 ? EvenBox : OddBox);
        }
    }

    private void ScrollTo(Control control)
    {
        var offset = 0f;
        Control? walk = control;
        while (walk != null && walk != _partsHost)
        {
            offset += walk.Position.Y;
            walk = walk.Parent;
        }

        if (walk == null)
            return;

        var top = _partsScroll.GetScrollValue().Y;
        if (offset < top)
            _partsScroll.VScrollTarget = MathF.Max(0f, offset - 4f);
        else if (offset + control.Height > top + _partsScroll.Height)
            _partsScroll.VScrollTarget = offset + control.Height - _partsScroll.Height + 4f;
    }

    public static TargetIntegrity DollIntegrity(Wh40kChassisPartEntry entry)
    {
        if (!entry.Attached)
            return TargetIntegrity.Severed;

        if (entry.Isolated || !entry.Working)
            return TargetIntegrity.Disabled;

        var integrity = entry.Integrity;
        return integrity >= 0.9f ? TargetIntegrity.Healthy
            : integrity >= 0.7f ? TargetIntegrity.LightlyWounded
            : integrity >= 0.5f ? TargetIntegrity.SomewhatWounded
            : integrity >= 0.3f ? TargetIntegrity.ModeratelyWounded
            : integrity >= 0.1f ? TargetIntegrity.HeavilyWounded
            : TargetIntegrity.CriticallyWounded;
    }

    public static Dictionary<TargetBodyPart, TargetIntegrity> BuildDoll(IEnumerable<Wh40kChassisPartEntry> parts)
    {
        var body = new Dictionary<TargetBodyPart, TargetIntegrity>();
        foreach (var entry in parts)
            body[entry.Slot] = DollIntegrity(entry);

        if (!body.ContainsKey(TargetBodyPart.Groin) && body.TryGetValue(TargetBodyPart.Torso, out var torso))
            body[TargetBodyPart.Groin] = torso;

        return body;
    }

    private void SyncOrgans(List<Wh40kChassisOrganEntry> entries)
    {
        if (_organRows.Count != entries.Count)
        {
            foreach (var row in _organRows)
            {
                foreach (var cell in row.Cells)
                    _organsGrid.RemoveChild(cell);
            }

            _organRows.Clear();
            for (var i = 0; i < entries.Count; i++)
            {
                var row = new OrganRow();
                row.Disconnect.OnPressed += _ => PressDisconnect(row);
                row.Paint(i % 2 == 0 ? EvenBox : OddBox);
                foreach (var cell in row.Cells)
                    _organsGrid.AddChild(cell);
                _organRows.Add(row);
            }
        }

        for (var i = 0; i < entries.Count; i++)
            ApplyOrgan(_organRows[i], entries[i]);
    }

    private void ApplyPart(PartRow row, Wh40kChassisPartEntry entry)
    {
        row.Entry = entry;
        row.Name.Text = Loc.GetString(entry.Name);

        var (stateKey, stateColour) = entry switch
        {
            { Attached: false } => ("wh40k-chassis-ui-state-detached", Alert),
            { Isolated: true } => ("wh40k-chassis-ui-state-isolated", Cyan),
            { Loose: true } => ("wh40k-chassis-ui-state-loose", AmberBright),
            { Working: false } when _lowPower && IsArm(entry.Slot) => ("wh40k-chassis-ui-state-unpowered", AmberBright),
            { Working: false } => ("wh40k-chassis-ui-state-offline", Alert),
            _ => ("wh40k-chassis-ui-state-ok", Good),
        };
        row.State.Text = Loc.GetString(stateKey);
        row.State.FontColorOverride = stateColour;

        if (entry.Attached)
        {
            row.Integrity.Text = GaugeText(entry.Integrity);
            row.Integrity.FontColorOverride = FractionColour(entry.Integrity);
        }
        else
        {
            row.Integrity.Text = Loc.GetString("wh40k-chassis-ui-none");
            row.Integrity.FontColorOverride = AmberDim;
        }

        row.Faults.Text = entry.Faults.Count == 0
            ? Loc.GetString("wh40k-chassis-ui-none")
            : string.Join(", ", entry.Faults.Select(fault => Loc.GetString(fault)));
        row.Faults.FontColorOverride = entry.Faults.Count == 0 ? AmberDim : AmberBright;

        row.Isolate.Text = Loc.GetString(entry.Isolated ? "wh40k-chassis-ui-restore" : "wh40k-chassis-ui-isolate");
        SetEnabled(row.Isolate, entry.Part != null && entry.Attached && IsLimb(entry.Slot));

        var canDetachNow = entry.Part != null && entry.CanDetach && _tableReady;
        row.Detach.Text = Loc.GetString("wh40k-chassis-ui-detach");
        row.Detach.ToolTip = entry.CanDetach && !_tableReady
            ? Loc.GetString("wh40k-chassis-ui-tip-requires-table")
            : null;
        SetEnabled(row.Detach, canDetachNow);
    }

    private void ApplyOrgan(OrganRow row, Wh40kChassisOrganEntry entry)
    {
        row.Entry = entry;
        row.Slot.Text = _loc.TryGetString($"wh40k-chassis-slot-{entry.Slot}", out var slot) ? slot : entry.Slot.ToUpperInvariant();

        var present = entry.Organ != null;
        row.Name.Text = present ? entry.Name.ToUpperInvariant() : Loc.GetString("wh40k-chassis-ui-empty");
        row.Name.FontColorOverride = present ? Amber : AmberDim;

        var hasGauge = present && entry.Health >= 0f;
        var charge = entry.Band == ChargeBand;
        row.Health.Text = hasGauge ? GaugeText(entry.Health) : Loc.GetString("wh40k-chassis-ui-none");
        row.Health.FontColorOverride = hasGauge ? (charge ? Cyan : FractionColour(entry.Health)) : AmberDim;

        row.Band.Text = present && entry.Band.Length > 0 ? Loc.GetString(entry.Band) : string.Empty;
        row.Band.FontColorOverride = hasGauge && !charge && entry.Health < 0.25f ? Alert : AmberDim;

        row.Vital.Text = entry.Vital ? Loc.GetString("wh40k-chassis-ui-vital") : string.Empty;

        var armed = entry.Organ is { } organ && IsArmed(new ArmKey("organ", organ));
        row.Disconnect.Text = Loc.GetString(armed ? "wh40k-chassis-ui-confirm" : "wh40k-chassis-ui-disconnect");
        row.Disconnect.ToolTip = !entry.CanDisconnect
            ? Loc.GetString(!_bayOpen
                ? "wh40k-chassis-ui-tip-disconnect-closed"
                : "wh40k-chassis-ui-tip-disconnect-table")
            : entry.Vital ? Loc.GetString("wh40k-chassis-ui-tip-disconnect-vital") : null;
        SetEnabled(row.Disconnect, present && entry.CanDisconnect);
        if (armed)
            row.Disconnect.Label.FontColorOverride = Alert;
    }

    private void SyncAugments(Wh40kChassisPanelState state)
    {
        var ready = state.OnAugmentTable && state.AugmentTablePowered;
        if (ready)
        {
            _augmentBannerLabel.Text = Loc.GetString("wh40k-chassis-ui-aug-banner-ready");
            _augmentBannerLabel.FontColorOverride = Good;
            _augmentBannerPanel.PanelOverride = Box(Color.FromHex("#102114"), Good, 6f);
        }
        else if (state.OnAugmentTable)
        {
            _augmentBannerLabel.Text = Loc.GetString("wh40k-chassis-ui-aug-banner-offline");
            _augmentBannerLabel.FontColorOverride = Alert;
            _augmentBannerPanel.PanelOverride = Box(Color.FromHex("#241010"), Alert, 6f);
        }
        else
        {
            _augmentBannerLabel.Text = Loc.GetString("wh40k-chassis-ui-aug-banner-field");
            _augmentBannerLabel.FontColorOverride = Amber;
            _augmentBannerPanel.PanelOverride = Box(Panel, Border, 6f);
        }

        _augmentOptionsGrid.RemoveAllChildren();
        if (state.OnAugmentTable && state.AugmentOptions.Count > 0)
        {
            _augmentOptionsGrid.Visible = true;
            _augmentEmptyLabel.Visible = false;
            AddHeader(_augmentOptionsGrid, new[]
            {
                (Loc.GetString("wh40k-chassis-ui-col-zone"), AugmentZoneWidth),
                (Loc.GetString("wh40k-chassis-ui-col-augment"), 0f),
                (Loc.GetString("wh40k-chassis-ui-col-replaces"), AugmentReplaceWidth),
                (Loc.GetString("wh40k-chassis-ui-col-actions"), AugmentActionWidth),
            });

            for (var i = 0; i < state.AugmentOptions.Count; i++)
            {
                var option = state.AugmentOptions[i];
                var rowBox = i % 2 == 0 ? EvenBox : OddBox;

                var zoneLabel = Cell(AugmentZoneWidth, AmberDim, true);
                zoneLabel.Text = ZoneName(option.Zone);

                var nameLabel = Cell(0, Amber, true);
                nameLabel.Text = ProtoName(option.Prototype).ToUpperInvariant();

                var replacesLabel = Cell(AugmentReplaceWidth, option.ExistingPart != null ? AmberBright : AmberDim);
                replacesLabel.Text = option.ExistingPart != null
                    ? ProtoName(option.ExistingPart)
                    : Loc.GetString("wh40k-chassis-ui-none");

                var installBtn = FlatButton(Loc.GetString("wh40k-chassis-ui-aug-install"));
                installBtn.SetWidth = AugmentActionWidth;
                SetEnabled(installBtn, ready && !state.Dead);
                var captured = option;
                installBtn.OnPressed += _ => OnInstallAugment?.Invoke(captured.Item, captured.Zone);

                _augmentOptionsGrid.AddChild(Holder(zoneLabel, AugmentZoneWidth, rowBox));
                _augmentOptionsGrid.AddChild(Holder(nameLabel, 0, rowBox));
                _augmentOptionsGrid.AddChild(Holder(replacesLabel, AugmentReplaceWidth, rowBox));
                _augmentOptionsGrid.AddChild(Holder(installBtn, AugmentActionWidth, rowBox));
            }
        }
        else
        {
            _augmentOptionsGrid.Visible = false;
            _augmentEmptyLabel.Visible = true;
            _augmentEmptyLabel.Text = Loc.GetString(state.OnAugmentTable
                ? "wh40k-augment-bed-empty"
                : "wh40k-chassis-ui-aug-need-table");
        }

        _installedAugmentsGrid.RemoveAllChildren();
        if (state.InstalledAugments.Count > 0)
        {
            _installedAugmentsGrid.Visible = true;
            _installedEmptyLabel.Visible = false;
            AddHeader(_installedAugmentsGrid, new[]
            {
                (Loc.GetString("wh40k-chassis-ui-col-zone"), AugmentZoneWidth),
                (Loc.GetString("wh40k-chassis-ui-col-augment"), 0f),
            });

            for (var i = 0; i < state.InstalledAugments.Count; i++)
            {
                var inst = state.InstalledAugments[i];
                var rowBox = i % 2 == 0 ? EvenBox : OddBox;

                var zoneLabel = Cell(AugmentZoneWidth, AmberDim, true);
                zoneLabel.Text = ZoneName(inst.Zone);

                var nameLabel = Cell(0, Amber);
                nameLabel.Text = ProtoName(inst.Prototype).ToUpperInvariant();

                _installedAugmentsGrid.AddChild(Holder(zoneLabel, AugmentZoneWidth, rowBox));
                _installedAugmentsGrid.AddChild(Holder(nameLabel, 0, rowBox));
            }
        }
        else
        {
            _installedAugmentsGrid.Visible = false;
            _installedEmptyLabel.Visible = true;
        }
    }

    private string ZoneName(Wh40kAugmentBedZone zone)
    {
        var key = $"wh40k-augment-bed-zone-{zone.ToString().ToLowerInvariant()}";
        return _loc.TryGetString(key, out var text) ? text.ToUpperInvariant() : zone.ToString().ToUpperInvariant();
    }

    private string ProtoName(string protoId) =>
        _prototypes.TryIndex<EntityPrototype>(protoId, out var proto) && !string.IsNullOrEmpty(proto.Name)
            ? proto.Name
            : protoId;

    private void PressIsolate(PartRow row)
    {
        if (row.Entry is { Part: { } part } entry)
            OnIsolate?.Invoke(part, !entry.Isolated);
    }

    private void PressDetach(PartRow row)
    {
        if (row.Entry is { Part: { } part })
            OnDetach?.Invoke(part);
    }

    private void PressDisconnect(OrganRow row)
    {
        if (row.Entry is not { Organ: { } organ } entry)
            return;

        if (entry.Vital && !Confirm(new ArmKey("organ", organ)))
            return;

        OnDisconnect?.Invoke(organ);
    }

    private bool IsArmed(ArmKey key) => _armed == key && _timing.RealTime < _armedUntil;

    private bool Confirm(ArmKey key)
    {
        var confirmed = IsArmed(key);
        if (confirmed)
        {
            _armed = null;
        }
        else
        {
            _armed = key;
            _armedUntil = _timing.RealTime + TimeSpan.FromSeconds(ConfirmSeconds);
        }

        if (_state != null)
            Update(_state);

        return confirmed;
    }

    public static bool IsLimb(TargetBodyPart slot) =>
        (slot & (TargetBodyPart.Arms | TargetBodyPart.Hands | TargetBodyPart.Legs | TargetBodyPart.Feet)) != 0 &&
        (slot & (TargetBodyPart.Head | TargetBodyPart.Torso | TargetBodyPart.Groin)) == 0;

    private void UpdateRadiationAndHeat(Wh40kChassisPanelState state)
    {
        if (state.RadCollector < 0f)
        {
            RadCollectorLabel.Text = Loc.GetString("wh40k-chassis-ui-rad-collector") + " " + Loc.GetString("wh40k-chassis-ui-rad-collector-none");
            RadCollectorLabel.FontColorOverride = Alert;
        }
        else
        {
            RadCollectorLabel.Text = Loc.GetString("wh40k-chassis-ui-rad-collector") + " " + GaugeText(state.RadCollector);
            RadCollectorLabel.FontColorOverride = state.RadCollector >= 1f ? Alert : FractionColour(1f - state.RadCollector);
        }

        RadiationLabel.Text = Loc.GetString("wh40k-chassis-ui-radiation", ("value", state.Radiation.ToString("0.0")));
        RadiationLabel.FontColorOverride = state.Radiation <= 0f ? AmberDim
            : state.RadCollector < 0f || state.RadCollector >= 1f ? Alert
            : AmberBright;

        HeatLabel.Visible = state.ChassisHeat > 0.01f || state.Overclocked;
        HeatLabel.Text = Loc.GetString("wh40k-chassis-ui-row-heat") + " " + GaugeText(state.ChassisHeat);
        HeatLabel.FontColorOverride = state.ChassisHeat >= 0.75f ? Alert : state.ChassisHeat >= 0.45f ? AmberBright : Good;
    }

    private static void SetGauge(Label label, string key, float fraction, bool visible)
    {
        label.Visible = visible;
        if (!visible)
            return;

        label.Text = Loc.GetString(key) + " " + GaugeText(fraction);
        label.FontColorOverride = FractionColour(fraction);
    }

    private static string GaugeText(float fraction) => $"{Gauge(fraction, GaugeWidth)} {Percent(fraction),4}";
    private static string Percent(float fraction) => $"{(int) MathF.Round(Math.Clamp(fraction, 0f, 1f) * 100f)}%";
    private static Color FractionColour(float fraction) => fraction >= 0.5f ? Good : fraction >= 0.25f ? AmberBright : Alert;

    private static void Style(Label label, int size, Color colour, bool bold = false)
    {
        label.FontOverride = Mono(size, bold);
        label.FontColorOverride = colour;
    }

    private static void StyleButton(Button button)
    {
        button.StyleBoxOverride = Box(Panel, Border, 5f);
        button.Label.FontOverride = Mono(11, true);
        button.Label.FontColorOverride = Amber;
    }

    private static void SetEnabled(Button button, bool enabled)
    {
        button.Disabled = !enabled;
        button.Label.FontColorOverride = enabled ? Amber : AmberFaint;
    }

    private static Label Cell(float width, Color? colour = null, bool bold = false)
    {
        var label = Text(string.Empty, 11, colour ?? Amber, bold);
        if (width > 0)
        {
            label.SetWidth = width;
        }
        else
        {
            label.HorizontalExpand = true;
            label.MinWidth = ExpandMinWidth;
        }

        label.ClipText = true;
        return label;
    }

    private static StyleBoxFlat CellBox(Color background, Color line) => new()
    {
        BackgroundColor = background,
        BorderColor = line,
        BorderThickness = new Thickness(0, 0, 0, 1),
        ContentMarginLeftOverride = 4f,
        ContentMarginRightOverride = 4f,
        ContentMarginTopOverride = 3f,
        ContentMarginBottomOverride = 3f,
    };

    private static GridContainer Table(int columns) => new()
    {
        Columns = columns,
        HSeparationOverride = 0,
        VSeparationOverride = 0,
        HorizontalExpand = true,
    };

    private static PanelContainer Holder(Control content, float width, StyleBox? box = null)
    {
        var holder = new PanelContainer
        {
            PanelOverride = box ?? EvenBox,
            HorizontalExpand = width <= 0,
            MouseFilter = Control.MouseFilterMode.Stop,
        };
        holder.AddChild(content);
        return holder;
    }

    private static void AddHeader(GridContainer grid, IEnumerable<(string Text, float Width)> columns)
    {
        foreach (var (text, width) in columns)
        {
            var label = Cell(width, AmberDim, true);
            label.Text = text;
            grid.AddChild(Holder(label, width, HeaderBox));
        }
    }

    public sealed class PartRow
    {
        public readonly Label Name = Cell(NameWidth, bold: true);
        public readonly Label State = Cell(StateWidth, bold: true);
        public readonly Label Integrity = Cell(GaugeColumn);
        public readonly Label Faults = Cell(0);
        public readonly Button Isolate = FlatButton(string.Empty);
        public readonly Button Detach = FlatButton(string.Empty);

        public readonly IReadOnlyList<PanelContainer> Cells;
        public Wh40kChassisPartEntry? Entry;

        public PartRow()
        {
            Isolate.SetWidth = Detach.SetWidth = ButtonWidth;
            Cells = new[]
            {
                Holder(Name, NameWidth),
                Holder(State, StateWidth),
                Holder(Integrity, GaugeColumn),
                Holder(Faults, 0),
                Holder(Isolate, ButtonWidth),
                Holder(Detach, ButtonWidth),
            };
        }

        public void Paint(StyleBox box)
        {
            foreach (var cell in Cells)
                cell.PanelOverride = box;
        }
    }

    public sealed class OrganRow
    {
        public readonly Label Slot = Cell(SlotWidth, AmberDim, true);
        public readonly Label Name = Cell(0);
        public readonly Label Health = Cell(GaugeColumn);
