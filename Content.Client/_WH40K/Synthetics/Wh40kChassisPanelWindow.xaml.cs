                Holder(Name, 0),
                Holder(Health, GaugeColumn),
                Holder(Band, BandWidth),
                Holder(Vital, VitalWidth),
                Holder(Disconnect, DisconnectWidth),
            };
        }

        public void Paint(StyleBox box)
        {
            foreach (var cell in Cells)
                cell.PanelOverride = box;
        }
    }

