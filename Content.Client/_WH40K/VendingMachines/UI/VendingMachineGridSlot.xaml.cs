using System.Numerics;
using Content.Shared.Labels.Components;
using Content.Shared._NF.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Input;
using Robust.Shared.Timing;

namespace Content.Client._WH40K.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class VendingMachineGridSlot : PanelContainer
{
    [Dependency] private IPrototypeManager _protoManager = null!;
    [Dependency] private ILocalizationManager _loc = null!;
    [Dependency] private IComponentFactory _componentFactory = default!;

    private const float SlotSize = 84f;
    private const float SlotHeight = 102f;
    private const float ItemSize = 64f;
    private const float BadgeSize = 20f;
    private const float AnimDuration = 0.55f;
    private const float DropDistance = 20f;
    private const float IconScale = 2.5f;
    private readonly Vector2 _restingPos;
    private bool _animating;
    private float _animElapsed;
    private bool _pendingSoldOut;

    // highlighting
    private readonly StyleBoxFlat _normalStyle = new() { BackgroundColor = Color.FromHex("#222222"), BorderColor = Color.FromHex("#626262"), BorderThickness = new Thickness(1) };
    private readonly StyleBoxFlat _rowMatchStyle = new() { BackgroundColor = Color.FromHex("#343434"), BorderColor = Color.FromHex("#a2a2a2"), BorderThickness = new Thickness(2) };
    private readonly StyleBoxFlat _exactMatchStyle = new() { BackgroundColor = Color.FromHex("#343c32"), BorderColor = Color.FromHex("#b0c59f"), BorderThickness = new Thickness(2) };

    public bool SoldOut { get; private set; }
    public string ItemName { get; private set; } = string.Empty;
    public int Price { get; private set; }
    public event Action? OnItemPressed;

    public VendingMachineGridSlot()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;
        OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UIClick)
                return;

            args.Handle();
            OnItemPressed?.Invoke();
        };

        MinSize = SetSize = new Vector2(SlotSize, SlotHeight);

        PanelOverride = _normalStyle;

        SlotLayout.SetSize = new Vector2(SlotSize, SlotHeight);
        LayoutContainer.SetPosition(SlotLayout, Vector2.Zero);

        _restingPos = new Vector2((SlotSize - ItemSize) / 2f, (SlotSize - ItemSize) / 2f);
        ItemSprite.SetSize = new Vector2(ItemSize, ItemSize);
        ItemSprite.Scale = new Vector2(IconScale, IconScale);
        LayoutContainer.SetPosition(ItemSprite, _restingPos);

        LayoutContainer.SetPosition(CodeLabel, new Vector2(2f, 2f));

        AmountBadge.SetSize = new Vector2(28f, BadgeSize);
        LayoutContainer.SetPosition(AmountBadge, new Vector2(SlotSize - 30f, SlotHeight - BadgeSize - 2f));
        PriceLabel.SetSize = new Vector2(52f, BadgeSize);
        LayoutContainer.SetPosition(PriceLabel, new Vector2(2f, SlotHeight - BadgeSize - 2f));

        SoldOverlay.SetSize = new Vector2(SlotSize, 22f);
        LayoutContainer.SetPosition(SoldOverlay, new Vector2(0f, (SlotSize - 22f) / 2f));
    }

    public void SetItem(EntProtoId protoId, string code, uint amount, bool soldOut)
    {
        CodeLabel.Text = code;
        ItemSprite.SetPrototype(protoId);

        if (_protoManager.TryIndex(protoId, out var proto))
        {
            ToolTip = GetItemText(proto);
        }

        SetAmount(amount, soldOut);
    }

    public void SetAmount(uint amount, bool soldOut)
    {
        AmountLabel.Text = amount == uint.MaxValue ? "∞" : amount > 999 ? "999+" : amount.ToString();
        AmountBadge.ToolTip = amount == uint.MaxValue ? Loc.GetString("wh40k-vending-unlimited") : amount.ToString();
        SoldOut = soldOut;

        if (_animating)
        {
            _pendingSoldOut = soldOut;
            return;
        }

        ApplySoldOutState(soldOut);
    }

    public void SetPrice(int price, long available)
    {
        Price = price;
        PriceLabel.Text = price == 0 ? Loc.GetString("wh40k-vending-free") : BankSystemExtensions.ToSpesoString(price);
        PriceLabel.ToolTip = Loc.GetString("wh40k-vending-price", ("price", BankSystemExtensions.ToSpesoString(price)));
        PriceLabel.FontColorOverride = price > available ? Color.FromHex("#d3b08b") : Color.FromHex("#b9b9b2");
    }

    public void SetHighlight(bool isRowMatch, bool isExactMatch)
    {
        if (isExactMatch)
            PanelOverride = _exactMatchStyle;
        else if (isRowMatch)
            PanelOverride = _rowMatchStyle;
        else
            PanelOverride = _normalStyle;
    }

    private void ApplySoldOutState(bool soldOut)
    {
        SoldOverlay.Visible = soldOut;
        ItemSprite.Visible = true;
        ItemSprite.Modulate = soldOut ? Color.White.WithAlpha(0.3f) : Color.White;
        AmountBadge.Visible = !soldOut;
    }

    public void PlayVendAnimation()
    {
        _animating = true;
        _animElapsed = 0f;
        _pendingSoldOut = SoldOverlay.Visible;

        ItemSprite.Visible = true;
        ItemSprite.Modulate = Color.White;
        LayoutContainer.SetPosition(ItemSprite, _restingPos);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_animating)
            return;

        _animElapsed += args.DeltaSeconds;
        var t = Math.Clamp(_animElapsed / AnimDuration, 0f, 1f);

        var pos = _restingPos + new Vector2(0f, DropDistance * t);
        LayoutContainer.SetPosition(ItemSprite, pos);
        ItemSprite.Modulate = Color.White.WithAlpha(1f - t);

        if (t >= 1f)
        {
            _animating = false;
            LayoutContainer.SetPosition(ItemSprite, _restingPos);
            ItemSprite.Modulate = Color.White;

            ApplySoldOutState(_pendingSoldOut);
        }
    }

    private string GetItemText(EntityPrototype prototype)
    {
        var itemName = prototype.Name;

        if (prototype.TryGetComponent<LabelComponent>(out var label, _componentFactory) &&
            !string.IsNullOrWhiteSpace(label.CurrentLabel))
        {
            var labelText = _loc.TryGetString(label.CurrentLabel, out var localized)
                ? localized
                : label.CurrentLabel;

            itemName = _loc.GetString("comp-label-format",
                ("baseName", itemName),
                ("label", labelText));
        }
        ItemName = itemName;
        return string.IsNullOrWhiteSpace(prototype.Description)
            ? itemName
            : $"{itemName}\n{prototype.Description}";
    }
}
